layout=json.loads((ROOT/'pres_layout.json').read_text(encoding='utf-8'))
assert {int(key.split(':')[1],16) for key in notes}==set(layout['entry_points'])
assert all(all(note.get(field) for field in ('name','purpose','details','inputs','outputs','corrupt')) for note in notes.values())
(ROOT/'pres_annotations.json').write_text(json.dumps(notes,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
