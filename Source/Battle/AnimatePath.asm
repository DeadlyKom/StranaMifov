
; -----------------------------------------
; провести мигающую анимацию от исходной клетки к целевой
; BuildNeighbours выбирает первую соседнюю клетку по направлению к цели, занятость здесь не учитывается
; SaveCursorBack сохраняет фон этой клетки, шесть групп по 1000 вызовов TickCursorAnim дают мигание
; задержка кадра также равна 1000, после группы RestoreCursor возвращает фон
; пока выбранная клетка не совпала с целью, анимация продолжается из неё следующим шагом
; In:
;   DE цель, BC исходная клетка
; Out:
;   DE цель, BC конечная клетка, фон восстановлен
; Corrupt:
;   HL, DE, BC, AF, Candidates, Timer, Frame, Background, TickCursorAnim.Delay и пиксели анимации
;   IX и IY сохранены
; -----------------------------------------
AnimatePath     CALL BuildNeighbours                                            ; построить восемь соседних клеток в порядке приближения к цели
                LD BC, (Battle.ClassifyCells.FirstCoords)
                PUSH BC
                PUSH DE
                LD HL, #0001
                LD (Battle.SaveCursorBack.Timer), HL
                LD HL, #03E8
                LD (Battle.TickCursorAnim.Delay), HL
                XOR A
                LD (Battle.SaveCursorBack.Frame), A
                CALL SaveCursorBack                                             ; сохранить фон под курсором клетки
                LD D, #06
.FlashStep      PUSH DE
                LD DE, #03E8
.DelayTicks     PUSH DE
                PUSH BC
                CALL TickCursorAnim                                             ; обновить кадр мигающего курсора выбранной клетки
                POP BC
                POP DE
                DEC DE
                LD A, E
                OR D
                JR NZ, .DelayTicks                                              ; переход, если не закончилась задержка текущей вспышки

                POP DE
                DEC D
                JR NZ, .FlashStep                                               ; переход, если ещё не выполнены все вспышки

                POP DE
                POP BC
                CALL RestoreCursor                                              ; восстановить фон под курсором клетки
                PUSH DE
                POP HL
                OR A
                SBC HL, BC
                JR NZ, AnimatePath                                              ; переход, если текущая клетка ещё не совпала с конечной

                RET

; -----------------------------------------
; Battle.AnimatePath.TurnMode
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | .. | .. | .. | .. | .. | .. | NW | RP |
;   +----+----+----+----+----+----+----+----+
;
;   флаги:
;   NW       [1] - флаг, повторный проход ИИ запрещает снова откладывать отряд за своим соседом
;     AI_NO_WAIT_BIT
;   RP       [0] - флаг, режим отложенного прохода ИИ требует отметки AI_DEFERRED_BIT
;     AI_REPEAT_BIT
; Штатные режимы задаются значениями 0 и 3, каждый бит проверяется своим потребителем
; -----------------------------------------
.TurnMode       DB #00                                                          ; режим обычного либо отложенного прохода ИИ
.MoveRules      DB #02, #13, #17, #01, #14, #01, #03                            ; правила приоритета целей обычного движения
                DB #02, #10, #00, #01, #07, #01, #04, #FF
.ShotRules      DB #04, #13, #17, #03, #07, #02, #14, #04                       ; правила приоритета целей дальней атаки
                DB #02, #10, #00, #FF
.FlightRules    DB #04, #13, #17, #03                                           ; правила приоритета целей полёта
                DB #07, #02, #14, #04, #02, #10, #00, #FF
