
; -----------------------------------------
; отметить участие типа отряда в бою и сбросить накопленные дни бездействия
; IndexFlagArray выбирает IdleDays[ID-1], соседний массив UpgradeCount находится на 25 байтов дальше
; дни бездействия обнуляются, счётчик развития увеличивается по модулю 256
; In:
;   HL боевой отряд
; Out:
;   IdleDays[ID-1]=0, UpgradeCount[ID-1] увеличен
; Corrupt:
;   AF, счётчик дней бездействия и счётчик развития выбранного типа
;   HL, DE, BC, IX и IY сохранены
; -----------------------------------------
MarkUnitFight   PUSH IX
                LD A, (HL)
                CALL Engine.IndexFlagArray                                      ; получить счётчик IdleDays данного типа, BC и остальные указатели сохранены
                LD (IX + #00), #00                                              ; дни бездействия данного типа сбрасываются после участия в бою
                INC (IX + State.UpgradeCount - State.IdleDays)                  ; участие в бою прибавляет единицу к счётчику развития типа
                POP IX
                RET
