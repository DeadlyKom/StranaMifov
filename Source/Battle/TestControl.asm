
; -----------------------------------------
; сравнить численность отряда с пределом управления
; 86EA получает целый предел BC по типу (IY+0), 6D62 передаёт его на стек ROM, 6DAE передаёт
; количество IY+2, 6DDA вычитает количество из предела и выдаёт знак, HL, DE, BC сохраняются
; In:
;   IY боевой отряд
; Out:
;   CF=1 количество выше предела, Z=1 равенство
; Corrupt:
;   AF, меняются флаги результата, рабочее пятибайтное поле 6E09..6E0D и состояние калькулятора,
;   HL, DE, BC, IX, IY сохранены
; -----------------------------------------
TestControl     PUSH HL
                PUSH DE
                PUSH BC
                LD A, (IY + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                CALL Engine.ControlLimit                                        ; рассчитать численный предел типа отряда из поля героя и таблицы
                PUSH IY
                POP HL
                INC HL
                INC HL
                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                CALL Engine.FloatSignZero                                       ; определить знак и нулевое значение результата калькулятора
                POP BC
                POP DE
                POP HL
                RET
