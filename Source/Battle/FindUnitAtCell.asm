
; -----------------------------------------
; найти отряд с заданными координатами в одной армии
; до пяти записей с шагом 18, пустой ID завершает поиск, OR A перед чтением координат очищает
; carry, слово +10/+11 сравнивается с BC через SBC
; In:
;   IX начало армии, BC клетка
; Out:
;   Z=1 найдено, IX найденная запись, Z=0 нет совпадения
; Corrupt:
;   HL, DE, AF, IX, BC и IY сохранены
; -----------------------------------------
FindUnitAtCell  LD D, #05
.UnitLoop       LD A, (IX + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                JR Z, .NotFound                                                 ; переход, если список отрядов завершён

                LD L, (IX + FBattleUnit.X)                                      ; +#0A, колонка 0..7
                LD H, (IX + FBattleUnit.Y)                                      ; +#0B, строка 0..4
                SBC HL, BC
                RET Z                                                           ; выход, если координаты отряда совпали с искомой клеткой

                PUSH DE
                LD DE, #0012
                ADD IX, DE
                POP DE
                DEC D
                JR NZ, .UnitLoop                                                ; переход, если остались непроверенные записи армии

.NotFound       XOR A
                INC A
                RET
