
; -----------------------------------------
; изменить количество цели по силе заклинания
; входной C сохраняется как последний токен калькулятора в F5BD, количество IX+2 помещается на
; стек, F5C4 выбирает слово для заклинания B и типа IX+0, младший байт коэффициента умножается на
; входной DE/20000, токен 03 вычитает воздействие, 0F прибавляет рассчитанное количество, результат сохраняется в
; IX+2
; In:
;   IX цель, B номер заклинания, C=03 вычитание или 0F сложение, DE сила
; Out:
;   количество цели обновлено
; Corrupt:
;   HL, DE, BC, AF, количество IX+2..6, операнд F5BD и состояние калькулятора, IX сохраняется
;   F5C4
; -----------------------------------------
ApplySpell      LD A, C
                LD (Battle.ApplySpell.SpellOp), A
                PUSH IX
                POP HL
                INC HL
                INC HL
                PUSH HL
                PUSH DE
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                LD C, (IX + FBattleUnit.UnitID)
                CALL SpellCoeffs                                                ; получить два байта коэффициентов заклинания для типа существа
                LD A, C
                CALL Engine.StackA                                              ; передать байт A на стек калькулятора ROM
                POP BC
                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                LD BC, #4E20
                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, F5BB
                DB #04                                                          ; multiply, умножение, F5BC
.SpellOp        DB #00                                                          ; изменяемый токен калькулятора, операция выбранного заклинания
                DB #38                                                          ; end-calc, возврат в Z80, F5BE
                POP HL
                CALL Engine.StoreFloat5                                         ; сохранить вершину калькулятора в пятибайтное поле по HL
                RET
