
; -----------------------------------------
; вычислить весовую оценку боевого отряда
; помещает количество IX+2 на стек ROM, 8036 получает описатель типа, слово +16..17 умножается на
; количество токеном 04, 6DC4 сохраняет результат по входному HL
; In:
;   HL адрес float5 результата, IX отряд
; Out:
;   float5=количество*слово описателя 16, IX, IY, BC сохранены
; Corrupt:
;   HL, DE, AF, пять байтов результата по входному HL и состояние калькулятора, BC, IX, IY
;   восстановлены
; -----------------------------------------
StackStrength   PUSH IX
                PUSH IY
                PUSH BC
                PUSH HL
                PUSH IX
                POP HL
                INC HL
                INC HL
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                LD A, (IX + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                CALL Engine.UnitDesc                                            ; получить описатель типа отряда
                LD C, (IX + FSoldier.UnitValue.Low)                             ; +#16, младший байт, вес одного воина в оценке армии и цене найма корабля
                LD B, (IX + FSoldier.UnitValue.High)                            ; +#17, старший байт, вес одного воина в оценке армии и цене найма корабля
                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, E8CB
                DB #38                                                          ; end-calc, возврат в Z80, E8CC
                POP HL
                CALL Engine.StoreFloat5                                         ; сохранить вершину калькулятора в пятибайтное поле по HL
                POP BC
                POP IY
                POP IX
                RET

.BestScore      DB #00, #00, #00, #00, #00                                      ; пятибайтная оценка лучшего кандидата
.TrialScore     DB #00, #00, #00                                                ; пятибайтная оценка проверяемого кандидата
                DB #00, #00
.BestUnit       DW #0000                                                        ; указатель лучшего кандидата
