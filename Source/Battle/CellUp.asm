
; -----------------------------------------
; уменьшить строку клетки без выхода за верхний край
; при B=0 оставляет строку без изменения, иначе уменьшает B
; In:
;   BC клетка, B строка 0..4
; Out:
;   BC новая клетка, AF изменён
; Corrupt:
;   BC и AF, меняются B и флаги, HL, DE, C, IX, IY сохранены
; -----------------------------------------
CellUp          LD A, B
                OR A
                RET Z                                                           ; выход, если клетка уже в верхней строке

                DEC B
                RET
