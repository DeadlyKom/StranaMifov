
; -----------------------------------------
; проверить неположительное пятибайтное количество отряда
; бит 7 поля (IX+3) сразу возвращает carry, иначе OR пяти байтов IX+2..6 проверяет ноль,
; отрицательное и нулевое количества считаются погибшим отрядом
; In:
;   IX боевой отряд
; Out:
;   CF=1 погиб, CF=0 положительное количество, IX сохранён
; Corrupt:
;   BC и AF, используется B и меняются A/F, HL, DE, IX, IY сохранены
; -----------------------------------------
TestDeadStack   BIT FLOAT_SIGN_BIT, (IX + FBattleUnit.Quantity + 1)             ; позиция знака в байте мантиссы пятибайтового числа ROM
                JR NZ, .DeadStack                                               ; переход, если численность отряда отрицательна

                PUSH IX
                LD B, #05
                XOR A
.TestCountBytes OR (IX + FBattleUnit.Quantity)
                INC IX
                DJNZ .TestCountBytes

                POP IX
                RET NZ                                                          ; выход, если численность отряда ненулевая

.DeadStack      SCF
                RET
