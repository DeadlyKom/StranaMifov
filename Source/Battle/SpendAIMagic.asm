
; -----------------------------------------
; списать цену и показать применяемое противником заклинание
; 8066 получает описатель по A, IX сохраняется в F07C текстового шаблона F06A, из FCB9 вычитается
; слово +15..16 описателя, название выводится через 7117, основные входные регистры
; восстанавливаются
; In:
;   A номер заклинания
; Out:
;   FCB9 уменьшено, HL, DE, BC, IX, IY сохранены
; Corrupt:
;   AF, сила FCB9, указатель F07C и экран заголовка, HL, DE, BC, IX, IY восстанавливаются
; -----------------------------------------
SpendAIMagic    PUSH HL
                PUSH DE
                PUSH BC
                PUSH IX
                PUSH IY
                PUSH AF
                LD A, #42
                CALL DrawHeader                                                 ; оформить рамку заголовка боя цветом A
                POP AF
                CALL Engine.SpellDesc                                           ; получить описатель одного из десяти заклинаний
                LD (Battle.SpendAIMagic.SpellDesc), IX
                LD HL, (Battle.FinishField.EnemyMana)
                LD E, (IX + FSpell.ManaCost.Low)
                LD D, (IX + FSpell.ManaCost.High)
                OR A
                SBC HL, DE
                LD (Battle.FinishField.EnemyMana), HL
                LD DE, Battle.SpendAIMagic.CastSpellText                        ; сообщение противник применяет заклинание, имя подставляется через SpellDesc
                LD B, #01
                CALL Engine.PrintMessage                                        ; разобрать строку сообщения с управляющими кодами
                POP IY
                POP IX
                POP BC
                POP DE
                POP HL
                RET

.MoveTarget     DW #0000                                                        ; указатель цели, возле которой ищется посадка телепортации
.MovingUnit     DW #0000                                                        ; указатель переносимого телепортацией отряда
.BestScore      DB #00, #00, #00, #00                                           ; пятибайтная оценка лучшего отряда для телепортации
                DB #00
.CastSpellText  EQU $+5                                                         ; сообщение противник применяет заклинание, имя подставляется через SpellDesc
.TrialScore     DB #00, #00, #00, #00, #00, #82, #E0                            ; пятибайтная оценка очередного отряда для телепортации
                DB #A0, #A6, #A5, #E1, #AA, #A0, #EF, #20
                DB #AC, #A0, #A3, #A8, #EF, #0D, #2A, #0E
.SpellDesc      DB #00, #00, #0D, #2A, #00                                      ; сохранённый указатель описателя оплачиваемого заклинания
; -----------------------------------------
; Battle.SpendAIMagic, байт исключения заклинания
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | .. | .. | .. | .. | .. | .. | .. | BL |
;   +----+----+----+----+----+----+----+----+
;
;   флаги:
;   BL       [0] - флаг, это заклинание исключено из выбора ИИ в текущей попытке
;     SPELL_BLOCK_BIT
; Схема применяется к каждому байту NoFreeze..NoSubjugate
; -----------------------------------------
.NoFreeze       DB #00                                                          ; байт исключения заморозки из выбора ИИ
.NoBlind        DB #00                                                          ; байт исключения ослепления из выбора ИИ
.NoBallBolt     DB #00                                                          ; байт исключения шаровой молнии из выбора ИИ
.NoTeleport     DB #00                                                          ; байт исключения телепортации из выбора ИИ
.NoBanish       DB #00                                                          ; байт исключения возвращения в могилу из выбора ИИ
.NoClone        DB #00                                                          ; байт исключения клонирования из выбора ИИ
.NoWall         DB #00                                                          ; байт исключения волшебной стены из выбора ИИ
.NoInvisible    DB #00                                                          ; байт исключения невидимости из выбора ИИ
.NoWard         DB #00                                                          ; байт исключения магического щита из выбора ИИ
.NoSubjugate    DB #00                                                          ; байт исключения подчинения из выбора ИИ
.SpellRules     DB #01                                                          ; правила выбора цели неатакующих заклинаний
                DB #07, #01, #03, #01, #04, #01, #00, #FF
.AttackRules    DB #02, #17, #07, #02, #13, #03, #02, #14                       ; правила выбора цели атакующих заклинаний
                DB #04, #01, #10, #FF
