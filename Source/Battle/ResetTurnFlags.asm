
; -----------------------------------------
; очистить временные флаги одной армии
; в каждой непустой записи оставляет только младшие три бита поля +9 через AND07, сбрасывает
; отметки 3..7, шаг 18, предел пять, DE, BC, AF, IY сохраняются
; In:
;   IY начало армии
; Out:
;   поле +9 каждой записи равно исходному AND07
; Corrupt:
;   поля +9 непустых записей армии, HL, DE, BC, AF, IX, IY сохранены
; -----------------------------------------
ResetTurnFlags  PUSH DE
                PUSH BC
                PUSH AF
                PUSH IY
                LD DE, #0012
                LD B, #05
.UnitLoop       LD A, (IY + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                JR Z, .RestoreRegs                                              ; переход, если список отрядов завершён

                LD A, (IY + FBattleUnit.Flags)                                  ; +#09, способности и временные отметки раунда, цели и контроля
                AND #07
                LD (IY + FBattleUnit.Flags), A                                  ; +#09, способности и временные отметки раунда, цели и контроля
                ADD IY, DE
                DJNZ .UnitLoop

.RestoreRegs    POP IY
                POP AF
                POP BC
                POP DE
                RET
