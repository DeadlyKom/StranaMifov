
; -----------------------------------------
; выполнить проход ИИ по ещё не завершившим ход отрядам
; перебирает до пяти записей FD47, пропускает завершившие ход по биту 4 поля +9, первый режим 0
; пропускает отложенные битом 3, режим 3 требует этот бит в E117, после действия сканирование
; начинается с начала массива
; In:
;   A режим 0 либо 3
; Out:
;   отряды помечаются битом 4 после завершения действий
; Corrupt:
;   HL, DE, BC, AF, IX, IY, операнд E111, флаги и действия отрядов противника, состояние атак и
;   перемещений
; -----------------------------------------
AIArmyPass      LD (Battle.AIArmyPass.PassMode), A

                ; повторный проход армии после действия отряда, пока остаются незавершённые ходы
.RestartArmy    LD IY, Battle.FinishField.EnemyArmy
                LD DE, #0012
                LD B, #05

                ; проверка текущего отряда, завершённые и отложенные записи пропускаются
.UnitLoop       LD A, (IY + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                RET Z                                                           ; выход, если список отрядов завершён

                BIT AI_DONE_BIT, (IY + FBattleUnit.Flags)                       ; +#09, флаг, обработка отряда ИИ в текущем раунде завершена
                JR NZ, .NextUnit                                                ; переход, если отряд уже обработан в этом раунде

                LD A, (Battle.AIArmyPass.PassMode)
                OR A
                JR NZ, .TakeUnitTurn                                            ; переход, если выполняется проход отложенных отрядов

                BIT AI_DEFERRED_BIT, (IY + FBattleUnit.Flags)                   ; +#09, флаг, действие отряда ИИ отложено до повторного прохода армии с режимом 3
                JR Z, .TakeUnitTurn                                             ; переход, если отряд не откладывал действие

.NextUnit       ADD IY, DE
                DJNZ .UnitLoop

                RET

                ; обработка одного отряда и повторный просмотр армии с начала
.PassMode       EQU $+1                                                         ; операнд A обычного либо отложенного прохода армии
.TakeUnitTurn   LD A, #00
                CALL AIUnitTurn                                                 ; выбрать движение или атаку одного отряда компьютера
                JR .RestartArmy
