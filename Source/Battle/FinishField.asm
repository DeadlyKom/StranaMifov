;   армии FCED/FD47 и сорок фоновых объектов подготовлены
; Out:
;   обработка объектов включена, прошёл кадр, управление возвращено из FAAF
; Corrupt:
;   AF, память экранных объектов, состояние фоновой обработки
; -----------------------------------------
