
; -----------------------------------------
; выдержать десять кадров между фазами атаки
; B=10 и цикл HALT/DJNZ, исходный BC сохраняется
; In:
;   прерывания разрешены
; Out:
;   прошло десять прерываний, BC сохранён
; Corrupt:
;   собственных изменений регистров или данных нет, BC восстановлен, исполнение ожидает десять
;   прерываний
; -----------------------------------------
WaitAttack      PUSH BC
                LD B, #0A
.FrameLoop      HALT
                DJNZ .FrameLoop

                POP BC
                RET
