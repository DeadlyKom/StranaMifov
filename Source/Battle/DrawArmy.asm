
; -----------------------------------------
; обновить экранные объекты одной армии
; до пяти плотных записей IY с шагом 18 передаёт отряд F8BB, A берётся из изменяемого операнда
; F51D, ID0 завершает список
; In:
;   IY начало армии, F51D флаг объекта
; Out:
;   отряды переданы объектной системе, IY продвинут
; Corrupt:
;   DE, BC, AF, IY, объекты отрядов и бит 2 поля 6566, HL и IX сохранены
; -----------------------------------------
DrawArmy        LD B, #05
.DrawUnitLoop   LD A, (IY + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                RET Z                                                           ; выход, если список отрядов завершён

.ObjectFlags    EQU $+1                                                         ; операнд A режима экранного объекта при выводе одной армии
                LD A, #23
                CALL MakeStaticUnit                                             ; сформировать неподвижный объект отряда и его отображаемое количество
                LD DE, #0012
                ADD IY, DE
                DJNZ .DrawUnitLoop

                RET
