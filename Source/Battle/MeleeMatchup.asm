
; -----------------------------------------
; получить слово коэффициента совместимости двух типов в рукопашном бою
; IX=C3E8+50*B+2*(C-1), из IX читается DE, таблица имеет 25 слов на строку, IX, BC, AF сохраняются
; In:
;   B ID атакующего, C ID цели, оба >0
; Out:
;   DE коэффициент рукопашной пары
; Corrupt:
;   DE, HL, BC, AF, IX, IY сохранены
; -----------------------------------------
MeleeMatchup    PUSH IX
                PUSH BC
                PUSH AF
                LD DE, #0032
                LD IX, Data.Battle.MeleeFactors - 25 * FWord                    ; база матрицы ближнего боя до первой строки, ID атакующего начинается с1
.MatchupRow     ADD IX, DE
                DJNZ .MatchupRow

                DEC C
                SLA C
                ADD IX, BC
                LD E, (IX + FWord.Low)
                LD D, (IX + FWord.High)
                POP AF
                POP BC
                POP IX
                RET

.AttackerEffect DB #00                                                          ; коэффициент временного эффекта первого атакующего
.DefenderEffect DB #00                                                          ; коэффициент временного эффекта первой цели
.MatchFactor    DW #0000                                                        ; слово коэффициента совместимости типов
.DamageSpread   DB #00, #00, #00                                                ; слово разброса урона из FSoldier
.QuantityPtr    DB #00                                                          ; указатель численности для расчёта текущего удара
                DB #00
.MoodNumerator  DB #00                                                          ; числитель поправки совместимости состава армии
.MoodDenom      DB #00                                                          ; знаменатель поправки совместимости состава армии
.DamageDivisor  DW #0000                                                        ; слово делителя урона из FSoldier
.Attacker       DW #0000                                                        ; указатель первого атакующего
.Defender       DB #00                                                          ; указатель первой цели
                DB #00
.AttackKind     DB #00                                                          ; 1 рукопашная атака с ответом, 2 дальняя без ответа
.CounterLoss    DB #00, #00, #00, #00, #00                                      ; пятибайтные потери первого атакующего от ответа
.MainLoss       DB #00                                                          ; пятибайтные потери первой цели от основного удара
                DB #00, #00, #00, #00
.MoodRatios     DB #01, #03, #01, #02                                           ; таблица пар числитель и знаменатель по совместимости армии -2..2
.RangedRules    EQU $+6                                                         ; семь троек ID атакующего и смещение строки матрицы дальнего действия
                DB #01, #01, #03, #02, #02, #01, #0B, #00
                DB #00, #03, #32, #00, #0C, #64, #00, #0F
                DB #96, #00, #16, #C8, #00, #17, #FA, #00
                DB #18, #2C, #01
