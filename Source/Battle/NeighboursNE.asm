
; -----------------------------------------
; задать координаты восьми кандидатов для выбранного направления поиска
; IY указывает на FBattleCells, все восемь записей первоначально содержат исходную клетку
; порядок кандидатов First..Eighth:
;   северо-восток, север, восток, юго-восток, северо-запад, юг, запад, юго-запад
; север уменьшает Y, восток увеличивает X, меняются только координаты, Status проверяется позже
; BuildNeighbours запускает процедуру вычисленным RET, возврат передаёт управление ClassifyCells
; In:
;   IY массив восьми FBattleCell с исходными координатами
; Out:
;   координаты кандидатов записаны в порядке приоритета, Status не изменён
; Corrupt:
;   F и координаты по IY, HL, DE, BC, A, IX и IY сохранены
; -----------------------------------------
NeighboursNE    INC (IY + FBattleCells.First.X)                                 ; кандидат 1, северо-восток, координата X
                DEC (IY + FBattleCells.First.Y)                                 ; кандидат 1, северо-восток, координата Y
                INC (IY + FBattleCells.Third.X)                                 ; кандидат 3, восток, координата X
                DEC (IY + FBattleCells.Second.Y)                                ; кандидат 2, север, координата Y
                INC (IY + FBattleCells.Fourth.X)                                ; кандидат 4, юго-восток, координата X
                INC (IY + FBattleCells.Fourth.Y)                                ; кандидат 4, юго-восток, координата Y
                DEC (IY + FBattleCells.Fifth.X)                                 ; кандидат 5, северо-запад, координата X
                DEC (IY + FBattleCells.Fifth.Y)                                 ; кандидат 5, северо-запад, координата Y
                INC (IY + FBattleCells.Sixth.Y)                                 ; кандидат 6, юг, координата Y
                DEC (IY + FBattleCells.Seventh.X)                               ; кандидат 7, запад, координата X
                DEC (IY + FBattleCells.Eighth.X)                                ; кандидат 8, юго-запад, координата X
                INC (IY + FBattleCells.Eighth.Y)                                ; кандидат 8, юго-запад, координата Y
                RET
