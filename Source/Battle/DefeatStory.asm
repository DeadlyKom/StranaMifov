
; -----------------------------------------
; обработать сюжетные последствия поражения
; FCB8=6 сразу вызывает 8799, иначе обходит FD47, 8036 получает описатель и бит 3 поля +15
; разрешает 8799 с C=0, процедура 8799 загружает оверлей 20 окончания игры
; In:
;   FCB8 тип боя, FD47 армия противника
; Out:
;   возможен переход к окончанию игры
; Corrupt:
;   HL, DE, BC, AF, IX, IY и состояние загруженного оверлея 20 на соответствующих ветках,
;   возможен переход к окончанию игры без обычного возврата
; -----------------------------------------
DefeatStory     LD A, (Battle.FinishField.FieldKind)
                CP #06
                JR Z, .ShowDefeat                                               ; переход, если бой относится к сюжетному типу 6

                LD IY, Battle.FinishField.EnemyArmy
                LD DE, #0012
                LD B, #05
.CheckStoryUnit LD A, (IY + FBattleUnit.UnitID)
                OR A
                RET Z                                                           ; выход, если список отрядов противника завершён

                CALL Engine.UnitDesc                                            ; получить описатель типа отряда
                BIT STORY_END_BIT, (IX + FSoldier.SpecialFlags)                 ; флаг, поражение от этого типа запускает сюжетное окончание
                JR Z, .NextStoryUnit                                            ; переход, если тип отряда не запускает сюжет поражения

.ShowDefeat     LD C, #00
                CALL Engine.RunOverlay20                                        ; выполнить оверлей 20 и продолжить подсчётом записей
.NextStoryUnit  ADD IY, DE
                DJNZ .CheckStoryUnit

                RET
