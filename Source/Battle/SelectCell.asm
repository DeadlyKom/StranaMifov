
; -----------------------------------------
; перемещать курсор по боевому полю до подтверждения либо отмены
; E091 выдаёт код ввода с анимацией, коды 13,1B,23,12,22,11,19,21 задают восемь направлений, код
; 27 подтверждает только клетку без препятствия по F67C, код 20 отменяет
; In:
;   BC начальная клетка
; Out:
;   Z=1 подтверждение, Z=0 отмена, BC выбранная клетка
; Corrupt:
;   HL, DE, BC, AF, состояние курсора и изменяемый байт проверки препятствия F694, IX и IY
;   сохраняются вызываемыми процедурами
; -----------------------------------------
SelectCell      CALL ReadCursorInput                                            ; прочитать очередной ввод с мигающим курсором клетки
                CP #13
                JR NZ, .TestUp                                                  ; переход, если не выбрано движение влево вверх

                CALL CellLeft                                                   ; уменьшить столбец клетки без выхода за левый край
                CALL CellUp                                                     ; уменьшить строку клетки без выхода за верхний край
                JR SelectCell

.TestUp         CP #1B
                JR NZ, .TestNorthEast                                           ; переход, если не выбрано движение вверх

                CALL CellUp                                                     ; уменьшить строку клетки без выхода за верхний край
                JR SelectCell

.TestNorthEast  CP #23
                JR NZ, .TestLeft                                                ; переход, если не выбрано движение вправо вверх

                CALL CellUp                                                     ; уменьшить строку клетки без выхода за верхний край
                CALL CellRight                                                  ; увеличить столбец клетки без выхода за правый край
                JR SelectCell

.TestLeft       CP #12
                JR NZ, .TestRight                                               ; переход, если не выбрано движение влево

                CALL CellLeft                                                   ; уменьшить столбец клетки без выхода за левый край
                JR SelectCell

.TestRight      CP #22
                JR NZ, .TestSouthWest                                           ; переход, если не выбрано движение вправо

                CALL CellRight                                                  ; увеличить столбец клетки без выхода за правый край
                JR SelectCell

.TestSouthWest  CP #11
                JR NZ, .TestDown                                                ; переход, если не выбрано движение влево вниз

                CALL CellDown                                                   ; увеличить строку клетки без выхода за нижний край
                CALL CellLeft                                                   ; уменьшить столбец клетки без выхода за левый край
                JR SelectCell

.TestDown       CP #19
                JR NZ, .TestSouthEast                                           ; переход, если не выбрано движение вниз

                CALL CellDown                                                   ; увеличить строку клетки без выхода за нижний край
                JR SelectCell

.TestSouthEast  CP #21
                JR NZ, .TestConfirm                                             ; переход, если не выбрано движение вправо вниз

                CALL CellDown                                                   ; увеличить строку клетки без выхода за нижний край
                CALL CellRight                                                  ; увеличить столбец клетки без выхода за правый край
                JR SelectCell

.TestConfirm    CP #27
                JR NZ, .TestCancel                                              ; переход, если не нажато подтверждение клетки

                CALL TestObstacle                                               ; проверить препятствие выбранной клетки
                JP NZ, SelectCell                                               ; переход, если подтверждаемая клетка закрыта препятствием

                RET

.TestCancel     CP #20
                JR NZ, SelectCell                                               ; переход, если не нажата отмена выбора

                OR A
                RET
