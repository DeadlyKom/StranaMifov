
; -----------------------------------------
; задать координаты восьми кандидатов для выбранного направления поиска
; IY указывает на FBattleCells, все восемь записей первоначально содержат исходную клетку
; порядок кандидатов First..Eighth:
;   север, северо-запад, северо-восток, запад, восток, юго-запад, юго-восток, юг
; север уменьшает Y, восток увеличивает X, меняются только координаты, Status проверяется позже
; BuildNeighbours запускает процедуру вычисленным RET, возврат передаёт управление ClassifyCells
; In:
;   IY массив восьми FBattleCell с исходными координатами
; Out:
;   координаты кандидатов записаны в порядке приоритета, Status не изменён
; Corrupt:
;   F и координаты по IY, HL, DE, BC, A, IX и IY сохранены
; -----------------------------------------
NeighboursN     DEC (IY + FBattleCells.First.Y)                                 ; кандидат 1, север, координата Y
                DEC (IY + FBattleCells.Second.X)                                ; кандидат 2, северо-запад, координата X
                DEC (IY + FBattleCells.Second.Y)                                ; кандидат 2, северо-запад, координата Y
                INC (IY + FBattleCells.Third.X)                                 ; кандидат 3, северо-восток, координата X
                DEC (IY + FBattleCells.Third.Y)                                 ; кандидат 3, северо-восток, координата Y
                DEC (IY + FBattleCells.Fourth.X)                                ; кандидат 4, запад, координата X
                INC (IY + FBattleCells.Fifth.X)                                 ; кандидат 5, восток, координата X
                DEC (IY + FBattleCells.Sixth.X)                                 ; кандидат 6, юго-запад, координата X
                INC (IY + FBattleCells.Sixth.Y)                                 ; кандидат 6, юго-запад, координата Y
                INC (IY + FBattleCells.Seventh.X)                               ; кандидат 7, юго-восток, координата X
                INC (IY + FBattleCells.Seventh.Y)                               ; кандидат 7, юго-восток, координата Y
                INC (IY + FBattleCells.Eighth.Y)                                ; кандидат 8, юг, координата Y
                RET
