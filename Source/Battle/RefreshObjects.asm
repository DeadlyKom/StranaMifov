
; -----------------------------------------
; сбросить флаги сорока объектов поля и заново отобразить армии
; через 6D34 временно выключает обработку объектов в прерывании, у сорока объектов от 6611 с шагом
; 20 в поле 0 сохраняет бит 7 и ставит бит 0, затем F4F4 создаёт объекты отрядов, IX и IY
; сохраняются, 6D34 сам не переключает банк
; In:
;   армии подготовлены
; Out:
;   объекты поля помечены, IX и IY сохранены
; Corrupt:
;   HL, DE, BC, AF, флаги сорока объектов от 6611, поля их ресурсов и численности, бит 2 поля
;   6566, IX и IY восстановлены
; -----------------------------------------
RefreshObjects  PUSH IY
                PUSH IX
                CALL Engine.StopView                                            ; выключить обработку объектов в прерывании
                LD HL, State.ViewObjects + 8 * FScreenObject20                  ; первые восемь экранных объектов зарезервированы, далее40объектов боевых клеток
                LD DE, #0014
                LD B, #28
.ObjectLoop     LD A, (HL)
                AND #80
                OR #01
                LD (HL), A
                ADD HL, DE
                DJNZ .ObjectLoop

                CALL DrawBothArmies                                             ; обновить экранные объекты обеих армий
                POP IX
                POP IY
                RET
