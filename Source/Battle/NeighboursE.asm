
; -----------------------------------------
; задать координаты восьми кандидатов для выбранного направления поиска
; IY указывает на FBattleCells, все восемь записей первоначально содержат исходную клетку
; порядок кандидатов First..Eighth:
;   восток, северо-восток, юго-восток, север, юг, северо-восток, юго-запад, запад
; север уменьшает Y, восток увеличивает X, меняются только координаты, Status проверяется позже
; исходный порядок содержит северо-восток дважды, Sixth повторяет Second, байты игры сохранены
; BuildNeighbours запускает процедуру вычисленным RET, возврат передаёт управление ClassifyCells
; In:
;   IY массив восьми FBattleCell с исходными координатами
; Out:
;   координаты кандидатов записаны в порядке приоритета, Status не изменён
; Corrupt:
;   F и координаты по IY, HL, DE, BC, A, IX и IY сохранены
; -----------------------------------------
NeighboursE     INC (IY + FBattleCells.First.X)                                 ; кандидат 1, восток, координата X
                INC (IY + FBattleCells.Second.X)                                ; кандидат 2, северо-восток, координата X
                DEC (IY + FBattleCells.Second.Y)                                ; кандидат 2, северо-восток, координата Y
                INC (IY + FBattleCells.Third.X)                                 ; кандидат 3, юго-восток, координата X
                INC (IY + FBattleCells.Third.Y)                                 ; кандидат 3, юго-восток, координата Y
                DEC (IY + FBattleCells.Fourth.Y)                                ; кандидат 4, север, координата Y
                INC (IY + FBattleCells.Fifth.Y)                                 ; кандидат 5, юг, координата Y
                INC (IY + FBattleCells.Sixth.X)                                 ; кандидат 6, северо-восток, координата X
                DEC (IY + FBattleCells.Sixth.Y)                                 ; кандидат 6, северо-восток, координата Y
                DEC (IY + FBattleCells.Seventh.X)                               ; кандидат 7, юго-запад, координата X
                INC (IY + FBattleCells.Seventh.Y)                               ; кандидат 7, юго-запад, координата Y
                DEC (IY + FBattleCells.Eighth.X)                                ; кандидат 8, запад, координата X
                RET
