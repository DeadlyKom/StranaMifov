
; -----------------------------------------
; уменьшить длительность временных эффектов одной армии
; младшая тетрада +13 равна нулю означает пропуск, значение 1 обнуляет весь байт эффекта,
; остальные значения уменьшаются с сохранением старшей тетрады, до пяти плотных записей
; In:
;   IY начало армии
; Out:
;   поле +13 обновлено, IY продвинут
; Corrupt:
;   DE, BC, AF, IY и поля +13 непустых отрядов, HL и IX не изменяются
; -----------------------------------------
TickEffects     LD B, #05
.EffectLoop     LD A, (IY + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                RET Z                                                           ; выход, если список отрядов завершён

                ; уменьшение длительности эффекта из младшей тетрады, номер эффекта в старшей тетраде сохраняется
                LD A, (IY + FBattleUnit.Effect)                                 ; +#0D, старшая тетрада вид эффекта, младшая оставшаяся длительность
                AND #0F
                JR Z, .NextUnit                                                 ; переход, если длительность временного эффекта уже нулевая

                DEC A
                JR NZ, .StoreDuration                                           ; переход, если после тика остались ходы действия эффекта

                ; истёк последний раунд, очистить одновременно номер эффекта и его длительность
                LD (IY + FBattleUnit.Effect), A                                 ; +#0D, старшая тетрада вид эффекта, младшая оставшаяся длительность
                JR .NextUnit

                ; сборка байта из прежнего номера эффекта и уменьшенной длительности
.StoreDuration  LD C, A
                LD A, (IY + FBattleUnit.Effect)                                 ; +#0D, старшая тетрада вид эффекта, младшая оставшаяся длительность
                AND #F0
                OR C
                LD (IY + FBattleUnit.Effect), A                                 ; +#0D, старшая тетрада вид эффекта, младшая оставшаяся длительность
.NextUnit       LD DE, #0012
                ADD IY, DE
                DJNZ .EffectLoop

                RET
