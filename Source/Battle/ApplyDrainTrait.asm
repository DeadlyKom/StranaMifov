
; -----------------------------------------
; увеличить количество атакующего за счёт нанесённого воздействия
; бит 7 регистра E из 7AEF разрешает ветку, бит 1 описателя цели +15 запрещает её, калькулятор
; сравнивает урон по HL с количеством цели, меньшее прибавляется к количеству атакующего IX+2,
; структура соответствует восстановлению по типу вампиризма
; In:
;   HL float5 урона, IX атакующий, IY цель
; Out:
;   количество IX+2 может увеличиться
; Corrupt:
;   HL, DE, BC, AF, сохранённый указатель F335, количество атакующего IX+2..6 и состояние
;   калькулятора, IX и IY сохраняют указатели участников
; -----------------------------------------
ApplyDrainTrait LD (Battle.ApplyDrainTrait.DrainAmount), HL
                LD A, (IX + FBattleUnit.UnitID)
                CALL Engine.UnitFlags                                           ; прочитать пару флагов описателя отряда
                BIT DRAIN_HIT_BIT, E                                            ; флаг, атакующий тип восстанавливает численность за счёт нанесённого воздействия
                RET Z                                                           ; выход, если атакующий тип не восстанавливает численность от урона

                LD A, (IY + FBattleUnit.UnitID)
                PUSH IX
                CALL Engine.UnitDesc                                            ; получить описатель типа отряда
                BIT NO_DRAIN_BIT, (IX + FSoldier.SpecialFlags)                  ; флаг, тип жертвы запрещает атакующему восстанавливать численность за нанесённый ей урон
                POP IX
                RET NZ                                                          ; выход, если тип жертвы запрещает восстановление атакующего

                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                PUSH IY
                POP HL
                INC HL
                INC HL
                PUSH HL
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                CALL Engine.FloatSignZero                                       ; определить знак и нулевое значение результата калькулятора
                POP HL
                JR NC, .AddDrainCount                                           ; переход, если нанесённое воздействие не меньше численности жертвы, восстановить всю её численность

                LD HL, (Battle.ApplyDrainTrait.DrainAmount)
.AddDrainCount  CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                PUSH IX
                POP HL
                INC HL
                INC HL
                PUSH HL
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #0F                                                          ; addition, сложение, F32E
                DB #38                                                          ; end-calc, возврат в Z80, F32F
                POP HL
                CALL Engine.StoreFloat5                                         ; сохранить вершину калькулятора в пятибайтное поле по HL
                RET

.DrainAmount    DB #00, #00                                                     ; указатель пятибайтного количества для восстановления от урона
