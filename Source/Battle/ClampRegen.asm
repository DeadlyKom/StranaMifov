
; -----------------------------------------
; ограничить количество специального отряда исходной численностью
; бит 0 описателя типа +15 разрешает проверку, количество IX+2 сравнивается с исходным целым
; IX+14..15, превышение заменяется исходным количеством
; In:
;   IX боевой отряд
; Out:
;   для специального типа количество не выше исходного
; Corrupt:
;   HL, DE, BC, AF, количество IX+2..6 при превышении исходного, состояние калькулятора, IX
;   восстановлен
; -----------------------------------------
ClampRegen      LD A, (IX + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                PUSH IX
                CALL Engine.UnitDesc                                            ; получить описатель типа отряда
                BIT DRAIN_CAP_BIT, (IX + FSoldier.SpecialFlags)                 ; флаг, восстановление численности типа ограничено исходным InitialCount
                POP IX
                RET Z                                                           ; выход, если тип допускает восстановление сверх исходного количества

                ; сравнение текущей численности с исходным целым количеством, избыток регенерации отбрасывается
                PUSH IX
                POP HL
                INC HL
                INC HL
                LD C, (IX + FBattleUnit.InitialCount.Low)                       ; +#0E, младший байт, исходное целое количество, ограничивает восстановление
                LD B, (IX + FBattleUnit.InitialCount.High)                      ; +#0F, старший байт, исходное целое количество, ограничивает восстановление
                PUSH HL
                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                CALL Engine.StackFloat5                                         ; передать пятибайтное число по HL на стек калькулятора
                CALL Engine.FloatSignZero                                       ; определить знак и нулевое значение результата калькулятора
                POP HL
                RET NC                                                          ; выход, если восстановленное количество не превышает исходное

                CALL Engine.StackBC                                             ; передать целое BC на стек калькулятора ROM
                CALL Engine.StoreFloat5                                         ; сохранить вершину калькулятора в пятибайтное поле по HL
                RET
