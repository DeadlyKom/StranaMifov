
; -----------------------------------------
; списать магическую силу героя с насыщением нулём
; устанавливает бит 2 в FCE7, вычитает BC из слова 6A04, при займе записывает ноль, carry
; сохраняет признак недостатка, вызывающий код отменяет эффект после исчерпания силы
; In:
;   BC цена заклинания
; Out:
;   CF=1 силы не хватило, CF=0 вычитание допустимо, HL новый остаток
; Corrupt:
;   HL, AF, слово 6A04 и бит 2 поля FCE7, DE, BC, IX, IY сохранены
; -----------------------------------------
SpendHeroMagic  LD A, (Battle.FinishField.Flags)
                SET SPELL_USED_BIT, A                                           ; флаг, попытка магии героя уже использована в текущем раунде
                LD (Battle.FinishField.Flags), A
                LD HL, (State.Mana)
                OR A
                SBC HL, BC
                LD (State.Mana), HL
                RET NC                                                          ; выход, если маны героя хватило на оплату заклинания

                LD HL, #0000
                LD (State.Mana), HL
                RET
