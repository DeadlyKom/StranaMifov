
; -----------------------------------------
; получить коэффициент воздействия временного эффекта
; старшая тетрада A задаёт номер эффекта, ноль или номер >=7 возвращает 10, иначе SpellCoeffs выбирает
; слово для эффекта и типа отряда, возвращается старший байт B
; In:
;   A байт эффекта, IX отряд
; Out:
;   A=10 либо старший байт табличного слова, BC изменён
; Corrupt:
;   BC, AF, HL, DE, IX, IY не изменяются
; -----------------------------------------

                ; выделение номера эффекта из старшей тетрады FBattleUnit.Effect, младшая тетрада длительности отбрасывается
EffectFactor    SRL A
                SRL A
                SRL A
                SRL A

                ; проверка отсутствия эффекта и наличия строки коэффициентов для его номера
                OR A
                JR Z, .FullFactor                                               ; переход, если временный эффект отсутствует

                CP #07
                JR C, .LookupFactor                                             ; переход, если номер эффекта входит в таблицу поправок

                ; возврат базового значения 10 для отсутствующего или неподдерживаемого эффекта
.FullFactor     LD A, #0A
                RET

                ; выбор табличного коэффициента по номеру эффекта и типу боевого отряда
.LookupFactor   LD B, A
                LD C, (IX + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                CALL SpellCoeffs                                                ; получить два байта коэффициентов заклинания для типа существа
                LD A, B
                RET
