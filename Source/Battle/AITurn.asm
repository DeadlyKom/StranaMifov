
; -----------------------------------------
; выполнить ход противника и сбросить отметки раунда
; EBA9 выбирает заклинание противника, затем очищается верхняя строка интерфейса, F556 сбрасывает
; временные флаги обеих армий, F578 восстанавливает движения противнику, E0E8 вызывается с
; режимами 0 и 3
; In:
;   армии FCED и FD47
; Out:
;   армии изменены, F6B8 может завершить бой
; Corrupt:
;   HL, DE, BC, AF, IX, IY, флаги обеих армий, движения и магическая сила противника, экран и
;   рабочие поля ИИ
; -----------------------------------------
AITurn          CALL AISpell                                                    ; выбрать и применить доступное заклинание противника
                LD BC, #0000
                LD DE, #0420
                XOR A
                CALL Engine.ClearRectangle                                      ; обнулить пиксели прямоугольника и заполнить его атрибуты
                LD IY, Battle.FinishField.HeroArmy
                CALL ResetTurnFlags                                             ; очистить временные флаги одной армии
                LD IY, Battle.FinishField.EnemyArmy
                CALL ResetTurnFlags                                             ; очистить временные флаги одной армии
                CALL RestoreMovement                                            ; восстановить очки движения армии на новый раунд
                LD A, #00
                CALL AIArmyPass                                                 ; выполнить проход ИИ по ещё не завершившим ход отрядам
                LD A, #03
                CALL AIArmyPass                                                 ; выполнить проход ИИ по ещё не завершившим ход отрядам
                RET
