
; -----------------------------------------
; задать координаты восьми кандидатов для выбранного направления поиска
; IY указывает на FBattleCells, все восемь записей первоначально содержат исходную клетку
; порядок кандидатов First..Eighth:
;   юго-восток, восток, юг, северо-восток, юго-запад, запад, север, северо-запад
; север уменьшает Y, восток увеличивает X, меняются только координаты, Status проверяется позже
; BuildNeighbours запускает процедуру вычисленным RET, возврат передаёт управление ClassifyCells
; In:
;   IY массив восьми FBattleCell с исходными координатами
; Out:
;   координаты кандидатов записаны в порядке приоритета, Status не изменён
; Corrupt:
;   F и координаты по IY, HL, DE, BC, A, IX и IY сохранены
; -----------------------------------------
NeighboursSE    INC (IY + FBattleCells.First.X)                                 ; кандидат 1, юго-восток, координата X
                INC (IY + FBattleCells.First.Y)                                 ; кандидат 1, юго-восток, координата Y
                INC (IY + FBattleCells.Second.X)                                ; кандидат 2, восток, координата X
                INC (IY + FBattleCells.Third.Y)                                 ; кандидат 3, юг, координата Y
                INC (IY + FBattleCells.Fourth.X)                                ; кандидат 4, северо-восток, координата X
                DEC (IY + FBattleCells.Fourth.Y)                                ; кандидат 4, северо-восток, координата Y
                DEC (IY + FBattleCells.Fifth.X)                                 ; кандидат 5, юго-запад, координата X
                INC (IY + FBattleCells.Fifth.Y)                                 ; кандидат 5, юго-запад, координата Y
                DEC (IY + FBattleCells.Sixth.X)                                 ; кандидат 6, запад, координата X
                DEC (IY + FBattleCells.Seventh.Y)                               ; кандидат 7, север, координата Y
                DEC (IY + FBattleCells.Eighth.X)                                ; кандидат 8, северо-запад, координата X
                DEC (IY + FBattleCells.Eighth.Y)                                ; кандидат 8, северо-запад, координата Y
                RET
