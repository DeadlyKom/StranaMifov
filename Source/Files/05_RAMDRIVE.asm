; определение схемы расширенной памяти и установка переключателя банков
; исходный файл каталога 05, смещение #0000
                module MemoryDriver
                org #7D34

; -----------------------------------------
; определение схемы расширенной памяти и установка общего переключателя банков
; Копирует 33-байтовый шаблон BankCode..#7ED6 в #5FA1. Очищает экран, печатает сообщение. Проверяет
; различимость банков через #7FFD и по очереди устанавливает 8-байтовые варианты старшего порта.
; Проверка CheckBanks записывает разные значения в одну позицию банков 0 и 8 и читает их
; обратно. После
; первого успешного варианта печатает название режима и возвращается. Если подходящая память не
; найдена, печатает отказ и навсегда меняет бордюр от R&7.
; In:
;   состояние портов расширения памяти
; Out:
;   подпрограмма переключения банков по #5FA1, #5FA0 содержит последний логический номер
; Corrupt:
;   HL, DE, BC, AF
; -----------------------------------------
Detect          DI
                LD DE, Memory.SelectBank                                        ; адрес установки и последующего вызова определённого драйвера банка
                LD HL, BankCode
                LD BC, #0021
                LDIR
                LD HL, Screen.Pixels                                            ; начало видимой пиксельной области Spectrum
                LD DE, Screen.Pixels + 1                                        ; следующий байт видимой пиксельной области для размножения заполнителя
                LD BC, #1800
                LD (HL), L
                LDIR
                LD BC, #02FF
                LD (HL), #07
                LDIR
                LD A, #19
                OUT (#FE), A
                LD DE, MemoryDriver.CheckBanks.TestText                         ; сообщение MEMORY TEST
                CALL Print                                                      ; печать строки с управляющими кодами цвета и позиции
                LD BC, #7FFD
                LD HL, Memory.PageWindow + 6                                    ; пробная ячейка определения модели расширения памяти
                LD D, #10
                LD A, D
                OUT (C), A
                LD (HL), A
                LD A, L
                OUT (C), A
                LD (HL), A
                LD A, D
                OUT (C), A
                LD A, (HL)
                CP D
                JR NZ, .NoMemory                                                ; переход, если проверяемые банки через #7FFD не сохраняют разные значения

                LD HL, PortDFFD
                LD BC, #0008
                CALL CheckBanks                                                 ; проверка независимости нижней и верхней группы банков
                LD DE, MemoryDriver.CheckBanks.ProfiText                        ; надпись PROFI
                JR Z, .PrintMemory                                              ; переход, если вариант порта PROFI обеспечил независимость банков

                LD BC, #0008
                CALL CheckBanks                                                 ; проверка независимости нижней и верхней группы банков
                LD DE, MemoryDriver.CheckBanks.AtmText                          ; надпись ATM TURBO
                JR Z, .PrintMemory                                              ; переход, если вариант ATM-TURBO обеспечил независимость банков

                LD BC, #0008
                CALL CheckBanks                                                 ; проверка независимости нижней и верхней группы банков
                LD DE, MemoryDriver.CheckBanks.ScorpionText                     ; надпись SCORPION
                JR Z, .PrintMemory                                              ; переход, если вариант SCORPION обеспечил независимость банков

                LD BC, #000F
                CALL CheckBanks                                                 ; проверка независимости нижней и верхней группы банков
                LD DE, MemoryDriver.CheckBanks.PentagonText                     ; надпись PENTAGON512
                JR Z, .PrintMemory                                              ; переход, если вариант PENTAGON512 обеспечил независимость банков

.NoMemory       LD DE, MemoryDriver.CheckBanks.FailureText                      ; ошибка отсутствия 256 К памяти
                CALL Print                                                      ; печать строки с управляющими кодами цвета и позиции
.BorderLoop     LD A, R
                AND #07
                OUT (#FE), A
                JR .BorderLoop

.PrintMemory    CALL Print                                                      ; печать строки с управляющими кодами цвета и позиции
                LD DE, MemoryDriver.CheckBanks.ActiveText                       ; суффикс 256K MODE ACTIVATED
                CALL Print                                                      ; печать строки с управляющими кодами цвета и позиции
                XOR A
                OUT (#FE), A
                RET

; -----------------------------------------
; проверка независимости нижней и верхней группы банков
; Копирует следующий вариант управляющих команд из HL в #5FAC. В ячейку #C000 банка 0 записывает
; 0, в ту же ячейку банка 8 записывает 8. Повторным чтением проверяет, что значения сохранились
; раздельно. Выбирает банк 0 перед возвратом, сохраняя результат сравнения в AF.
; In:
;   HL — следующий вариант, BC — число копируемых байтов
; Out:
;   HL после варианта, Z установлен при успехе
; Corrupt:
;   HL, DE, BC, AF
; -----------------------------------------
CheckBanks      LD DE, Memory.SelectBank + 11                                   ; адрес замены фрагмента установленного банкового драйвера
                LDIR
                EX DE, HL
                LD HL, Memory.PageWindow                                        ; начало отображаемого окна памяти, пробная ячейка проверки банка
                LD C, #08
                LD (HL), L
                LD A, C
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                LD (HL), A
                LD A, L
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                LD A, (HL)
                AND A
                JR NZ, .SelectBank                                              ; переход, если запись в банк 8 изменила проверяемый байт банка 0

                LD A, C
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                LD A, (HL)
                CP C
.SelectBank     PUSH AF
                LD A, L
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                POP AF
                EX DE, HL
                RET

.TestText       EQU $                                                           ; сообщение MEMORY TEST
                DB #16, #08, #09, #4D, #45, #4D, #4F, #52
                DB #59, #20, #54, #45, #53, #54, #20, #2E
.ProfiText      EQU $+4                                                         ; надпись PROFI
                DB #2E, #2E, #2E, #00, #16, #03, #0D, #10
                DB #20, #06, #50, #52, #4F, #46, #49, #00
.AtmText        EQU $                                                           ; надпись ATM TURBO
                DB #16, #01, #0D, #10, #20, #06, #41, #54
                DB #4D, #2D, #54, #55, #52, #42, #4F, #00
.ScorpionText   EQU $                                                           ; надпись SCORPION
                DB #16, #01, #0D, #10, #20, #06, #53, #43
.PentagonText   EQU $+7                                                         ; надпись PENTAGON512
                DB #4F, #52, #50, #49, #4F, #4E, #00, #16
                DB #00, #0D, #10, #20, #06, #50, #45, #4E
                DB #54, #41, #47, #4F, #4E, #35, #31, #32
.ActiveText     EQU $+1                                                         ; суффикс 256K MODE ACTIVATED
                DB #00, #2F, #32, #35, #36, #4B, #20, #4D
                DB #4F, #44, #45, #20, #41, #43, #54, #49
.FailureText    EQU $+7                                                         ; ошибка отсутствия 256 К памяти
                DB #56, #41, #54, #45, #44, #2E, #00, #16
                DB #0B, #0D, #10, #96, #02, #53, #4F, #52
                DB #52, #59, #20, #21, #21, #21, #16, #03
                DB #0F, #32, #35, #36, #4B, #20, #4D, #45
                DB #4D, #4F, #52, #59, #20, #4E, #4F, #54
                DB #20, #44, #45, #54, #45, #43, #54, #45
                DB #44, #20, #21, #21, #16, #07, #11, #47
                DB #41, #4D, #45, #20, #43, #41, #4E, #20
                DB #4E, #4F, #54, #20, #57, #4F, #52, #4B
                DB #2E, #00

; -----------------------------------------
; шаблон старшего порта #DFFD
; B=#DF, затем A с битом 3 сдвигается вправо трижды, получается бит 0 дополнительной группы
; памяти. Эти байты являются исполняемым шаблоном для копирования в #5FAC, а не обычной вызываемой
; процедурой.
; In:
;   AF — старшая часть логического номера
; Out:
;   BC и A для OUT (C), A
; Corrupt:
;   BC, AF
; -----------------------------------------
PortDFFD        LD B, #DF
                SRA A
                SRA A
                SRA A

; -----------------------------------------
; шаблон старшего порта #FDFD
; B=#FD, затем A с битом 3 сдвигается вправо трижды. Эти байты являются исполняемым шаблоном для
; копирования в #5FAC, а не обычной вызываемой процедурой.
; In:
;   AF — старшая часть логического номера
; Out:
;   BC и A для OUT (C), A
; Corrupt:
;   BC, AF
; -----------------------------------------
PortFDFD        LD B, #FD
                SRA A
                SRA A
                SRA A

; -----------------------------------------
; шаблон старшего порта #1FFD
; B=#1F, затем A с битом 3 сдвигается влево один раз, получается бит 4. Эти байты являются
; исполняемым шаблоном для копирования в #5FAC, а не обычной вызываемой процедурой.
; In:
;   AF — старшая часть логического номера
; Out:
;   BC и A для OUT (C), A
; Corrupt:
;   BC, AF
; -----------------------------------------
Port1FFD        LD B, #1F
                SLA A
                NOP
                NOP
                NOP
                NOP

; -----------------------------------------
; шаблон расширения верхних битов #7FFD
; A с битом 3 сдвигается влево трижды в бит 6, объединяется с младшими тремя битами исходного
; номера, B=#7F. Эти байты являются исполняемым шаблоном для копирования в #5FAC, а не обычной
; вызываемой процедурой.
; In:
;   AF — старшая часть логического номера
; Out:
;   BC и A для OUT (C), A
; Corrupt:
;   BC, AF
; -----------------------------------------
Port7FFD        SLA A
                SLA A
                SLA A
                LD B, A
                POP AF
                AND #07
                OR B
                LD B, #7F
                NOP
                NOP

; -----------------------------------------
; копируемый общий переключатель логических банков 0..15
; После переноса исполняется с #5FA1. Запрещает прерывания, сохраняет BC и AF. Записывает исходный
; номер в #5FA0. Патчируемый участок формирует старший порт из бита 3, затем #7FFD получает
; младшие 3 бита и принудительный бит 4 выбора ПЗУ 48. Возвращает BC и AF, прерывания остаются
; запрещёнными.
; In:
;   AF — логический номер банка в A
; Out:
;   регистры сохранены, выбран банк, DI остаётся действующим
; Corrupt:
;   HL, DE, BC, AF сохранены, регистр R меняется при исполнении, прерывания остаются
;   запрещёнными
; -----------------------------------------
BankCode        DI
                PUSH BC
                PUSH AF
                PUSH AF
                LD C, #FD
                LD (Memory.CurrentBank), A
                AND #08
                LD B, #00
                NOP
                NOP
                NOP
                NOP
                NOP
                NOP
                OUT (C), A
                POP AF
                LD B, #7F
                AND #07
                OR #10
                OUT (C), A
                POP AF
                POP BC
                RET

                DB #00
.PrintXY        DB #00                                                          ; координаты печати, X затем Y
.PrintY         DB #00                                                          ; строка печати

; -----------------------------------------
; заполнение атрибутов строки сообщения
; Берёт позицию из BankCode.PrintXY, рассчитывает адрес атрибутов через AttrAddress и записывает
; A в число соседних
; ячеек, заданное DrawGlyph.PrintAttr. Внешние HL, BC, AF сохранены стеком.
; In:
;   AF — атрибут в A, BankCode.PrintXY — позиция, DrawGlyph.PrintAttr — длина
; Out:
;   заполнена строка атрибутов
; Corrupt:
;   HL, DE, BC, AF сохранены
; -----------------------------------------
FillAttr        PUSH HL
                LD HL, (BankCode.PrintXY)
                PUSH BC
                PUSH AF
                LD B, L
                LD C, H
                CALL AttrAddress                                                ; расчёт атрибутного адреса по символьным координатам
                LD A, (DrawGlyph.PrintAttr)
                LD B, A
                POP AF
.FillGlyph      LD (HL), A
                INC HL
                DJNZ .FillGlyph

                POP BC
                POP HL
                RET

; -----------------------------------------
; печать утолщённого символа шрифта ПЗУ
; Вычитает 32 из кода, умножает индекс на 8 и прибавляет #3D00, то есть выбирает символ по
; #3C00+8*код. Вычисляет нелинейный экранный адрес по позиции BankCode.PrintXY. В каждой из 8 строк
; объединяет исходный байт со сдвигом влево на 1 и пишет в экран. Увеличивает горизонтальную
; позицию.
; In:
;   AF — код символа в A, BankCode.PrintXY — координаты
; Out:
;   символ выведен, горизонтальная позиция увеличена
; Corrupt:
;   HL, DE, AF
; -----------------------------------------
DrawGlyph       PUSH BC
                SUB #20
                LD L, A
                XOR A
                LD H, A
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                PUSH HL
                POP BC
                LD HL, #3D00
                ADD HL, BC
                PUSH HL
                LD A, (BankCode.PrintXY)
                LD C, A
                XOR A
                LD B, A
                XOR A
                LD L, A
                LD A, (BankCode.PrintY)
                AND #F8
                ADD A, #40
                LD H, A
                ADD HL, BC
                LD A, (BankCode.PrintY)
                ADD A, A
                ADD A, A
                ADD A, A
                ADD A, A
                ADD A, A
                LD C, A
                ADD HL, BC
                EX DE, HL
                POP HL
                LD B, #08
.ExpandGlyph    LD A, B
                LD A, (HL)
                LD C, A
                SLA A
                OR C
                INC HL
                LD (DE), A
                INC D
                DJNZ .ExpandGlyph

                LD HL, BankCode.PrintXY
                INC (HL)
                POP BC
                RET

.PrintAttr      DB #00                                                          ; операнд текущего цвета печати

; -----------------------------------------
; расчёт атрибутного адреса по символьным координатам
; Формирует HL=#5800+32*C+B с маскированием B до 5 младших битов и C до 5 младших битов.
; Возвращённый адрес используется для окраски знакомест.
; In:
;   BC — B колонка, C строка
; Out:
;   HL — адрес атрибута
; Corrupt:
;   HL, AF
; -----------------------------------------
AttrAddress     LD HL, Screen.Attributes                                        ; начало видимой области атрибутов Spectrum
                LD A, B
                AND #1F
                LD L, A
                LD A, C
                AND #18
                SRL A
                SRL A
                SRL A
                ADD A, H
                LD H, A
                LD A, C
                AND #07
                SRL A
                RRA
                RRA
                RRA
                ADD A, L
                LD L, A
                RET

; -----------------------------------------
; печать строки с управляющими кодами цвета и позиции
; Читает поток из DE до 0. Код #10 берёт длину и атрибут и вызывает FillAttr. Код #16 читает две
; координаты и сохраняет их по BankCode.PrintXY. Остальные коды выводятся через DrawGlyph. Цикл
; продвигает DE до
; завершающего 0.
; In:
;   DE — нуль-терминированная строка
; Out:
;   DE у завершающего 0, текст выведен
; Corrupt:
;   HL, DE, AF
; -----------------------------------------
Print           LD A, (DE)
                AND A
                RET Z                                                           ; выход, если прочитан нулевой терминатор сообщения

                CP #10
                JR NZ, .CheckControl                                            ; переход, если прочитан не управляющий код цвета #10

                INC DE
                LD A, (DE)
                LD (DrawGlyph.PrintAttr), A
                INC DE
                LD A, (DE)
                CALL FillAttr                                                   ; заполнение атрибутов строки сообщения
                INC DE
                JR Print

.CheckControl   CP #16
                JR NZ, .DrawChar                                                ; переход, если прочитан не управляющий код позиции #16

                INC DE
                PUSH HL
                LD A, (DE)
                LD L, A
                INC DE
                LD A, (DE)
                LD H, A
                LD (BankCode.PrintXY), HL
                POP HL
                INC DE
                JR Print

.DrawChar       PUSH DE
                PUSH BC
                LD A, (DE)
                CALL DrawGlyph                                                  ; печать утолщённого символа шрифта ПЗУ
                POP BC
                POP DE
                INC DE
                JR Print

                assert $ = #7F80
                endmodule
