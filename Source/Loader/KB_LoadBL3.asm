; защищённый загрузчик, KB_LoadBL3
; исходный файл каталога 03, смещение #008E
                module Protection
                module Load
                org #C000

; -----------------------------------------
; построение имени проверяемого BASIC-файла
; вычисляет семь операндов имени CTPAHA  B из IYh=5C, арифметики и показаний R, изменяя байты
; C0DE, C0E2, C0E6, C0EA, C0EE, C0F2, C0FE в процедуре C0DA, два исходных пробела C0F6, C0FA
; сохраняются, затем вызывает C0DA для записи девятибайтового имени в 5CDD
; In:
;   IY=5C3A, расшифрованный блок C000..C100 доступен, байты операндов C0DE..C0FE и переменные
;   5CDD..5CE5 доступны
; Out:
;   вычислены семь операндов имени, два исходных пробела C0F6, C0FA сохранены, в 5CDD..5CE5
;   записано CTPAHA  B, HL=5CE5, BC=0008, A=42, затем C03E, DE, SP, IX, IY сохранены
; Corrupt:
;   HL, BC, AF, R, семь операндов имени C0DE, C0E2, C0E6, C0EA, C0EE, C0F2, C0FE и 9 байтов
;   5CDD..5CE5
; -----------------------------------------
MakeCheckName   LD A, #27
                LD R, A
                LD HL, WriteName.NameChar0
                LD BC, #0008
                SRL B
                RR C
                LD A, IYH
                ADD A, #88
                CPL
                INC A
                OR #40
                SUB #D6
                SRL A
                LD (HL), A
                ADD HL, BC
                ADD A, #11
                LD (HL), A
                ADD HL, BC
                XOR #03
                SBC A, #07
                LD (HL), A
                ADD HL, BC
                LD A, R
                LD (HL), A
                ADD HL, BC
                XOR #09
                LD (HL), A
                ADD HL, BC
                LD A, R
                XOR #09
                LD (HL), A
                ADD HL, BC
                SLA C
                RL B
                ADD HL, BC
                INC A
                LD (HL), A
                CALL WriteName                                                  ; запись имени файла из самомодифицируемых операндов

; -----------------------------------------
; проверка положения BASIC-файла в каталоге
; сохраняет R, вызывает TR-DOS C=0A для поиска CTPAHA.B, восстанавливает R, значение C XOR2
; записывает в операнд по C07B, нормальная позиция файла в каталоге 2 даёт ноль
; In:
;   в 5CDD..5CE5 имя CTPAHA  B, доступен TR-DOS и его каталог, под SP доступны байты для
;   сохранённого AF и CALL
; Out:
;   выполнен поиск C=0A, операнд C07B получает returnedC XOR2, индекс 2 даёт 0, R
;   восстанавливается из сохранённого AF и далее учитывает три команды, прерывания после DOS
;   запрещены, затем C050
; Corrupt:
;   BC, AF, R, операнд C07B и рабочие переменные TR-DOS, остальные регистры обёртка поиска
;   собственными PUSH не защищает
; -----------------------------------------
FindBasic       LD A, R
                PUSH AF
                LD C, #0A
                CALL TrDos.Service                                              ; вызов сервиса TR-DOS, номер операции находится в C
                DI
                POP AF
                LD R, A
                LD A, C
                XOR #02
                LD (MakeLoaderName.CatalogDelta), A

; -----------------------------------------
; построение имени BL3 и настройка ветви защиты
; меняет операнды процедуры C0DA для формирования BL3     C, использует IYl=3A и R, загружает
; HL=003E при правильной позиции CTPAHA и сохраняет это слово в C0AB, превращая будущий код в LD
; A,0
; In:
;   IYl=3A, R восстановлен предыдущим блоком, C07B уже равен returnedC XOR2, доступна процедура
;   C0DA с операндами имени
; Out:
;   в 5CDD..5CE5 записано BL3     C, в C0AB..C0AC записана инструкция LD A, returnedC XOR2, при
;   индексе CTPAHA=2 это LD A,0, C подготовлен как 0E, затем C07F, DE, SP, IX, IY сохранены
; Corrupt:
;   HL, BC, AF, R, семь операндов имени C0DE, C0E2, C0E6, C0EA, C0EE, C0F2, C0FE,9 байтов
;   5CDD..5CE5 и два байта C0AB..C0AC, исходные пробелы C0F6, C0FA сохранены
; -----------------------------------------
MakeLoaderName  LD HL, WriteName.NameChar0
                LD BC, #0004
                DEC (HL)
                ADD HL, BC
                LD A, IYL
                XOR #76
                LD (HL), A
                ADD HL, BC
                LD A, R
                SUB (HL)
                ADD A, #04
                LD (HL), A
                ADD HL, BC
                SBC A, #13
                LD (HL), A
                ADC HL, BC
                LD (HL), A
                ADD HL, BC
                LD (HL), A
                ADD HL, BC
                SLA C
                RL B
                ADD HL, BC
                INC (HL)
                CALL WriteName                                                  ; запись имени файла из самомодифицируемых операндов
                LD C, #0E
                LD HL, #FF3E
.CatalogDelta   EQU $ - 1                                                       ; старший байт слова для подмены проверки, получает номер каталога XOR2
                LD (CheckPosition), HL

; -----------------------------------------
; загрузка BL3 через TR-DOS
; сохраняет R, обнуляет 5D10 и вызывает TR-DOS C=0E с A=0 для загрузки BL3 по адресу каталога
; 6149, затем восстанавливает R
; In:
;   C=0E, имя BL3     C в 5CDD, TR-DOS доступен, файл BL3 имеет адрес 6149 и длину 1BEB, стек
;   доступен
; Out:
;   A=0 перед DOS выбирает параметры файла, BL3 загружен в 6149..7D33, слово 5CE6 содержит 6149,
;   слово 5CE8 длину 1BEB, сохранённое значение R восстановлено через POP AF/LD R, A, прерывания
;   запрещены, затем C08D
; Corrupt:
;   AF, R, память загруженного файла и рабочие переменные TR-DOS, вызывающий блок не сохраняет
;   остальные регистры сервиса
; -----------------------------------------
Load            LD A, R
                PUSH AF
                XOR A
                LD (TrDos.Error), A
                CALL TrDos.Service                                              ; вызов сервиса TR-DOS, номер операции находится в C
                DI
                POP AF
                LD R, A

; -----------------------------------------
; пятнадцать проходов расшифровки BL3
; пятнадцать проходов по 7147 байтам от адреса в 5CE6, на каждом байте читает R, XOR L и
; записывает результат в R, затем XOR B, C, D, E, H и байт(HL), записывает расшифрованный байт,
; увеличивает HL и C, уменьшает DE, внешний B от 0F до 01
; In:
;   в 5CE6 адрес 6149, блок 7147 байтов 6149..7D33 загружен, A и R соответствуют
;   восстановленному состоянию C07F, код дешифратора C08D..C0AA цел
; Out:
;   выполнено 15 проходов по 7147 байтам, BL3 преобразован внешним XOR-потоком, HL=7D34, DE=0,
;   B=0, A=0, C увеличен на 15*7147 по модулю 256 относительно входного A, затем C0AB, SP, IX,
;   IY сохранены
; Corrupt:
;   HL, DE, BC, AF, R и память 6149..7D33
; -----------------------------------------
Decode          LD C, A
                LD B, #0F

                ; каждый проход заново начинает расшифровку BL3 с адреса из дескриптора файла
.DecodePass     LD HL, (TrDos.LoadAddress)
                LD DE, #1BEB

                ; ключ объединяет R, адрес, номер прохода и остаток длины, значение R изменяется
                ; и между байтами
.DecodeByte     LD A, R
                XOR L
                LD R, A
                XOR B
                XOR C
                XOR D
                XOR E
                XOR H
                XOR (HL)
                LD (HL), A
                INC HL
                INC C
                DEC DE
                LD A, E
                OR D
                JR NZ, .DecodeByte                                              ; переход, если расшифрованы ещё не все байты BL3

                DJNZ .DecodePass

; -----------------------------------------
; ветвь проверки каталога и повреждения при ошибке
; после нормального C=2 от поиска выполнит LD A,0, OR A и переход C0CD, затем JP6149, при другом
; результате копирует десять байтов из C0D0 в 6C16 и портит двадцать псевдослучайных байтов
; страницы 64xx, поэтому поведение зависит от исходного порядка файлов
; In:
;   C050 заменил исходные C7, C7 в C0AB..C0AC инструкцией LD A, returnedC XOR2, BL3 уже
;   расшифрован
; Out:
;   при returnedC=2 выполняется JP6149 без повреждения, иначе десять байтов C0D0..C0D9
;   копируются в 6C16..6C1F и 20 псевдослучайных байтов страницы 6400..64FF меняются XOR с R,
;   затем также JP6149, SP, IX, IY сохранены
; Corrupt:
;   AF на обоих путях, при нарушении проверки HL, DE, BC, R, память 6C16..6C1F и 20 выбранных
;   байтов 6400..64FF
; -----------------------------------------
CheckPosition   RST #00

                DB #C7, #B7, #28, #1D, #11, #16, #6C, #21
                DB #D0, #C0, #01, #0A, #00, #ED, #B0, #26
                DB #64, #ED, #5F, #1F, #ED, #4F, #6F, #06
                DB #14, #ED, #5F, #AE, #77, #AD, #6F, #10
                DB #F8, #C3, #49, #61, #4A, #0A, #7F, #67
                DB #70, #68, #02, #0B, #1A, #1B

; -----------------------------------------
; запись имени файла из самомодифицируемых операндов
; записывает девять байтов имени и расширения из самомодифицируемых операндов LD A, n в
; 5CDD..5CE5, операнды находятся C0DE, C0E2, C0E6, C0EA, C0EE, C0F2, C0F6, C0FA, C0FE
; In:
;   девять операндов LD A, n по C0DE, C0E2, C0E6, C0EA, C0EE, C0F2, C0F6, C0FA, C0FE уже
;   содержат имя 8 байтов и тип 1 байт
; Out:
;   девять байтов записаны в 5CDD..5CE5, HL=5CE5, A=последний байт типа, DE, BC, F, SP, IX, IY
;   сохранены
; Corrupt:
;   HL и A, память 5CDD..5CE5, флаги F собственным кодом не изменяются
; -----------------------------------------
WriteName       LD HL, TrDos.Descriptor
                LD A, #20
.NameChar0      EQU $ - 1                                                       ; операнд первого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar1      EQU $ - 1                                                       ; операнд второго символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar2      EQU $ - 1                                                       ; операнд третьего символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar3      EQU $ - 1                                                       ; операнд четвёртого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar4      EQU $ - 1                                                       ; операнд пятого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar5      EQU $ - 1                                                       ; операнд шестого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar6      EQU $ - 1                                                       ; операнд седьмого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.NameChar7      EQU $ - 1                                                       ; операнд восьмого символа имени загружаемого файла
                LD (HL), A
                INC HL
                LD A, #20
.FileType       EQU $ - 1                                                       ; операнд типа загружаемого файла
                LD (HL), A
                RET

                assert $ = #C101
                endmodule
                endmodule
