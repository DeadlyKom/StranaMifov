; защищённый загрузчик, KB_Outer
; исходный файл каталога 03, смещение #0000
                module Protection
                module Outer
                org #6149

; -----------------------------------------
; наружные шесть проходов защиты
; отключает прерывания, задаёт R=70 и шесть раз обрабатывает 220 байт с 6165, каждый байт получает
; XOR с текущим R, H, L и номером оставшегося прохода B, R учитывает реальные M1-циклы инструкций
; In:
;   зашифрованные байты KB находятся в 6165..6240, код 6149..6164 исполняется из RAM,
;   регистровые аргументы не требуются
; Out:
;   после шести проходов расшифрованы 220 байтов 6165..6240, переход по потоку в 6165, HL=6241,
;   DE=0, B=0, C сохранён, A=0, R=63, SP, IX, IY и альтернативные регистры сохранены
; Corrupt:
;   HL, DE, BC, AF, R, память 6165..6240, маскируемые прерывания запрещены через DI
; -----------------------------------------
Decode          DI
                LD A, #70
                LD R, A
                LD B, #06

                ; наружная защита выполняет шесть полных проходов по одному и тому же блоку
.DecodePass     LD HL, Protection.Move.Relocate                                 ; дешифруемый второй слой KB.co с процедурой переноса
                LD DE, #00DC

                ; число выборок команд влияет на R и поэтому является частью исходного ключа
.DecodeByte     LD A, R
                XOR (HL)
                XOR H
                XOR L
                XOR B
                LD (HL), A
                INC HL
                DEC DE
                LD A, E
                OR D
                JR NZ, .DecodeByte                                              ; переход, если в текущем проходе остаются зашифрованные байты

                DJNZ .DecodePass

                assert $ = #6165
                endmodule
                endmodule
