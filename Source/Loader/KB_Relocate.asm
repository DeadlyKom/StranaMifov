; защищённый загрузчик, KB_Relocate
; исходный файл каталога 03, смещение #001C
                module Protection
                module Move
                org #6165

; -----------------------------------------
; перенос следующего слоя защиты
; переносит 299 байтов из 61B4 в BFDE, исходник последних 158 байтов не входит в диапазон
; наружного шифрования
; In:
;   первый слой расшифрован, исходный блок 299 байтов 61B4..62DE доступен, назначение BFDE..C108
;   доступно для записи
; Out:
;   299 байтов скопированы в BFDE..C108, HL=62DF, DE=C109, BC=0, исполнение продолжается 6170,
;   SP, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, флаги LDIR и память BFDE..C108, A сохраняется
; -----------------------------------------
Relocate        LD HL, Protection.Move.InnerSource                              ; исходный адрес закодированного внутреннего слоя в перенесённом KB.co
                LD DE, Protection.Xor.DecodeAdjacent + 1                        ; адрес временного переноса внутреннего слоя перед сдвигом на байт влево
                LD BC, #012B
                LDIR

; -----------------------------------------
; самостирание наружного слоя
; записывает ноль в 6149 и запускает LDIR с BC=0, после 50 переносов байт ED самой инструкции LDIR
; по 617B становится нулём, повторение прекращается, байт B0 по 617C исполняется как OR B, нули
; остаются в 6149..617B
; In:
;   код 6170..617C находится по исходным адресам, RAM6149..617B доступна для записи, прерывания
;   запрещены
; Out:
;   самостирание 6149..617B завершает повторение LDIR после 50 переносов, затем исполняется
;   оставшийся B0 как OR B, вход в 617D с HL=617B, DE=617C, BC=FFCE, A=FF, R=27 при штатном
;   пути, SP, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, AF, R и память 6149..617B
; -----------------------------------------
EraseOuter      XOR A
                LD HL, Protection.Outer.Decode                                  ; начало стираемой внешней защиты KB.co
                LD DE, Protection.Outer.Decode + 1                              ; следующий байт внешней защиты для размножения нуля LDIR
                LD BC, #0000
                LD (HL), A
                LDIR

; -----------------------------------------
; подготовка стекового цикла расшифровки
; нормализует R после самостирания, помещает в стек адрес 6192 и промежуточный адрес BFDD, задаёт
; HL=BFDE, DE=BFDD, BC=012B
; In:
;   штатный выход 6170 даёт A=B=FF, код 617D..6191 цел, под SP доступны четыре байта стека
; Out:
;   HL=BFDE, DE=BFDD, BC=012B, SP восстановлен к входному значению, под SP остаются слова 6192
;   по SP-2 и BFDD по SP-4, переход в 6192 с R=32 при штатном пути, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, AF, R и четыре байта под входным SP
; -----------------------------------------
SetStack        LD C, A
                LD A, R
                XOR C
                XOR B
                LD R, A
                LD HL, DecodeShift
                PUSH HL
                LD DE, Protection.Xor.DecodeAdjacent                            ; окончательный адрес внутреннего слоя после сдвига
                PUSH DE
                POP HL
                INC HL
                POP BC
                LD BC, #012B

; -----------------------------------------
; побайтовая расшифровка со сдвигом на один адрес
; XOR байта(HL) с R, LDI одновременно переносит его на один байт вниз и уменьшает BC, DEC SP
; дважды возвращает стек к сохранённому адресу 6192, RET PE повторяет цикл пока BC не ноль, затем
; второй DEC SP дважды и RET PO передают управление в BFDD, ключ первого байта 34 и шаг 9 по
; модулю 128
; In:
;   HL=BFDE, DE=BFDD, BC=012B, R=32, по SP-2 сохранён 6192 и по SP-4 BFDD,299 байтов источника и
;   назначения доступны
; Out:
;   299 байтов расшифрованы и сдвинуты вниз в BFDD..C107, ключ 34+9*j по модулю 128, HL=C109,
;   DE=C108, BC=0, A=0, RET PO передаёт управление BFDD, итоговый SP равен входному SP-2, IX, IY
;   сохранены
; Corrupt:
;   HL, DE, BC, AF, R, SP, память BFDD..C108, адреса стека используются как управляющие переходы
; -----------------------------------------
DecodeShift     LD A, R
                XOR (HL)
                LD (HL), A
                LDI
                DEC SP
                DEC SP
                RET PE                                                          ; выход, если BC ещё не ноль, стек возвращает управление к DecodeShift

                DEC SP
                DEC SP
                RET PO                                                          ; выход, если все байты перенесены, стек передаёт управление расшифрованному блоку

; -----------------------------------------
; недостигаемая в нормальном ходе ветвь защиты
; в нормальном ходе не достигается, обе развилки RET PE и RET PO покрывают состояния PV после LDI,
; поэтому нельзя объявлять этот фрагмент исполняемым без отдельной точки входа
; In:
;   в обычном ходе входа нет, RET PE и RET PO по 619A/619D покрывают оба состояния PV после LDI,
;   при отдельном внешнем входе необходимы доступный байт BFDC и целый код 619E..61B3
; Out:
;   при отдельном входе R=7 и 299 итераций XOR одного байта BFDC с показаниями R, затем JP BFDC,
;   HL=BFDC, BC=0, A=0, DE, SP, IX, IY сохранены
; Corrupt:
;   HL, BC, AF, R и один байт BFDC, тело не увеличивает HL и не расшифровывает последовательный
;   блок
; -----------------------------------------
DeadBranch      LD A, #07
                LD R, A
                LD BC, #012B
                LD HL, Protection.Xor.DecodeAdjacent - 1                        ; адрес перед внутренним слоем в неиспользуемой ветви защиты, не именуется самостоятельной функцией

                ; недостижимая в разобранном штатном пути ветвь защиты оставлена в исходном
                ; размещении
.UnusedXorLoop  LD A, R
                XOR (HL)
                LD (HL), A
                DEC BC
                LD A, B
                OR C
                JR NZ, .UnusedXorLoop                                           ; переход, если выполнены ещё не все 299 итераций недостижимой ветви

                JP Protection.Xor.DecodeAdjacent - 1                            ; адрес перед внутренним слоем в неиспользуемой ветви защиты, не именуется самостоятельной функцией

                assert $ = #61B4
                endmodule
                endmodule
