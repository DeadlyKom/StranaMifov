; защищённый загрузчик, KB_Difference
; исходный файл каталога 03, смещение #006B
                module Protection
                module Xor
                org #BFDD

; -----------------------------------------
; соседнее XOR-преобразование через стек
; сохраняет текущий SP в операнде LD SP по BFFE, задаёт SP=C000 и 257 раз читает пару соседних
; байтов POP DE, обнуляет A после фиктивного LD A, R, записывает E XOR D обратно через PUSH DE,
; увеличивает SP на 1, тем самым преобразует C000..C100 как p[i]=s[i] XOR s[i+1], затем
; восстанавливает SP и входит в C000
; In:
;   в памяти BFDD..C107 находится второй слой, C000..C101 доступны, SP указывает исходный стек
;   после RET PO
; Out:
;   C000..C100 преобразованы какold[i] XOR old[i+1], выполнено 257 итераций, исходный SP
;   восстановлен через изменённый операнд BFFE, затем вход по потоку в C000, HL сохраняет
;   входной SP, BC=0, A=0, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, AF, R, временное SP=C000..C101, операнд BFFE..BFFF и память C000..C100,
;   прерывания запрещены
; -----------------------------------------
DecodeAdjacent  DI
                LD HL, #0000
                ADD HL, SP
                LD (DecodeAdjacent.SavedSP), HL
                LD A, #90
                LD R, A
                LD SP, Protection.Load.MakeCheckName                            ; временная вершина стека над внутренним декодером до перехода к последнему слою защиты
                LD BC, #0101

                ; каждая пара соседних байтов превращается в XOR, стек сдвигается на один байт
                ; для следующей пары
.XorPairs       POP DE
                LD A, R                                                         ; фиктивное чтение R, значение отбрасывается последующим XOR A
                XOR A
                XOR D
                XOR E
                LD E, A
                PUSH DE
                INC SP
                DEC BC
                LD A, B
                OR C
                JR NZ, .XorPairs                                                ; переход, если ещё остались пары байтов для вычитания и XOR

                LD SP, #4C00
.SavedSP        EQU $ - 2                                                       ; операнд восстановления стека после соседнего XOR

                assert $ = #C000
                endmodule
                endmodule

