
; -----------------------------------------
; вывод прямоугольника байтов в пиксельных координатах
; Для каждой строки преобразует координаты HL в адрес экрана, вызывает сдвинутую запись B байтов,
; затем увеличивает y. Число строк задаёт C.
; In:
;   H — x, L — y, B — ширина в байтах, C — высота в пикселях, DE — источник
; Out:
;   L увеличен на высоту, C=0, DE после данных
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   экран, PrintChar.LeftMask..PrintChar.BitPosition
; -----------------------------------------
DrawByteRect    PUSH HL
                PUSH BC
                PUSH HL
                POP BC
                CALL PixelAddress                                               ; адрес пиксельного байта и положение бита на экране ZX Spectrum
                POP BC
                PUSH BC
                CALL DrawShiftedRow                                             ; вывод строки байтов со сдвигом по горизонтали
                POP BC
                POP HL
                INC L
                DEC C
                JR NZ, DrawByteRect                                             ; переход, если остаются столбцы байтового прямоугольника

                RET

