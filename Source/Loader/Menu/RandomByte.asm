
; -----------------------------------------
; получение псевдослучайного байта для бипера
; Увеличивает указатель MenuState.BeepRandom, сбрасывает bit 5 H и возвращает XOR байта
; памяти с R. Использование
; R связывает результат с исполнением команд.
; In:
;   MenuState.BeepRandom — указатель
; Out:
;   A — псевдослучайное значение, HL сохранён
; Corrupt:
;   AF
; -----------------------------------------
RandomByte      PUSH HL
                LD HL, (MenuState.BeepRandom)
                INC HL
                RES BEEP_WRAP_BIT, H                                            ; разряд старшего байта указателя генератора бипера, сброс удерживает адрес последовательности в диапазоне первых 8 Кбайт при исходном нулевом указателе
                LD (MenuState.BeepRandom), HL
                LD A, R
                XOR (HL)
                POP HL
                RET
