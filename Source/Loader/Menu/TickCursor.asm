
; -----------------------------------------
; обновление курсора и подсветки в прерывании
; Восстанавливает фон старой позиции, переносит следующую позицию MenuState.NextXY в
; MenuState.CursorXY, обновляет
; подсветку, сохраняет фон новой позиции и рисует курсор.
; In:
;   MenuState.CursorXY — старая, MenuState.NextXY — новая позиция
; Out:
;   новый курсор на экране
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   MenuState.CursorXY, #6C31, экран
; -----------------------------------------
TickCursor      LD C, #80
                CALL CursorBackdrop                                             ; сохранение или восстановление фона курсора
                LD BC, (MenuState.NextXY)
                LD (MenuState.CursorXY), BC
                SRL B
                SRL B
                SRL B
                SRL C
                SRL C
                SRL C
                CALL HighlightAreas                                             ; подсветка области меню под курсором
                LD C, #00
                CALL CursorBackdrop                                             ; сохранение или восстановление фона курсора
                JP DrawCursor

CursorPixels    INCBIN "Assets/Gfx/raw/CTPAHA_cursor.ink"                       ; графический ресурс, исходное смещение #0CA0
CursorMask      INCBIN "Assets/Gfx/raw/CTPAHA_cursor.mask"                      ; графический ресурс, исходное смещение #0CB0
MenuState       DB #00, #00, #00, #00, #00, #00, #00, #00                       ; фон курсора, далее рабочие переменные и таблицы скрытого меню
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
.BeepRandom     DW #0000                                                        ; слово генератора задержек бипера

; -----------------------------------------
; Loader.Menu.MenuState.SoundFlags
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | .. | .. | .. | .. | .. | .. | .. | SN |
;   +----+----+----+----+----+----+----+----+
;
;   флаги и поля:
;   SN       [0] - флаг, 1 разрешает биперные эффекты, 0 Beep сразу возвращается
; .. [7, 6, 5, 4, 3, 2, 1] - назначение не установлено
; Проверено по потребителям:
;   Loader.Menu.Beep
; -----------------------------------------
.SoundFlags     DB #81                                                          ; бит0 разрешает биперные эффекты
.PortFE         DB #05                                                          ; сохранённое значение порта бордюра и бипера
.InputPorts     EQU $                                                           ; девять слов портов восьми полурядов клавиатуры и Kempston
                DB #FE, #F7, #FE, #FB, #FE, #FD, #FE, #FE
                DB #FE, #EF, #FE, #DF, #FE, #BF, #FE, #7F
.KeyMaps        EQU $+2                                                         ; первые три набора соответствия кнопок управления
                DB #1F, #00, #29, #28, #11, #1A, #38, #29
                DB #28, #11, #1A, #3B, #41, #40, #43, #42
.ExtraKeys      EQU $+1                                                         ; четвёртый набор соответствия кнопок управления
                DB #44, #24, #23, #21, #22, #20, #00
.CursorXY       DB #00                                                          ; текущие пиксельные координаты курсора, X затем Y
.CursorY        DB #00                                                          ; вертикальная пиксельная координата курсора
.NextXY         DW #0000                                                        ; следующие пиксельные координаты курсора
; -----------------------------------------
; Loader.Menu.MenuState.KeyMask, нормализованный ввод
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | .. | .. | .. | LT | RT | UP | DN | OK |
;   +----+----+----+----+----+----+----+----+
;
;   флаги:
;   LT       [4] - флаг, движение влево
;     MENU_LEFT_BIT
;   RT       [3] - флаг, движение вправо
;     MENU_RIGHT_BIT
;   UP       [2] - флаг, движение вверх
;     MENU_UP_BIT
;   DN       [1] - флаг, движение вниз
;     MENU_DOWN_BIT
;   OK       [0] - флаг, действие или завершение выбора
;     MENU_FIRE_BIT
; -----------------------------------------
.KeyMask        DB #00                                                          ; маска кнопок предыдущего опроса
.HoldTicks      DB #00                                                          ; число опросов удержания одной комбинации кнопок
.Areas          DW #0000                                                        ; адрес таблицы трёхбайтовых областей выбора
.Choice         DB #00                                                          ; индекс подтверждённой области выбора
                DB #00, #80, #C0, #E0, #F0, #F8, #FC, #FE
                DB #FF
