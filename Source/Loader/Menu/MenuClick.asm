
; -----------------------------------------
; короткий звуковой отклик меню
; Задаёт D=10, E=5 и переходит к общему биперу Beep.
; In:
; нет регистровых аргументов, бит 0 MenuState.SoundFlags разрешает звук,
; MenuState.PortFE — начальный байт порта #FE,
;   MenuState.BeepRandom и R участвуют в псевдослучайной задержке
; Out:
;   при разрешённом звуке выведено 10 импульсов, D=0, E=5, B=0. При выключенном звуке
;   немедленный возврат, DE=#0A05. HL и C сохранены
; Corrupt:
;   DE, BC, AF, AF'. HL, C, HL', DE', BC', IX, IY сохранены, C внутри пары BC не изменяется
; Note:
;   порт #FE при разрешённом звуке
; -----------------------------------------
MenuClick       LD DE, #0A05
                JR Beep
