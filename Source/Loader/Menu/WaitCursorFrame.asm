
; -----------------------------------------
; ожидание одного прерывания с обновлением курсора
; HALT оставляет адрес возврата #6BEC. Обработчик MenuInterrupt узнаёт этот адрес и вызывает
; TickCursor,
; поэтому курсор обновляется только в данном ожидании.
; In:
;   IM 2 уже установлен, прерывания разрешены
; Out:
;   после прерывания RET
; Corrupt:
;   сохранённые обработчиком основные регистры не меняются
; Note:
;   AY, экран в обработчике
; -----------------------------------------
WaitCursorFrame HALT
.Resume         EQU $                                                           ; RET после HALT в WaitCursorFrame, сравнивается с адресом возврата прерывания перед TickCursor
                RET
