
; -----------------------------------------
; операция с файлом по имени и смещению в секторах
; Копирует 9 байтов имени/типа из HL в TrDos.Descriptor, находит дескриптор. При отсутствии
; файла уходит в
; ShowDiskError. При успехе берёт дисковую позицию TrDos.FileSector, прибавляет A секторов,
; восстанавливает адрес
; буфера из DE, выполняет операцию C. B=#FF заменяется числом секторов файла из TrDos.SectorCount.
; In:
;   HL — 9 байтов имени, DE — буфер, A — секторное смещение, B — число секторов или #FF, C —
;   функция TR-DOS (5 чтение, 6 запись)
; Out:
;   успешный возврат из DiskOperation
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   буфер и/или диск, системный дескриптор TrDos.Descriptor
; -----------------------------------------

                ; имя и тип копируются в системный дескриптор, секторное смещение отсчитывается
                ; от начала найденного файла
AccessFile      PUSH BC
                PUSH DE
                PUSH AF
                LD DE, TrDos.Descriptor
                LD BC, #0009
                LDIR
                CALL FindFile                                                   ; поиск 9-байтового имени в каталоге TR-DOS
                JR C, ShowDiskError.FileOffset                                  ; переход, если файл найден и можно вычислить адрес нужного сектора

                LD HL, Loader.Menu.SelectDrive.MissingText                      ; сообщение о ненайденном файле
