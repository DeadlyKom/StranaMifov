
; -----------------------------------------
; преобразование беззнакового байта в три десятичные цифры
; Последовательными вычитаниями 100 и 10 получает сотни и десятки, затем записывает единицы.
; Ведущие нули сохраняются.
; In:
;   A — число 0..255
; Out:
;   #66B0..#66B2 — три ASCII-цифры
; Corrupt:
;   HL, BC, AF
; Note:
;   #66B0..#66B2
; -----------------------------------------
ByteToDecimal   LD HL, Loader.Menu.SelectDrive.DecimalText                      ; трёхзначное десятичное число с нулевым терминатором
                LD BC, #0064
                CALL WriteDigit                                                 ; получение одной десятичной цифры повторным вычитанием
                LD BC, #000A
                CALL WriteDigit                                                 ; получение одной десятичной цифры повторным вычитанием
                ADD A, #30
                LD (HL), A
                RET
