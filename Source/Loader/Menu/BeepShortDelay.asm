
; -----------------------------------------
; вариант биперного эффекта с параметрами D=96, E=8
; Задаёт параметры и переходит к Beep. Прямой вызывающий код внутри исследованного меню не
; найден.
; In:
; нет регистровых аргументов, бит 0 MenuState.SoundFlags разрешает звук,
; MenuState.PortFE — начальный байт порта #FE,
;   MenuState.BeepRandom и R участвуют в псевдослучайной задержке
; Out:
;   при разрешённом звуке выведено 96 импульсов, D=0, E=8, B=0. При выключенном звуке
;   немедленный возврат, DE=#6008. HL и C сохранены
; Corrupt:
;   DE, BC, AF, AF'. HL, C, HL', DE', BC', IX, IY сохранены, C внутри пары BC не изменяется
; -----------------------------------------
BeepShortDelay  LD DE, #6008
                JR Beep
