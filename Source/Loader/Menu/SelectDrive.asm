
; -----------------------------------------
; установка текущего привода TR-DOS
; Записывает A в TrDos.Drive, задаёт C=#FF и адрес возврата #2A53 на стеке, затем переходит в TR-DOS
; #3D2F. Использование внутренних адресов зависит от версии ROM TR-DOS.
; In:
;   A — номер привода
; Out:
;   выбран привод
; Corrupt:
;   HL, BC, AF, прочие регистры по ROM TR-DOS
; Note:
;   TrDos.Drive, состояние TR-DOS
