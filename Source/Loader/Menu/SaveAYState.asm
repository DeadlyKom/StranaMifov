
; -----------------------------------------
; переход к IM 1 с сохранением состояния AY перед дисковой операцией
; Запрещает прерывания, включает IM 1, устанавливает I=#3F и IY=#5C3A, задаёт HL'=#2758. Читает
; регистры AY 0..13 в #641B..#6428 и записывает в них нули. Включает прерывания.
; In:
;   нет явных аргументов
; Out:
;   IM 1, EI
; Corrupt:
;   HL, DE, BC, AF, HL', IY, I
; Note:
;   #641B..#6428 — сохранённые регистры AY, порты #FFFD/#BFFD
; -----------------------------------------
SaveAYState     DI
                IM 1
                LD A, #3F
                LD I, A
                LD IY, System.Vars                                              ; база системных переменных ROM в IY для BASIC и TR-DOS
                LD HL, #2758
                EXX
                LD DE, #BFFF
                LD HL, Loader.Menu.SaveAYState.AYRegisters                      ; буфер четырнадцати сохранённых регистров AY
                XOR A
                LD C, #FD

                ; каждый AY-регистр сначала читается в буфер, затем исходная ED 71 обнуляет его
                ; на NMOS Z80
.SaveRegister   LD B, E
                OUT (C), A
                INI
                LD B, D
                DB #ED, #71                                                     ; OUT (C), #00/#FF на NMOS/CMOS Z80
                INC A
                CP #0E
                JR NZ, .SaveRegister                                            ; переход, если сохранены ещё не все 14 регистров AY

                EI
                RET

.MenuStack      DW #0000                                                        ; исходный стек вызывающего BASIC
.AYRegisters    EQU $                                                           ; буфер четырнадцати сохранённых регистров AY
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00
