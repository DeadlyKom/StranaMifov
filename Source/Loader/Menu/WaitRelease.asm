
; -----------------------------------------
; ожидание отпускания кнопки действия
; Повторяет опрос до сброса bit 0 в C.
; In:
;   нет регистровых аргументов, #6C5F..#6C72 содержат четыре набора назначений пяти действий,
;   доступны настроенные порты клавиатуры/джойстика
; Out:
;   B=0, бит 0 C=0, Z=1 после проверки кнопки, остальные биты C содержат результат последнего
;   опроса
; Corrupt:
;   HL, DE, BC, AF. HL', DE', BC', AF', IX, IY сохранены
; -----------------------------------------
WaitRelease     CALL ReadControls                                               ; объединённый опрос клавиатуры и Kempston
                BIT MENU_FIRE_BIT, C                                            ; флаг, действие или завершение выбора
                JR NZ, WaitRelease                                              ; переход, если кнопка действия ещё удерживается

                RET
