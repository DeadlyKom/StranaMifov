
; -----------------------------------------
; умножение беззнакового байта на 6 по модулю 256
; Повторяет сложение 6 после установки A=#FA. При исходном A=#FF счётчик B оборачивается и даёт
; 256 итераций, что также сохраняет модульный результат.
; In:
;   A — множитель
; Out:
;   A=6*исходное A mod 256, BC сохранён
; Corrupt:
;   AF
; -----------------------------------------
MulSix          PUSH BC
                LD B, A
                INC B
                LD A, #FA
.AddSix         ADD A, #06
                DJNZ .AddSix

                POP BC
                RET
