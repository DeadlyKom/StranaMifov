
; -----------------------------------------
; перехватчик RST #10 внутри защитного преобразования
; Три POP HL снимают промежуточные адреса пути канала вывода, два DEC SP возвращают позицию к
; исходному адресу RST. Дополнительные XOR H и L смешивают снятый адрес с A. EXX возвращает
; рабочие регистры дешифратора, RET возвращает к #618E. Здесь стек является частью алгоритма
; защиты, обычный подпрограммный контракт неприменим.
; In:
;   стек и альтернативные регистры после пути вывода ПЗУ
; Out:
;   A содержит дополнительное XOR-преобразование, возврат к #618E
; Corrupt:
;   HL, AF, HL', DE', BC'
; -----------------------------------------
PrintHook       POP HL
                POP HL
                POP HL
                DEC SP
                DEC SP
                XOR H
                XOR L
                EXX
                RET

.OutputChannel  EQU $                                                           ; слово адреса PrintHook, временный канал вывода BASIC
                DB #9D, #61
