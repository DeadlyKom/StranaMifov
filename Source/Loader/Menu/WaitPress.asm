
; -----------------------------------------
; ожидание нового нажатия кнопки действия
; Сначала ждёт отпускания, затем повторяет опрос до установки bit 0 в C.
; In:
;   нет регистровых аргументов, #6C5F..#6C72 содержат назначения действий, доступны настроенные
;   порты клавиатуры/джойстика
; Out:
;   после отпускания зафиксировано новое нажатие, B=0, бит 0 C=1, Z=0, остальные биты C содержат
;   результат последнего опроса
; Corrupt:
;   HL, DE, BC, AF. HL', DE', BC', AF', IX, IY сохранены
; -----------------------------------------
WaitPress       CALL WaitRelease                                                ; ожидание отпускания кнопки действия
.PollPress      CALL ReadControls                                               ; объединённый опрос клавиатуры и Kempston
                BIT MENU_FIRE_BIT, C                                            ; флаг, действие или завершение выбора
                JR Z, .PollPress                                                ; переход, если новое нажатие кнопки действия ещё не появилось

                RET
