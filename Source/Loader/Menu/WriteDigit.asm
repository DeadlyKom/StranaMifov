
; -----------------------------------------
; получение одной десятичной цифры повторным вычитанием
; Вычитает C из A и увеличивает B до займа. Восстанавливает остаток, пишет B+ASCII 0 по HL и
; увеличивает HL.
; In:
;   A — делимое, C — делитель, B=0, HL — приёмник
; Out:
;   A — остаток, HL увеличен на 1
; Corrupt:
;   HL, BC, AF
; Note:
;   байт по исходному HL
; -----------------------------------------
WriteDigit      SUB C
                JR C, .StoreDigit                                               ; переход, если остаток меньше текущего десятичного разряда

                INC B
                JR WriteDigit

.StoreDigit     ADD A, C
                LD C, A
                LD A, B
                ADD A, #30
                LD (HL), A
                INC HL
                LD A, C
                RET
