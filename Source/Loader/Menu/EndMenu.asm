
; -----------------------------------------
; завершение выбора пункта меню
; Восстанавливает фон курсора, снимает подсветку всех областей сравнением с заведомо внешними
; координатами и воспроизводит короткий звуковой отклик.
; In:
;   состояние активного меню
; Out:
;   курсор и подсветка убраны
; Corrupt:
;   HL, DE, BC, AF, IX, AF'
; Note:
;   экран, порт #FE
; -----------------------------------------
EndMenu         LD C, #80
                CALL CursorBackdrop                                             ; сохранение или восстановление фона курсора
                LD BC, #8080
                CALL HighlightAreas                                             ; подсветка области меню под курсором
                JP MenuClick
