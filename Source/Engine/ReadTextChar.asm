
; -----------------------------------------
; прочитать и преобразовать символ текстового ввода
; ждёт LAST_K #5C08, #07 меняет бит 6 #6566, #06 меняет бит 1, бит 4 ограничивает ввод цифрами,
; бит 1 меняет регистр латиницы, бит 6 включает таблицу русского алфавита
; In:
;   LAST_K #5C08, флаги режима ввода #6566
; Out:
;   AF, A принятый и преобразованный символ, HL, DE, BC, IX, IY сохранены
; Corrupt:
;   AF, #5C08 очищается перед ожиданием, специальные коды переключают биты 1/6 #6566
; -----------------------------------------
ReadTextChar    PUSH HL
                PUSH BC
                LD HL, State.ViewFlags
.ClearKey       XOR A
                LD (System.LastKey), A

                ; ожидание нового кода клавиши от обработчика ROM
.WaitKey        LD A, (System.LastKey)
                OR A
                JR Z, .WaitKey                                                  ; переход, если ROM ещё не записал новую клавишу

                CALL RemapKey                                                   ; заменить специальные коды клавиатуры по таблице
                CP #07
                JR NZ, .CheckCase                                               ; переход, если клавиша не задаёт переключение алфавита

                LD A, (State.ViewFlags)
                XOR #40
                LD (State.ViewFlags), A
                JR .ClearKey

.CheckCase      CP #06
                JR NZ, .CheckControl                                            ; переход, если клавиша не задаёт переключение регистра

                LD A, (State.ViewFlags)
                XOR #02
                LD (State.ViewFlags), A
                JR .ClearKey

.CheckControl   CP #0C
                JR Z, .RestoreRegs                                              ; переход, если получена команда удаления символа

                CP #0D
                JR Z, .RestoreRegs                                              ; переход, если получена команда подтверждения строки

                CP #0E
                JR Z, .RestoreRegs                                              ; переход, если получена команда отмены ввода

                CP #20
                JR C, .ClearKey                                                 ; переход, если получен непечатный управляющий код

                BIT TEXT_DIGIT_BIT, (HL)                                        ; ограничивает обычный текстовый ввод десятичными цифрами
                JR Z, .ApplyCase                                                ; переход, если режим цифрового ввода не включён

                CP #30
                JR C, .ClearKey                                                 ; переход, если код меньше первой десятичной цифры

                CP #3A
                JR NC, .ClearKey                                                ; переход, если код расположен после последней десятичной цифры

                JR .RestoreRegs

                ; применение выбранного регистра латинских букв
.ApplyCase      BIT TEXT_CASE_BIT, (HL)                                         ; меняет регистр латинских букв и вариант таблицы перекодировки
                JR Z, .CheckAlphabet                                            ; переход, если смена регистра букв не запрошена

                CP #61
                JR C, .LowerCase                                                ; переход, если символ расположен до диапазона строчных латинских букв

                CP #7B
                JR NC, .LowerCase                                               ; переход, если символ расположен после диапазона строчных латинских букв

                SUB #20
                JR .CheckAlphabet

.LowerCase      CP #41
                JR C, .CheckAlphabet                                            ; переход, если символ расположен до диапазона прописных латинских букв

                CP #5B
                JR NC, .CheckAlphabet                                           ; переход, если символ расположен после диапазона прописных латинских букв

                ADD A, #20

                ; перекодировка алфавита разрешается отдельным флагом режима ввода
.CheckAlphabet  BIT TEXT_RUS_BIT, (HL)                                          ; включает перекодировку символов в русский алфавит
                JR Z, .RestoreRegs                                              ; переход, если перекодировка в русский алфавит выключена

                CP #30
                JR NC, .SymbolTable                                             ; переход, если для цифр и более высоких кодов используется основная таблица алфавита

                BIT TEXT_CASE_BIT, (HL)                                         ; меняет регистр латинских букв и вариант таблицы перекодировки
                LD HL, Engine.RemapKey.AltPunct - 32                            ; преобразование шестнадцати кодов пунктуации для альтернативного регистра
                JR Z, .ReadMapped                                               ; переход, если для символа выбран обычный вариант таблицы перекодировки

                LD HL, Engine.RemapKey.CharTable - 32                           ; таблица преобразования кодов символов, индекс начинается с #20
                JR .ReadMapped

.SymbolTable    LD HL, Engine.RemapKey.CharTable - 32                           ; таблица преобразования кодов символов, индекс начинается с #20
.ReadMapped     LD B, #00
                LD C, A
                ADD HL, BC
                LD A, (HL)
.RestoreRegs    POP BC
                POP HL
                RET
