
; -----------------------------------------
; пополнить численные запасы с ограничением максимума
; герой #6A04 +=#6A08 с максимумом #6A06, затем 744 активные записи по 22 байта в банке 1 от
; #C000, поля+3/+4 увеличиваются на+5/+6 с пределом 15000, далее 15 записей по 28 байт от #CCCB
; банка 3, текущие+22/+23 увеличиваются на+26/+27 с максимумом+24/+25, общий ограничитель #A0FC
; In:
;   поля запасов героя и массивов банков 1/3 инициализированы
; Out:
;   герой,744 записи по 22 байта банка 1 и 15 записей правителей по 28 байт банка 3 пополнены с
;   указанными максимумами, банк 3 выбран, IY сохранён
; Corrupt:
;   HL, DE, BC, AF, IX, перечисленные ресурсные поля, IFF разрешён, альтернативные регистры
;   собственным кодом не используются
; -----------------------------------------
RegenMana       LD HL, (State.Mana)
                LD DE, (State.ManaMax)
                LD BC, (State.ManaRegen)
                CALL AddClampedU16                                              ; прибавить BC к HL с верхней границей DE
                LD (State.Mana), HL
                LD A, #01
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, State.AllArmies                                          ; физические записи стратегических армий банка1
                LD BC, #02E8
                LD DE, #0016
.ArmyLoop       BIT ARMY_FREE_BIT, (IX + FMapArmy.Flags)                        ; +#00, состояние внешней армии
                JR NZ, .NextArmy                                                ; переход, если стратегическая армия исключена из обработки

                PUSH BC
                LD L, (IX + FMapArmy.Mana.Low)                                  ; +#03, младший байт, текущий запас магической силы внешней армии. Восстанавливается с пределом 15000 и передаётся словом DE в бой
                LD H, (IX + FMapArmy.Mana.High)                                 ; +#04, старший байт, текущий запас магической силы внешней армии. Восстанавливается с пределом 15000 и передаётся словом DE в бой
                LD DE, #3A98
                LD C, (IX + FMapArmy.ManaRegen.Low)                             ; +#05, младший байт, прибавляемое при регенерации количество магической силы
                LD B, (IX + FMapArmy.ManaRegen.High)                            ; +#06, старший байт, прибавляемое при регенерации количество магической силы
                CALL AddClampedU16                                              ; прибавить BC к HL с верхней границей DE
                LD (IX + FMapArmy.Mana.Low), L                                  ; +#03, младший байт, текущий запас магической силы внешней армии. Восстанавливается с пределом 15000 и передаётся словом DE в бой
                LD (IX + FMapArmy.Mana.High), H                                 ; +#04, старший байт, текущий запас магической силы внешней армии. Восстанавливается с пределом 15000 и передаётся словом DE в бой
                POP BC
                LD DE, #0016
.NextArmy       ADD IX, DE
                DEC BC
                LD A, B
                OR C
                JR NZ, .ArmyLoop                                                ; переход, если остались стратегические армии для восстановления маны

                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, Data.Battle.Ruler01                                      ; первый правитель логического банка3
                LD B, #0F
.RulerLoop      PUSH BC
                LD L, (IX + FRuler.Mana.Low)                                    ; +#16, младший байт, текущая магическая сила
                LD H, (IX + FRuler.Mana.High)                                   ; +#17, старший байт, текущая магическая сила
                LD E, (IX + FRuler.ManaMax.Low)                                 ; +#18, младший байт, максимум магической силы
                LD D, (IX + FRuler.ManaMax.High)                                ; +#19, старший байт, максимум магической силы
                LD C, (IX + FRuler.ManaRegen.Low)                               ; +#1A, младший байт, пополнение магической силы за вызов восстановления
                LD B, (IX + FRuler.ManaRegen.High)                              ; +#1B, старший байт, пополнение магической силы за вызов восстановления
                CALL AddClampedU16                                              ; прибавить BC к HL с верхней границей DE
                LD (IX + FRuler.Mana.Low), L                                    ; +#16, младший байт, текущая магическая сила
                LD (IX + FRuler.Mana.High), H                                   ; +#17, старший байт, текущая магическая сила
                POP BC
                LD DE, #001C
                ADD IX, DE
                DJNZ .RulerLoop

                RET
