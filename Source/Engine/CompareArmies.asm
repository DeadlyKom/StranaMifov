
; -----------------------------------------
; сопоставить взвешенные величины двух составов армии
; S героя=sum5 записей #6A1E(количество*поле 22/23), S вход=sumB записей HL, токен 05 получает S
; героя/S вход, затем на стек 2 и #6DDA вычитает, carry отражает отношение<2, zero отношение=2,
; деление на нулевую силу входной армии явно не защищено, IX/IY сохранены
; In:
;   HL входной список армии, BC, B число его записей, пять записей армии героя #6A1E
; Out:
;   AF, C=1 при силагероя/силавходной<2, Z=1 при равенстве 2, IX и IY сохранены, банк 1 выбран
; Corrupt:
;   HL, DE, BC, AF, альтернативные HL', DE', BC', AF' могут изменяться вызываемым калькулятором
;   ROM и здесь не сохраняются, делитель нулевой силы явно не защищён
; -----------------------------------------
CompareArmies   PUSH IX
                PUSH IY
                PUSH HL
                PUSH BC
                LD B, #05
                LD HL, State.Army
                CALL SumArmyBank1                                               ; вычислить сумму полей армии из банка 1
                POP BC
                POP HL
                CALL SumArmyBank1                                               ; вычислить сумму полей армии из банка 1
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 91A7
                DB #38                                                          ; end-calc, возврат в Z80, 91A8
                LD A, #02
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                CALL FloatSignZero                                              ; определить знак и нулевое значение результата калькулятора
                POP IY
                POP IX
                RET
