
; -----------------------------------------
; нарисовать маскированный слой объекта 4 на 4 знакоместа
; HL пиксели, маска следует через 128 байт, A=0 вызывает #75A2, A!=0 вызывает зеркальный #7649
; In:
;   HL пиксели 4 на 4 знакоместа, следующая маска по HL+128, BC позиция, AF признак зеркальности
;   A
; Out:
;   маскированный слой выведен, HL, BC, A, IX сохранены, DE=#0404, IY=HL исходный+128
; Corrupt:
;   DE, F, IY, атрибуты не изменяются
; -----------------------------------------
DrawMaskLayer   PUSH IX
                PUSH HL
                POP IY
                PUSH HL
                POP IX
                LD DE, #0080
                ADD IY, DE
                LD DE, #0404
                OR A
                JR NZ, .DrawMirrored                                            ; переход, если запрошено горизонтальное отражение маскированного слоя

                CALL DrawMask                                                   ; вывести пиксельный спрайт по маске
                POP IX
                RET

.DrawMirrored   CALL DrawMaskFlip                                               ; вывести маскированный спрайт с горизонтальным отражением
                POP IX
                RET
