
; -----------------------------------------
; выдержать паузу с досрочным выходом по вводу
; сначала #6BE9, затем до B периодов по 50 HALT, после каждого опрос #6BF1, carry завершает
; ожидание
; In:
;   BC, B число периодов по 50HALT, прерывания разрешены
; Out:
;   сначала 20HALT без прерывания вводом, затем ожидание до B*50HALT с досрочным выходом по
;   вводу, HL, DE, BC, AF, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, AF, IX, IY сохранены, обработчик #6BF1 потребляет ввод, причину окончания в
;   регистрах не возвращает, альтернативные регистры ROM клавиатуры отдельно не проверены
; -----------------------------------------
WaitOrInput     CALL Wait20Frames                                               ; выдержать двадцать прерываний
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
.DelayBlock     LD C, #32
.FrameLoop      HALT
                CALL ReadInput                                                  ; прочитать клавиатуру или Kempston
                JR C, .RestoreRegs                                              ; переход, если клавиатура или джойстик дали команду прервать ожидание

                DEC C
                JR NZ, .FrameLoop                                               ; переход, если в текущем блоке задержки остались кадры

                DJNZ .DelayBlock

.RestoreRegs    POP AF
                POP BC
                POP DE
                POP HL
                RET
