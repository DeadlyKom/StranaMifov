
; -----------------------------------------
; перемещение шестибайтовых объектов из континентальной таблицы #6B69
; Выбирает список текущего континента по #6B69, банк 0, шаг 6 байтов. Формирует включительный
; прямоугольник ±3 вокруг героя с обрезкой x=0..160, y=0..99. Пропускает записи с битом 0, вне
; прямоугольника, на клетке героя либо с битом 5, не соответствующим режиму героя 0/1. Направление
; к герою вычисляет #7C71, таблица #92A4 и стековый диспетчер #9245 формируют три кандидата.
; Требует x=3..157, y=3..96. Для объекта с битом 5 разрешён только класс #FF, без бита 5 класс #FF
; запрещён. #8CD1 различает свободную клетку, находку типа 8 и остальные занятые клетки. Свободная
; клетка дополнительно требует снятого бита 7 карты. Находка типа 8 сразу получает бит 0
; использованной записи, а у её байта карты снимается именно бит 0. Для ненулевого класса кандидат
; требует пересечения маски местности с E, возвращённым #7AEF для ID объекта из +3. При успехе
; снимает бит 7 старой клетки, пишет координаты +1/+2 и ориентацию через #91BF, ставит бит 7 новой
; клетки и завершает перебор кандидатов данной записи. После трёх отказов сохраняет исходную
; позицию. Конкретное игровое название этого вида объектов по одному списку не устанавливается.
; In:
;   #6A2D — континент, #6A2E — координаты героя, #6A33 — режим, #6B69 — четыре пары
;   указатель/количество шестибайтовых записей, банк 0 — записи объектов
; Out:
;   координаты и ориентация подходящих объектов обновлены, занятость карты перенесена,
;   встреченные находки типа 8 могут быть использованы до окончательной проверки проходимости
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; Note:
;   #928F..#92BE, #8D29, записи банка 0 и байты карт, переключение банков через драйвер #5FA1.
;   Исходная особенность, #8CD1 меняет IX на найденный объект. При C!=0 и C!=8 отказ #93BC ->
;   #9432 не восстанавливает IX из #928F. Если так заканчивается последний кандидат, #943E
;   прибавляет 6 к чужому указателю, последующий проход может читать другую запись. Проявление в
;   игре не проверено.
; -----------------------------------------
StepMapTroops   LD BC, (State.Position)
                LD A, B
                ADD A, #03
                CP #64
                JR C, .ClampMaxY                                                ; переход, если нижняя граница области близости ещё помещается в допустимую высоту карты

                LD A, #63
.ClampMaxY      LD B, A
                LD A, C
                ADD A, #03
                CP #A1
                JR C, .StoreMaxBounds                                           ; переход, если правая граница области близости ещё помещается в допустимую ширину карты

                LD A, #A0
.StoreMaxBounds LD C, A
                LD (State.NearbyMax), BC
                LD BC, (State.Position)
                LD A, B
                SUB #03
                JR NC, .ClampMinY                                               ; переход, если верхняя граница области близости ещё не вышла выше карты

                XOR A
.ClampMinY      LD B, A
                LD A, C
                SUB #03
                JR NC, .StoreMinBounds                                          ; переход, если вычитание отступа не вывело левую границу колонки за ноль

                XOR A
.StoreMinBounds LD C, A
                LD (State.NearbyMin), BC
                LD IX, State.MapTroopsIndex
                LD A, (State.Continent)
                CALL IndexFourBytes                                             ; сместить IX к четырёхбайтной записи с индексом A
                LD L, (IX + FMapList.Data.Low)                                  ; +#00, младший байт, адрес первой записи в банке выбранной группы
                LD H, (IX + FMapList.Data.High)                                 ; +#01, старший байт, адрес первой записи в банке выбранной группы
                LD C, (IX + FMapList.Count.Low)                                 ; +#02, младший байт, число записей little-endian, не размер в байтах
                LD B, (IX + FMapList.Count.High)                                ; +#03, старший байт, число записей little-endian, не размер в байтах
                PUSH HL
                POP IX

                ; обработка действующих стратегических отрядов около героя
.TroopLoop      XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                BIT TROOP_FREE_BIT, (IX + FMapTroop.Flags)                      ; +#00, состояние шестибайтовой группы, бит 0 свободна/использована, бит 5 вода, бит 6 ориентация, другие биты отдельно не именуются
                JP NZ, .NextTroop                                               ; переход, если стратегический отряд исключён из обработки

                LD E, (IX + FMapTroop.X)                                        ; +#01, столбец карты
                LD D, (IX + FMapTroop.Y)                                        ; +#02, строка карты
                CALL InNearbyRect                                               ; проверить координаты DE относительно ближайшей области героя
                JP NC, .NextTroop                                               ; переход, если отряд находится вне области близости героя

                LD A, (State.MoveFlags)
                AND #03
                LD E, A
                LD A, (IX + FMapTroop.Flags)                                    ; +#00, состояние шестибайтовой группы, бит 0 свободна/использована, бит 5 вода, бит 6 ориентация, другие биты отдельно не именуются
                AND #20
                RLCA
                RLCA
                RLCA
                CP E
                JP NZ, .NextTroop                                               ; переход, если режим местности отряда не совпадает с режимом героя

                LD HL, (State.Position)
                LD E, (IX + FMapTroop.X)                                        ; +#01, столбец карты
                LD D, (IX + FMapTroop.Y)                                        ; +#02, строка карты
                OR A
                SBC HL, DE
                JP Z, .NextTroop                                                ; переход, если отряд уже находится в клетке героя

                PUSH BC
                LD (State.MovingObject), IX
                LD C, (IX + FMapTroop.X)                                        ; +#01, столбец карты
                LD B, (IX + FMapTroop.Y)                                        ; +#02, строка карты
                LD DE, (State.Position)
                CALL GetDirection                                               ; определить одно из восьми направлений от BC к DE
                LD (State.MoveDirection), A
                LD IY, State.TowardSteps
                CALL MakeSteps                                                  ; построить три возможных шага объекта и вызвать обработчик направления
                LD IY, State.StepCandidates
                LD B, #03

                ; проверка трёх соседних кандидатов на границы, занятость и местность
.CandidateLoop  PUSH BC
                LD A, (IY + FMoveStep.X)                                        ; +#01, столбец соседней клетки
                CP #03
                JP C, .NextCandidate                                            ; переход, если кандидат находится левее допустимой области карты

                CP #9E
                JP NC, .NextCandidate                                           ; переход, если кандидат находится правее допустимой области карты

                LD A, (IY + FMoveStep.Y)                                        ; +#02, строка соседней клетки
                CP #03
                JP C, .NextCandidate                                            ; переход, если кандидат находится выше допустимой области карты

                CP #61
                JP NC, .NextCandidate                                           ; переход, если кандидат находится ниже допустимой области карты

                XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD HL, (State.MovingObject)
                LD A, (IY + FMoveStep.TerrainMask)                              ; +#00, маска класса местности кандидата, #FF выделяет водный класс, 0 не требует проверки способностей
                BIT ARMY_WATER_BIT, (HL)                                        ; выбирает водный класс перемещения внешней армии либо шестибайтовой группы
                JR NZ, .CheckSeaCell                                            ; переход, если отряд требует водный класс местности

                CP #FF
                JP Z, .NextCandidate                                            ; переход, если сухопутному отряду предложена водная клетка

                JR .CheckObject

.CheckSeaCell   CP #FF
                JP NZ, .NextCandidate                                           ; переход, если водному отряду предложена неводная клетка

.CheckObject    PUSH IY
                LD C, (IY + FMoveStep.X)                                        ; +#01, столбец соседней клетки
                LD B, (IY + FMoveStep.Y)                                        ; +#02, строка соседней клетки
                LD (State.ObjectCell), BC
                CALL FindMapObject                                              ; определить тип объекта в координатах #8D29
                POP IY
                LD A, C
                OR A
                JR Z, .CheckMapCell                                             ; переход, если в клетке кандидата нет стратегического объекта

                CP #08
                JP NZ, .NextCandidate                                           ; переход, если тип объекта в клетке не разрешает перемещение

                SET ITEM_USED_BIT, (IX + FMapItem.Flags)                        ; находка использована и исключена из обработки
                CALL SelectMapBank                                              ; выбрать логический банк 10 с текущей картой
                LD C, (IY + FMoveStep.X)                                        ; +#01, столбец соседней клетки
                LD B, (IY + FMoveStep.Y)                                        ; +#02, строка соседней клетки
                CALL MapCellAddress                                             ; вычислить адрес клетки карты
                RES TERRAIN_LSB_BIT, (HL)                                       ; младший разряд байта местности, исходный StepMapTroops снимает его после поглощения находки, бит занятости при этом отдельно не снимается
                JR .CheckTerrain

.CheckMapCell   LD C, (IY + FMoveStep.X)                                        ; +#01, столбец соседней клетки
                LD B, (IY + FMoveStep.Y)                                        ; +#02, строка соседней клетки
                CALL ReadMapCell                                                ; прочитать байт клетки текущей карты
                BIT MAP_BUSY_BIT, A                                             ; клетка стратегической карты занята объектом
                JP NZ, .NextCandidate                                           ; переход, если клетка кандидата занята

.CheckTerrain   LD A, (IY + FMoveStep.TerrainMask)                              ; +#00, маска класса местности кандидата, #FF выделяет водный класс, 0 не требует проверки способностей
                OR A
                JR Z, .CommitMove                                               ; переход, если кандидат не требует проверки маски способностей

                XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, (State.MovingObject)
                LD A, (IX + FMapTroop.ID)                                       ; +#03, тип отряда, описатель SOLDIERS
                CALL UnitFlags                                                  ; прочитать пару флагов описателя отряда
                LD A, E
                AND (IY + FMoveStep.TerrainMask)                                ; +#00, маска класса местности кандидата, #FF выделяет водный класс, 0 не требует проверки способностей
                JR Z, .NextCandidate                                            ; переход, если отряд не допускает местность кандидата

                ; перенос отряда в принятую клетку
.CommitMove     POP BC
                XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, (State.MovingObject)
                LD C, (IX + FMapTroop.X)                                        ; +#01, столбец карты
                LD B, (IX + FMapTroop.Y)                                        ; +#02, строка карты
                CALL SelectMapBank                                              ; выбрать логический банк 10 с текущей картой
                CALL MapCellAddress                                             ; вычислить адрес клетки карты
                RES MAP_BUSY_BIT, (HL)                                          ; клетка стратегической карты занята объектом
                XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD C, (IY + FMoveStep.X)                                        ; +#01, столбец соседней клетки
                LD B, (IY + FMoveStep.Y)                                        ; +#02, строка соседней клетки
                LD (IX + FMapTroop.X), C                                        ; +#01, столбец карты
                LD (IX + FMapTroop.Y), B                                        ; +#02, строка карты
                LD A, (State.MoveDirection)
                CALL SetFacing                                                  ; изменить бит 6 флагов объекта по коду направления
                CALL SelectMapBank                                              ; выбрать логический банк 10 с текущей картой
                CALL MapCellAddress                                             ; вычислить адрес клетки карты
                SET MAP_BUSY_BIT, (HL)                                          ; клетка стратегической карты занята объектом
                JR .RestoreCount

.NextCandidate  POP BC
                INC IY
                INC IY
                INC IY
                DEC B
                JP NZ, .CandidateLoop                                           ; переход, если остались кандидаты перемещения

.RestoreCount   POP BC
.NextTroop      LD DE, #0006
                ADD IX, DE
                DEC BC
                LD A, B
                OR C
                JP NZ, .TroopLoop                                               ; переход, если остались стратегические отряды для обработки

                RET
