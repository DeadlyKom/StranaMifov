
; -----------------------------------------
; увеличить столбец героя и повернуть его вправо
; при C=#9E переход #8BE4, иначе INC C, в #6A33 ставится бит 3, при режиме 1 также ставится бит 4
; In:
;   BC координаты героя, предполагается вызов из обработки перемещения
; Out:
;   если C!=158, C изменён на+1 и обычный RET, для горизонтального шага обновлены биты 3/4
;   #6A33. На границе 7HALT с бордюром, POP HL отбрасывает адрес возврата и JP #8A2C
; Corrupt:
;   AF и изменяемый байт BC в обычной ветви, HL, DE, IX, IY сохранены только до граничного
;   перехода, после перехода действует контракт #8A2C
; -----------------------------------------
MapMoveRight    LD A, C
                CP #9E
                JR Z, MapMoveUp.FlashBorder                                     ; переход, если герой достиг правой допустимой колонки карты

                INC C
                LD A, (State.MoveFlags)
                SET HERO_FACE_BIT, A                                            ; горизонтальное отражение изображения героя
                LD (State.MoveFlags), A
                AND #03
                CP #01
                RET NZ                                                          ; выход, если герой перемещается не на корабле

                LD A, (State.MoveFlags)
                SET SHIP_FACE_BIT, A                                            ; альтернативное горизонтальное представление корабля
                LD (State.MoveFlags), A
                RET
