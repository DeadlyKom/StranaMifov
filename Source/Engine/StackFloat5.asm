
; -----------------------------------------
; передать пятибайтное число по HL на стек калькулятора
; читает пять байтов в A, E, D, C, B и вызывает ROM #2ABB, возвращает HL после числа, DE, BC, AF
; сохранены
; In:
;   HL адрес пятибайтного числа в формате калькулятора Spectrum
; Out:
;   HL исходный адрес+5, число добавлено на стек калькулятора, DE, BC, AF сохранены
; Corrupt:
;   HL, альтернативные HL', DE', BC', AF' зависят от внутреннего соглашения ROM и отдельно не
;   проверены, IX/IY здесь явно не сохраняются, соглашение ROM #2ABB отдельно не проверено
; -----------------------------------------
StackFloat5     PUSH DE
                PUSH BC
                PUSH AF
                LD A, (HL)
                INC HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                INC HL
                LD C, (HL)
                INC HL
                LD B, (HL)
                INC HL
                PUSH HL
                CALL Rom.StackFloat                                             ; помещение пятибайтного числа A,E,D,C,B на стек калькулятора
                POP HL
                POP AF
                POP BC
                POP DE
                RET
