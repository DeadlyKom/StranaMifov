
; -----------------------------------------
; наложить один байт указателя в пределах пиксельной области
; при H<#58 экран=(экран AND(IY)) OR(IX), затем HL, IX, IY увеличиваются даже для пропущенного
; байта
; In:
;   HL адрес экрана, IX пиксели, IY маска
; Out:
;   HL, IX, IY увеличены на 1, при исходном H<#58 байт наложен как(screen AND mask)ORpixel, DE и
;   BC сохранены
; Corrupt:
;   HL, AF, IX, IY, пиксельный байт при допустимом H
; -----------------------------------------
CursorMaskByte  LD A, H
                CP #58
                JR NC, .NextMaskByte                                            ; переход, если вычисленный адрес уже находится за пиксельной областью экрана

                LD A, (HL)
                AND (IY + #00)
                OR (IX + #00)
                LD (HL), A
.NextMaskByte   INC HL
                INC IX
                INC IY
                RET
