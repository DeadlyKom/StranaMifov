
; -----------------------------------------
; преобразовать боевые записи обратно в исходный состав армии
; IX до 5 боевых записей по 18 байт в банке 3, IY целевой массив записей по 3 байта в банке C,
; сначала очищает B исходных записей, ID переносится напрямую, пятибайтное количество
; преобразуется ROM в BC и записывается +1/+2, исходный банк восстановлен
; In:
;   BC, B максимум записей и C банк назначения, IX боевые записи 18 байт банка 3, IY исходные
;   записи 3 байта
; Out:
;   до B непустых боевых отрядов преобразованы обратно, IX шагает 18, IY шагает 3, прежний банк
;   и исходные F восстановлены, A=прежнийбанк
; Corrupt:
;   HL, DE, BC, A, IX, IY и целевой массив, альтернативные HL', DE', BC', AF' могут изменяться
;   вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
StoreArmy       LD A, (State.Bank)
                PUSH AF
                LD A, C
                LD (Engine.BuildArmy.SourcePage), A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                PUSH BC
                PUSH IY
                POP HL
.ClearTroop     LD (HL), #00
                INC HL
                LD (HL), #00
                INC HL
                LD (HL), #00
                INC HL
                DJNZ .ClearTroop

                POP BC
.UnitLoop       LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD A, (IX + FBattleUnit.UnitID)                                 ; +#00, ID типа, 0 завершает плотный список
                OR A
                JR Z, .RestorePage                                              ; переход, если достигнут конец боевой армии

                PUSH BC
                PUSH AF
                LD A, (Engine.BuildArmy.SourcePage)
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                LD (IY + FTroop.ID), A                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                PUSH IX
                POP HL
                INC HL
                INC HL
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD A, (IX + FBattleUnit.Quantity)                               ; +#02, пятибайтовое число ROM, сохраняет дробные потери
                OR A
                JR Z, .StoreCount                                               ; переход, если боевое количество хранится в целочисленной форме ROM

                PUSH IY
                PUSH IX
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #27                                                          ; int, округление вниз, 8944
                DB #A1                                                          ; stk-one, константа 1, 8945
                DB #0F                                                          ; addition, сложение, 8946
                DB #38                                                          ; end-calc, возврат в Z80, 8947
                POP IX
                POP IY
.StoreCount     CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                LD A, (Engine.BuildArmy.SourcePage)
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD (IY + FTroop.Count.Low), C                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD (IY + FTroop.Count.High), B                                  ; +#02, старший байт, беззнаковая численность little-endian
                LD DE, #0003
                ADD IY, DE
                LD DE, #0012
                ADD IX, DE
                POP BC
                DJNZ .UnitLoop

.RestorePage    POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                RET
