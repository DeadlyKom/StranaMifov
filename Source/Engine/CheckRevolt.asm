
; -----------------------------------------
; проверить превышение контроля и обработать доплату либо бой с отделившимся отрядом
; пять плотных записей от 6A1E, ID0 завершает процедуру, CAP=floor(word[6A02]/byte[6AD3+ID]),
; конфликт требует Q>CAP и RandomScaled(3)=3, то есть нового слова генератора >=54614, доплата
; D=Q*word(описатель 8036+22), при M<D сразу бой, при M>=D ответ меню 1 вычитает D и сохраняет
; отряд, другой ответ вызывает RandomScaled(2), результат 0 сохраняет деньги и отряд, результаты
; 1/2 ведут к бою, перед боем запись копируется в A475, исходная обнуляется, армия уплотняется,
; D255 вызывается с DE=0, IX=A475, BC=0500, тип поля 6 при (6A33 AND3)=1 либо по 80C4/8697, A=0
; показывает успех, A!=0 вызывает 89E0 для насыщенного вычитания floor(2*float[656C]/float[6567])
; из 6A02, мирного удаления отряда без боя нет, оплата не меняет предел контроля, ветки оплаты,
; тихого отказа и победы вызывают 957C без сохранения IY и потому не гарантируют правильного
; продолжения обхода
; In:
;   армия 6A1E из пяти плотных записей ID/количество 16, поле 6A02, коэффициенты 6AD3, наличные
;   float5 по 6A14, генератор 7C6B..7C70, текущая клетка 6A2E и младшие два бита 6A33 для выбора
;   поля боя
; Out:
;   деньги уменьшены только при оплате или по собственному исходу боя, отряд сохраняется при
;   оплате и тихом отказе, перед боем отделяется от армии героя, непобеда дополнительно
;   уменьшает 6A02, обновляются панели и вид карты
; Corrupt:
;   HL, DE, BC, AF, IX, IY, армия 6A1E, временный список A475..A483, float5A564, состояние
;   генератора, интерфейсные поля и эффекты вызванного боя
; Note:
;   подтверждённая особенность исходника, CALL957C по A43B не сохраняет IY и заменяет его
;   указателем после обхода армии, поэтому дальнейший INC IY×3 может пропустить записи или выйти
;   за пределы армии, код не изменялся
; -----------------------------------------
CheckRevolt     LD IY, State.Army
                LD B, #05

                ; проверка численности каждого отряда относительно предела управления
.UnitLoop       LD A, (IY + FTroop.ID)                                          ; +#00, тип отряда и временные отметки
                OR A
                RET Z                                                           ; выход, если достигнут конец плотного списка армии

                PUSH BC
                CALL ControlLimit                                               ; рассчитать численный предел типа отряда из поля героя и таблицы
                LD L, C
                LD H, B
                LD E, (IY + FTroop.Count.Low)                                   ; +#01, младший байт численности
                LD D, (IY + FTroop.Count.High)                                  ; +#02, старший байт численности
                OR A
                SBC HL, DE
                JP NC, .NextUnit                                                ; переход, если численность отряда не превышает предел управления

                LD DE, #0003
                CALL RandomScaled                                               ; получить масштабированное псевдослучайное число
                LD A, E
                CP #03
                JP NZ, .NextUnit                                                ; переход, если случайная проверка не выбрала конфликт

                CALL StopView                                                   ; выключить обработку объектов в прерывании
                CALL ResetViewFlags                                             ; сбросить младшие шесть флагов 48 записей объектов
                LD A, (IY + FTroop.ID)                                          ; +#00, тип отряда и временные отметки
                CALL UnitDesc                                                   ; получить описатель типа отряда
                LD C, (IX + FSoldier.UnitValue.Low)
                LD B, (IX + FSoldier.UnitValue.High)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD C, (IY + FTroop.Count.Low)                                   ; +#01, младший байт численности
                LD B, (IY + FTroop.Count.High)                                  ; +#02, старший байт численности
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, A328
                DB #38                                                          ; end-calc, возврат в Z80, A329
                LD HL, Engine.CheckRevolt.PaymentDue                            ; пятибайтная сумма требуемой доплаты
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                LD HL, State.Money
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD HL, Engine.CheckRevolt.PaymentDue                            ; пятибайтная сумма требуемой доплаты
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                CALL FloatSignZero                                              ; определить знак и нулевое значение результата калькулятора
                JR NC, .ShowRevolt                                              ; переход, если наличных денег достаточно для требуемой доплаты

                LD BC, #0900
                LD DE, #0512
                LD A, #42
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                LD B, #0B
                LD DE, Engine.CheckRevolt.NoMoneyText                           ; сообщение мятежников при отсутствии денег для доплаты
                CALL PrintMessage                                               ; разобрать строку сообщения с управляющими кодами
                LD B, #14
                CALL WaitOrInput                                                ; выдержать паузу с досрочным выходом по вводу
                JP .ClearRebelArmy

                ; показ сообщения о выходе отряда из подчинения
.ShowRevolt     LD A, (IY + FTroop.ID)                                          ; +#00, тип отряда и временные отметки
                LD BC, #0202
                CALL SetUnitPicture                                             ; создать четырёхкадровый экранный объект
                LD BC, #0701
                LD DE, #0C10
                LD A, #02
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                LD BC, #0D02
                LD DE, #0310
                LD A, #46
                CALL FillAttributes                                             ; заполнить прямоугольник атрибутов цветом A
                LD DE, Engine.CheckRevolt.DemandText                            ; требование доплаты с подстановкой суммы
                LD B, #0D
                CALL PrintMessage                                               ; разобрать строку сообщения с управляющими кодами
                CALL StartView                                                  ; включить обработку объектов в прерывании
                PUSH IY
                LD IX, Engine.CheckRevolt.PaymentMenu                           ; два пункта меню согласия или отказа платить
                CALL SelectMenuItem                                             ; управлять указателем и выбрать прямоугольный пункт меню
                POP IY
                CP #01
                JR NZ, .RandomChoice                                            ; переход, если игрок выбрал не оплату

                LD HL, State.Money
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD HL, Engine.CheckRevolt.PaymentDue                            ; пятибайтная сумма требуемой доплаты
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #03                                                          ; subtract, вычитание, A3A2
                DB #38                                                          ; end-calc, возврат в Z80, A3A3
                LD HL, State.Money
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                JP .RefreshView

.RandomChoice   LD DE, #0002
                CALL RandomScaled                                               ; получить масштабированное псевдослучайное число
                LD A, E
                OR A
                JP Z, .RefreshView                                              ; переход, если случайный отказ позволил сохранить отряд без оплаты

                ; формирование отдельной армии для боя с мятежниками
.ClearRebelArmy LD HL, Engine.CheckRevolt.RebelArmy                             ; пять FTroop временной армии мятежников
                LD DE, Engine.CheckRevolt.RebelArmy + 1                         ; следующий байт при очистке временной армии мятежников
                LD BC, #000E
                LD (HL), #00
                LDIR
                PUSH IY
                POP HL
                LD DE, Engine.CheckRevolt.RebelArmy                             ; пять FTroop временной армии мятежников
                LD BC, #0003
                LDIR
                LD (IY + FTroop.ID), #00                                        ; +#00, тип отряда и временные отметки
                LD (IY + FTroop.Count.Low), #00                                 ; +#01, младший байт численности
                LD (IY + FTroop.Count.High), #00                                ; +#02, старший байт численности
                LD HL, State.Army
                LD B, #05
                CALL CompactArmy                                                ; сжать список трёхбайтных записей армии
                DEC IY
                DEC IY
                DEC IY
                LD DE, #0000
                LD IX, Engine.CheckRevolt.RebelArmy                             ; пять FTroop временной армии мятежников
                LD A, (State.MoveFlags)
                AND #03
                CP #01
                LD A, #06
                JR Z, .FightRebels                                              ; переход, если герой находится на корабле и требуется морское поле боя

                LD BC, (State.Position)
                CALL ReadMapCell                                                ; прочитать байт клетки текущей карты
                AND #3F
                CALL TerrainBattle                                              ; преобразовать местность по второй таблице порогов

                ; бой с выделенной армией мятежников
.FightRebels    LD BC, #0500
                PUSH IY
                CALL Battle.Battle                                              ; выполнить бой на поле 8 на 5 клеток
                POP IY
                OR A
                JR NZ, .LoseTroop                                               ; переход, если бой с мятежниками закончился непобедой

                PUSH IY
                CALL RefreshPanels                                              ; перерисовать верхнюю строку и боковую панель игры
                CALL UpdateLocalView                                            ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT
                CALL StopView                                                   ; выключить обработку объектов в прерывании
                LD BC, #0900
                LD DE, #0512
                LD A, #47
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                LD B, #0B
                LD DE, Engine.CheckRevolt.VictoryText                           ; сообщение успешного подавления отделившегося отряда
                CALL PrintMessage                                               ; разобрать строку сообщения с управляющими кодами
                LD B, #14
                CALL WaitOrInput                                                ; выдержать паузу с досрочным выходом по вводу
                POP IY
.RefreshView    CALL RefreshHero                                                ; обновить боковую панель героя, расходы и рейтинг
                JR .NextUnit

                ; штраф к лидерству и восстановление основного экрана
.LoseTroop      PUSH IY
                CALL LoseLeadership                                             ; уменьшить 16 битное поле героя #6A02 с насыщением 0
                CALL RefreshPanels                                              ; перерисовать верхнюю строку и боковую панель игры
                CALL UpdateLocalView                                            ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT
                CALL StopView                                                   ; выключить обработку объектов в прерывании
                LD BC, #0900
                LD DE, #0512
                LD A, #42
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                LD B, #0B
                LD DE, Engine.CheckRevolt.DefeatText                            ; сообщение после поражения от отделившегося отряда
                CALL PrintMessage                                               ; разобрать строку сообщения с управляющими кодами
                LD B, #14
                CALL WaitOrInput                                                ; выдержать паузу с досрочным выходом по вводу
                POP IY
.NextUnit       POP BC
                INC IY
                INC IY
                INC IY
                DEC B
                JP NZ, .UnitLoop                                                ; переход, если остались записи армии для проверки

                RET

.RebelArmy      EQU $                                                           ; пять FTroop временной армии мятежников
                DB #00, #00, #00, #00, #00, #00, #00, #00
.VictoryText    EQU $+7                                                         ; сообщение успешного подавления отделившегося отряда
                DB #00, #00, #00, #00, #00, #00, #00, #11
                DB #00, #1A, #82, #A0, #AC, #20, #E3, #A4
                DB #A0, #AB, #AE, #E1, #EC, #20, #E1, #AF
                DB #E0, #A0, #A2, #A8, #E2, #EC, #E1, #EF
                DB #0D, #2A, #E1, #20, #ED, #E2, #A8, #AC
                DB #A8, #20, #AC, #A5, #AB, #AA, #A8, #AC
                DB #A8, #0D, #2A, #AD, #A5, #AF, #E0, #A8
                DB #EF, #E2, #AD, #AE, #E1, #E2, #EF, #AC
.DefeatText     EQU $+7                                                         ; сообщение после поражения от отделившегося отряда
                DB #A8, #2E, #2E, #2E, #0D, #2A, #00, #11
                DB #00, #1A, #82, #20, #E1, #AB, #A5, #A4
                DB #E3, #EE, #E9, #A8, #A9, #20, #E0, #A0
                DB #A7, #0D, #2A, #E1, #AB, #E3, #E8, #A0
                DB #A9, #2C, #20, #E7, #E2, #AE, #20, #E2
                DB #A5, #A1, #A5, #0D, #2A, #A3, #AE, #A2
                DB #AE, #E0, #EF, #E2, #2E, #0D, #2A, #00
.NoMoneyText    EQU $                                                           ; сообщение мятежников при отсутствии денег для доплаты
                DB #11, #00, #1A, #8D, #A5, #E1, #E7, #A0
                DB #E1, #E2, #AD, #AE, #A5, #20, #AD, #A8
                DB #E9, #A5, #A5, #0D, #2A, #AD, #A8, #E7
                DB #E2, #AE, #A6, #A5, #E1, #E2, #A2, #AE
                DB #2C, #20, #AA, #A0, #AA, #20, #A6, #A5
                DB #0D, #2A, #E2, #EB, #20, #AD, #A0, #AC
                DB #20, #AD, #A0, #A4, #AE, #A5, #AB, #AE
.DemandText     EQU $+5                                                         ; требование доплаты с подстановкой суммы
                DB #20, #21, #0D, #2A, #00, #11, #00, #1A
                DB #8C, #EB, #20, #AF, #AE, #A4, #E3, #AC
                DB #A0, #AB, #A8, #20, #A8, #20, #E0, #A5
                DB #E8, #A8, #AB, #A8, #2C, #0D, #2A, #E7
                DB #E2, #AE, #20, #E2, #EB, #20, #AD, #A0
                DB #AC, #20, #A4, #AE, #AB, #A6, #A5, #AD
.PaymentDue     EQU $+7                                                         ; пятибайтная сумма требуемой доплаты
                DB #0D, #2A, #A5, #E9, #A5, #20, #10, #00
                DB #00, #00, #00, #00, #00, #AC, #AE, #AD
                DB #A5, #E2, #2E, #0D, #2A, #0D, #00, #95
                DB #AE, #E0, #AE, #E8, #AE, #2C, #20, #EF
                DB #20, #A7, #A0, #AF, #AB, #A0, #E7, #E3
                DB #2E, #0D, #2A, #8D, #A8, #E7, #A5, #A3
                DB #AE, #20, #AD, #A5, #20, #AF, #AE, #AB
                DB #E3, #E7, #A8, #E2, #A5, #20, #21, #0D
.PaymentMenu    EQU $+2                                                         ; два пункта меню согласия или отказа платить
                DB #2A, #00, #02, #0A, #88, #8C, #98, #32
                DB #8A, #02, #11, #12, #12, #02, #12, #12
                DB #13
