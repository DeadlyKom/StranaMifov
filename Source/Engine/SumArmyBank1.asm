
; -----------------------------------------
; вычислить сумму полей армии из банка 1
; A=1, #6D2F, затем #7A17, вход HL/B задаёт список трёхбайтных записей
; In:
;   HL список трёхбайтных записей, BC, B максимум записей
; Out:
;   банк 1 выбран, сумма количество*поле 22/23 на стеке калькулятора, как в #7A17
; Corrupt:
;   HL, DE, BC, AF, IX/IY не сохраняются единым контрактом ROM, альтернативные HL', DE', BC',
;   AF' могут изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
SumArmyBank1    LD A, #01
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                CALL SumArmyPower                                               ; сложить произведения количества отрядов на поле силы типа
                RET
