
; -----------------------------------------
; заполнить тип местности у трёх возможных шагов
; продолжение стекового диспетчера #9245, три записи [тип, C, B] по #92B6, #80C4 читает карту по
; координатам+1/+2, #867D преобразует байт местности в маску, она записывается в поле 0, IY шагает
; по 3 байта
; In:
;   три записи [тип, C, B] #92B6 уже заполнены координатами
; Out:
;   BC координаты третьего кандидата, AF, A его маска местности, IY=#92BF, D=0, HL и IX
;   сохранены
; Corrupt:
;   DE, BC, AF, IY, первый байт каждой из трёх записей получает результат #867D(#80C4)
; -----------------------------------------
ClassifySteps   LD IY, State.StepCandidates
                LD D, #03
.StepLoop       LD C, (IY + FMoveStep.X)
                LD B, (IY + FMoveStep.Y)
                CALL ReadMapCell                                                ; прочитать байт клетки текущей карты
                CALL TerrainMask                                                ; преобразовать младшие шесть бит байта местности по таблице порогов
                LD (IY + FMoveStep.TerrainMask), A
                INC IY
                INC IY
                INC IY
                DEC D
                JR NZ, .StepLoop                                                ; переход, если остались кандидаты, которым требуется определить класс местности

                RET

                DB #00, #00, #00, #00, #00, #00, #00, #0B
                DB #92, #1B, #92, #28, #92, #38, #92, #D1
                DB #91, #E1, #91, #EE, #91, #FE, #91, #D1
                DB #91, #E1, #91, #EE, #91, #FE, #91, #0B
                DB #92, #1B, #92, #28, #92, #38, #92, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00
