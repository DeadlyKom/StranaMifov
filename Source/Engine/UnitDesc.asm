
; -----------------------------------------
; получить описатель типа отряда
; выбирает логический банк 3, IX=#BFD6+42*A, ID1 соответствует первому элементу SOLDIERS по #C000,
; A сохраняется, нулевой ID не допускается из-за DJNZ
; In:
;   AF, A номер записи начиная с 1, нулевой индекс недопустим
; Out:
;   IX адрес записи, банк 3 выбран и прерывания разрешены, HL, DE, BC, AF, IY сохранены
; Corrupt:
;   IX, состояние банка и IFF, остальные регистры не меняются
; -----------------------------------------
UnitDesc        PUSH DE
                PUSH BC
                PUSH AF
                LD B, A
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD DE, #002A
                LD IX, UnitTypes.RuntimeBase - FSoldier                         ; смещённая база runtime-описателей банка3, ID1 даёт первый SOLDIERS по C000
.UnitLoop       ADD IX, DE
                DJNZ .UnitLoop

                POP AF
                POP BC
                POP DE
                RET
