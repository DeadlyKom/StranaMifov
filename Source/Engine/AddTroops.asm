
; -----------------------------------------
; добавить количество BC к типу отряда A в армии героя
; уплотняет пять записей #6A1E через #807E, находит совпадающий ID либо первую пустую запись, для
; нового ID #7A94 очищает два счётчика, записывает ID и прибавляет 16 битное количество BC
; In:
;   BC добавляемое количество, AF, A ID типа, в армии существует этот ID либо свободная запись
; Out:
;   ID найден/создан, его 16 битное количество увеличено на BC, HL у младшего байта количества,
;   DE новое количество, BC, A, IX, IY сохранены
; Corrupt:
;   HL, DE и F, массив #6A1E и два счётчика нового ID, переполнение количества и отсутствие
;   свободной записи отдельно не проверяются
; -----------------------------------------
AddTroops       PUSH BC
                PUSH AF
                LD HL, State.Army
                LD B, #05
                CALL CompactArmy                                                ; сжать список трёхбайтных записей армии
                POP AF
                POP BC
                LD HL, State.Army
                LD E, A
.FindTroop      LD A, (HL)
                OR A
                JR Z, .EmptySlot                                                ; переход, если найден свободный слот армии

                CP E
                JR Z, .AddCount                                                 ; переход, если в слоте уже находится добавляемый тип отряда

                INC HL
                INC HL
                INC HL
                JR .FindTroop

.EmptySlot      LD A, E
                CALL ClearTwoFlags                                              ; обнулить два связанных байта таблиц
.AddCount       LD (HL), E
                INC HL
                LD E, (HL)
                INC HL
                LD D, (HL)
                EX DE, HL
                ADD HL, BC
                EX DE, HL
                LD (HL), D
                DEC HL
                LD (HL), E
                RET
