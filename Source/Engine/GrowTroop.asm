
; -----------------------------------------
; увеличить количество заданного типа в трёхбайтной записи
; если ID по IX совпадает #A203, количество HL увеличивается на частное от деления исходного
; количества на #A204 через повторное вычитание, запись+1/+2 обновляется, IX всегда сдвигается на
; 3
; In:
;   IX трёхбайтная запись, #A203 требуемый ID, #A204 ненулевой делитель прироста
; Out:
;   IX увеличен на 3, при совпадении ID количество+=floor(старое/делитель), DE, BC, IY
;   сохранены, HL результат количества при совпадении иначе исходный
; Corrupt:
;   HL, AF, IX, запись количества при совпадении, делитель 0 ведёт незавершающемуся вычитанию,
;   переполнение прибавления не ограничивается
; -----------------------------------------
GrowTroop       LD A, (Engine.WeekEvent.GrowthUnitID)
                CP (IX + FTroop.ID)                                             ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                JR NZ, .NextTroop                                               ; переход, если тип записи не выбран для недельного роста

                PUSH DE
                PUSH BC
                LD L, (IX + FTroop.Count.Low)                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD H, (IX + FTroop.Count.High)                                  ; +#02, старший байт, беззнаковая численность little-endian
                LD A, (Engine.WeekEvent.GrowthDivisor)
                LD E, A
                LD D, #00
                LD BC, #FFFF
                PUSH HL
.DivideGrowth   INC BC
                SBC HL, DE
                JR NC, .DivideGrowth                                            ; переход, если в исходной численности ещё содержится целая доля прироста

                POP HL
                ADD HL, BC
                LD (IX + FTroop.Count.Low), L                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD (IX + FTroop.Count.High), H                                  ; +#02, старший байт, беззнаковая численность little-endian
                POP BC
                POP DE
.NextTroop      INC IX
                INC IX
                INC IX
                RET
