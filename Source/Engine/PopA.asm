
; -----------------------------------------
; извлечь байтовое целое из калькулятора ROM
; ROM #2DD5 возвращает численный результат в A, в #7227 используется для получения отдельной
; десятичной цифры, HL, DE, BC, IX, IY сохранены
; In:
;   верхнее число стека калькулятора ROM
; Out:
;   AF, A преобразованное байтовое целое, HL, DE, BC, IX, IY сохранены
; Corrupt:
;   AF, альтернативные HL', DE', BC', AF' зависят от внутреннего соглашения ROM и отдельно не
;   проверены, обработка переполнения самого ROM отдельно не доказана
; -----------------------------------------
PopA            PUSH HL
                PUSH DE
                PUSH BC
                PUSH IX
                PUSH IY
                CALL Rom.PopA                                                   ; преобразование вершины калькулятора в байтовое A
                POP IY
                POP IX
                POP BC
                POP DE
                POP HL
                RET
