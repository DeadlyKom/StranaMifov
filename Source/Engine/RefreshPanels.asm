
; -----------------------------------------
; перерисовать верхнюю строку и боковую панель игры
; верхняя рамка #73FE, обязательная проверяемая очистка #6B8D, строка #9525 по BC=#0112, дата
; через #9468, подробности героя через #957C
; In:
;   поля даты, героя и ресурсов главного экрана
; Out:
;   верхняя строка и боковая панель обновлены, #6B8D очищает рабочий банк 8 в проверяемой
;   контрольной точке
; Corrupt:
;   HL, DE, BC, AF, IX, IY, экран, рабочий банк 8 и калькулятор ROM
; -----------------------------------------
RefreshPanels   LD BC, #0000
                LD DE, #021E
                LD A, #45
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                CALL ClearBank8                                                 ; очистить рабочую область логического банка 8
                LD BC, #0112
                LD DE, Engine.PrintU16.DayText                                  ; слово день для подписи календаря
                CALL PrintZeroText                                              ; вывести строку с нулевым терминатором
                CALL PrintDate                                                  ; разобрать счётчик дней и вывести календарную дату
                CALL RefreshHero                                                ; обновить боковую панель героя, расходы и рейтинг
                RET
