
; -----------------------------------------
; построить три возможных шага объекта и вызвать обработчик направления
; A1..8, IY база таблицы слов, выбирает адрес по IY+2*A, кладёт в стек сначала #9270 затем
; выбранный адрес, создаёт три записи [0, IX+1, IX+2] по #92B6, IY=#92B6, RET передаёт управление
; выбранному обработчику, его RET возвращается в #9270
; In:
;   AF, A направление 1..8, IX запись объекта с координатами+1/+2, IY база таблицы направлений
; Out:
;   три кандидата [тип, C, B] сформированы по #92B6 и классифицированы продолжением #9270,
;   HL=#92BF, BC координаты третьего кандидата, IX сохранён, IY=#92BF
; Corrupt:
;   HL, DE, BC, AF, IY, временно использует два дополнительных адреса в стеке, баланс после
;   #9270 восстановлен
; -----------------------------------------
MakeSteps       INC IY
                INC IY
                DEC A
                JR NZ, MakeSteps                                                ; переход, если в таблице направлений ещё не достигнута выбранная запись

                LD HL, ClassifySteps
                PUSH HL
                LD L, (IY + FWord.Low)
                LD H, (IY + FWord.High)
                PUSH HL
                LD HL, State.StepCandidates
                LD E, (IX + FMapSite.X)
                LD D, (IX + FMapSite.Y)
                LD B, #03
.StoreStep      LD (HL), #00
                INC HL
                LD (HL), E
                INC HL
                LD (HL), D
                INC HL
                DJNZ .StoreStep

                LD IY, State.StepCandidates
                RET
