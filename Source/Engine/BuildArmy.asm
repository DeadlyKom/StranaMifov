
; -----------------------------------------
; преобразовать состав армии в пять боевых записей по 18 байт
; целевые записи IY сначала очищаются на 90 байт, исходные записи IX имеют шаг 3, пятибайтное
; количество записывается в+2..6, координаты из HL в+10/+11, характеристики из описателя #8036
; в+7,+8,+9
; In:
;   HL таблица координат в банке 3, BC, B максимум отрядов и C банк источника, AF, A
;   режим/местность, IX трёхбайтные записи, IY90 байт назначения в банке 3
; Out:
;   пять боевых записей очищены, до B непустых отрядов преобразованы в 18 байтный формат,
;   HL/IX/IY продвинуты по обработанным записям, прежний банк восстановлен, F исходного входа
;   восстановлен
; Corrupt:
;   HL, DE, BC, A, IX, IY, операнды #88F0/#88F9, альтернативные HL', DE', BC', AF' могут
;   изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
BuildArmy       LD (Engine.BuildArmy.BuildMode), A
                LD A, (State.Bank)
                PUSH AF
                LD A, C
                LD (Engine.BuildArmy.SourcePage), A
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                PUSH HL
                PUSH BC
                PUSH IY
                POP HL
                LD E, L
                LD D, H
                INC DE
                LD (HL), #00
                LD BC, #0059
                LDIR
                POP BC
                POP HL

                ; преобразование трёхбайтного стратегического отряда в восемнадцатибайтную боевую запись
.UnitLoop       LD A, (Engine.BuildArmy.SourcePage)
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD A, (IX + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                OR A
                JP Z, .RestorePage                                              ; переход, если достигнут конец стратегической армии

                PUSH BC
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD A, (HL)
                LD (IY + FBattleUnit.X), A                                      ; +#0A, колонка 0..7
                INC HL
                LD A, (HL)
                LD (IY + FBattleUnit.Y), A                                      ; +#0B, строка 0..4
                INC HL
                PUSH HL
                LD A, (Engine.BuildArmy.SourcePage)
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD C, (IX + FTroop.Count.Low)                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD B, (IX + FTroop.Count.High)                                  ; +#02, старший байт, беззнаковая численность little-endian
                LD A, (IX + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                PUSH AF
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                LD (IY + FBattleUnit.UnitID), A                                 ; +#00, ID типа, 0 завершает плотный список
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                PUSH IY
                POP HL
                INC HL
                INC HL
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                LD (IY + FBattleUnit.InitialCount.Low), C                       ; +#0E, младший байт, исходное целое количество, ограничивает восстановление
                LD (IY + FBattleUnit.InitialCount.High), B                      ; +#0F, старший байт, исходное целое количество, ограничивает восстановление
                PUSH IX
                CALL UnitDesc                                                   ; получить описатель типа отряда
                LD B, #00
                LD A, (Engine.BuildArmy.BuildMode)
                LD C, A
                LD HL, Engine.BuildArmy.BuildMode
                ADD HL, BC
                LD A, (IX + FSoldier.Actions)                                   ; +#0F, исходное число действий на раунд
                SUB (HL)
                JR Z, .MinimumActions                                           ; переход, если поправка уменьшила число действий до нуля

                JR NC, .StoreActions                                            ; переход, если после поправки осталось неотрицательное число действий

                ; боевой отряд получает не менее одного действия
.MinimumActions LD A, #01
.StoreActions   LD (IY + FBattleUnit.BaseActions), A                            ; +#07, число действий в начале раунда
                LD A, (IX + FSoldier.ActionStock)                               ; +#10, запас расходуемого дальнего действия
                LD (IY + FBattleUnit.ActionStock), A                            ; +#08, остаток расходуемого дальнего действия
                LD A, (IX + FSoldier.MoveFlags)                                 ; +#0D, первый байт способностей, младшие 3 бита копируются в боевые флаги
                POP IX
                AND #07
                LD C, A
                LD A, (Engine.BuildArmy.BuildMode)
                CP #03
                JR NZ, .StoreFlags                                              ; переход, если выбран не специальный режим построения армии

                RES UNIT_SHOT_BIT, C                                            ; обычная дальняя атака, младший байт способностей копируется в боевую запись
                RES UNIT_FLY_BIT, C                                             ; способность полёта, младший байт способностей копируется в боевую запись

                ; перенос способностей в боевые флаги и переход к следующей записи
.StoreFlags     LD (IY + FBattleUnit.Flags), C                                  ; +#09, способности и временные отметки раунда, цели и контроля
                LD BC, #0003
                ADD IX, BC
                LD BC, #0012
                ADD IY, BC
                POP HL
                POP BC
                DEC B
                JP NZ, .UnitLoop                                                ; переход, если остались стратегические отряды для преобразования

.RestorePage    POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                RET

.BuildMode      EQU $                                                           ; режим преобразования стратегической армии в боевую
                DB #00, #00, #02, #00, #01, #03, #00, #00
.SourcePage     EQU $+1                                                         ; банк исходной стратегической армии
                DB #00, #00
