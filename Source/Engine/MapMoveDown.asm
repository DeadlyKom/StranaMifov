
; -----------------------------------------
; увеличить строку героя в пределах рабочей части карты
; при B=#61 переход #8BE4, иначе INC B, верхняя допустимая строка 97
; In:
;   BC координаты героя, предполагается вызов из обработки перемещения
; Out:
;   если B!=97, B изменён на+1 и обычный RET, для горизонтального шага обновлены биты 3/4 #6A33.
;   На границе 7HALT с бордюром, POP HL отбрасывает адрес возврата и JP #8A2C
; Corrupt:
;   AF и изменяемый байт BC в обычной ветви, HL, DE, IX, IY сохранены только до граничного
;   перехода, после перехода действует контракт #8A2C
; -----------------------------------------
MapMoveDown     LD A, B
                CP #61
                JR Z, MapMoveUp.FlashBorder                                     ; переход, если герой достиг нижней допустимой строки карты

                INC B
                RET
