
; -----------------------------------------
; прочитать байт клетки текущей карты
; сохраняет банк, выбирает банк 10, вызывает #80B4, возвращает A=(HL), банк восстановлен
; In:
;   BC, B строка и C столбец текущей стратегической карты
; Out:
;   AF, A байт карты, HL, DE, BC, IX, IY сохранены, банк восстановлен
; Corrupt:
;   AF, IFF после вызова разрешён, собственные регистры кроме AF сохранены
; -----------------------------------------
ReadMapCell     PUSH HL
                PUSH DE
                PUSH BC
                LD A, (State.Bank)
                PUSH AF
                CALL SelectMapBank                                              ; выбрать логический банк 10 с текущей картой
                CALL MapCellAddress                                             ; вычислить адрес клетки карты
                LD B, (HL)
                POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD A, B
                POP BC
                POP DE
                POP HL
                RET
