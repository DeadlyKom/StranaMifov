
; -----------------------------------------
; найти следующий семибайтный маркер overlay
; сканирует память по байту, сравнивая с #6CC1, HL возвращает адрес сразу после маркера, верхней
; границы поиска нет
; In:
;   HL начало поиска, доступный завершающий маркер overlay
; Out:
;   HL сразу после маркера, DE=#6CC8, BC, B=0 и C сохранён, A последний байт маркера
; Corrupt:
;   HL, DE, BC, AF, IX и IY не меняются
; -----------------------------------------
FindOverlayEnd  LD DE, Engine.FindOverlayEnd.EndMarker                          ; семибайтный маркер overlay в конце каждого оверлея
                LD B, #07

                ; сопоставление последовательности байтов с маркером конца оверлея
.MatchMarker    LD A, (DE)
                CP (HL)
                JR NZ, .NextByte                                                ; переход, если очередной байт не совпал с маркером конца оверлея

                INC HL
                INC DE
                DJNZ .MatchMarker

                RET

.NextByte       INC HL
                JR FindOverlayEnd

.EndMarker      EQU $                                                           ; семибайтный маркер overlay в конце каждого оверлея
                DB #6F, #76, #65, #72, #6C, #61, #79
