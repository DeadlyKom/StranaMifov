
; -----------------------------------------
; загрузить именованный файл через TR-DOS
; HL адрес девятибайтного имени с типом, DE адрес загрузки, имя переносится в #5CDD, #5D10=0,
; HL=адрес назначения, C=#0E, A=3, переход на #6D15
; In:
;   HL девятибайтное имя с типом, DE адрес загрузки
; Out:
;   результат сервиса TR-DOS #0E, IM 2 и EI восстановлены
; Corrupt:
;   HL, DE, BC, AF и регистры, изменяемые TR-DOS, точный контракт сервиса здесь не установлен
; -----------------------------------------
LoadFile        PUSH DE
                LD DE, TrDos.Descriptor                                         ; рабочее имя файла в описателе TR-DOS
                LD BC, #0009
                LDIR
                XOR A
                LD (TrDos.Error), A
                POP HL
                LD C, #0E
                LD A, #03
                JP CallTrdos

.BootFile       EQU $                                                           ; девятибайтное имя KB.co для перезапуска начального модуля
                DB #4B, #42, #2E, #63, #6F, #20, #20, #20
.GameDiskText   EQU $+1                                                         ; сообщение с требованием вставить диск с игрой
                DB #43, #82, #E1, #E2, #A0, #A2, #EC, #E2
                DB #A5, #20, #A4, #A8, #E1, #AA, #A5, #E2
                DB #E3, #20, #E1, #20, #A8, #A3, #E0, #AE
                DB #A9, #20, #2E, #2E, #2E, #2E, #00, #83
                DB #07, #32, #14, #6D, #AE, #00, #23, #0B
                DB #78, #B1, #20, #E1, #C9, #00, #00, #00
