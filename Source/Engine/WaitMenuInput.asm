
; -----------------------------------------
; дождаться клавиши либо Kempston для меню
; ROM #028E возвращает E, #FF означает отсутствие клавиши, затем порт #1F, fire возвращает #27,
; направления ищутся в таблице #793B, при неизвестном ненулевом значении поиск не ограничен
; In:
;   клавиатура и Kempston #1F
; Out:
;   AF, A код клавиши либо направления, ожидание продолжается до ненулевого ввода
; Corrupt:
;   HL, DE, BC, AF, IX/IY собственный код не изменяет, их сохранение ROM #028E отдельно не
;   проверено
; -----------------------------------------
WaitMenuInput   CALL Rom.KeyScan                                                ; сканирование матрицы клавиатуры и возврат E=#FF при отсутствии клавиши
                LD A, E
                CP #FF
                RET NZ                                                          ; выход, если ROM вернул нажатую клавишу

                IN A, (#1F)
                OR A
                JR Z, WaitMenuInput                                             ; переход, если Kempston не дал команды

                BIT JOY_FIRE_BIT, A                                             ; кнопка огня в прочитанном байте Kempston
                JR Z, .SelectKeyTable                                           ; переход, если кнопка огня Kempston не нажата

                LD A, #27
                RET

.SelectKeyTable LD HL, Engine.WaitMenuInput.KempstonPairs - 1                   ; восемь пар Kempston-код и команда меню
.FindKey        INC HL
                CP (HL)
                INC HL
                JR NZ, .FindKey                                                 ; переход, если код ещё не совпал с записью таблицы джойстика

                LD A, (HL)
                RET

.KempstonPairs  EQU $                                                           ; восемь пар Kempston-код и команда меню
                DB #08, #1B, #09, #23, #01, #22, #05, #21
                DB #04, #19, #06, #11, #02, #12, #0A, #13
.HighlightRect  EQU $                                                           ; адрес ранее подсвеченного прямоугольника меню
                DB #00, #00, #00, #00, #00
