
; -----------------------------------------
; уменьшить 16 битное поле героя #6A02 с насыщением 0
; ROM формула использует число 2 и пятибайтные поля #656C, #6567, токены #05, #04, #27, результат
; BC вычитается из #6A02, при заёме записывается 0
; In:
;   пятибайтные #6567/#656C и поле #6A02
; Out:
;   HL новое значение #6A02=max(0, старое-floor(2*#656C/#6567)), BC вычисленное уменьшение
; Corrupt:
;   HL, DE, BC, AF, IX/IY зависят от прямых ROM токенов, альтернативные HL', DE', BC', AF' могут
;   изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
LoseLeadership  LD A, #02
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                LD HL, State.FloatB
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD HL, State.FloatA
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 89F2
                DB #04                                                          ; multiply, умножение, 89F3
                DB #27                                                          ; int, округление вниз, 89F4
                DB #38                                                          ; end-calc, возврат в Z80, 89F5
                CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                LD HL, (State.Leadership)
                OR A
                SBC HL, BC
                JR NC, .StoreLimit                                              ; переход, если вычитание штрафа не уменьшило лидерство ниже нуля

                LD HL, #0000
.StoreLimit     LD (State.Leadership), HL
                RET
