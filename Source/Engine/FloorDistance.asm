
; -----------------------------------------
; вычислить целую часть евклидова расстояния
; BC и DE координаты, абсолютные 8 битные разности возводятся #801F в квадрат,16 битная сумма
; передаётся калькулятору, токены 28,27 означают квадратный корень и округление вниз, #6D76
; возвращает BC, для карты 161 на 100 сумма не переполняет 16 бит, вне этого диапазона сумма
; усечётся
; In:
;   DE координаты цели, BC координаты начала
; Out:
;   BC=floor(sqrt(dx*dx+dy*dy)), HL, DE, AF, IX, IY сохранены
; Corrupt:
;   BC и альтернативные регистры калькулятора ROM, сумма квадратов вычисляется с разрядностью 16
;   бит
; -----------------------------------------
FloorDistance   PUSH IX
                PUSH IY
                PUSH HL
                PUSH DE
                PUSH AF
                LD A, C
                SUB E
                JR NC, .SquareDeltaX                                            ; переход, если разность горизонтальных координат неотрицательна

                NEG
.SquareDeltaX   CALL SquareByte                                                 ; возвести беззнаковый байт A в квадрат
                LD A, B
                SUB D
                JR NC, .SquareDeltaY                                            ; переход, если разность вертикальных координат неотрицательна

                NEG
.SquareDeltaY   EX DE, HL
                CALL SquareByte                                                 ; возвести беззнаковый байт A в квадрат
                ADD HL, DE
                LD C, L
                LD B, H
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #28                                                          ; sqr, квадратный корень, 8011
                DB #27                                                          ; int, округление вниз, 8012
                DB #38                                                          ; end-calc, возврат в Z80, 8013
                CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                POP AF
                POP DE
                POP HL
                POP IY
                POP IX
                RET
