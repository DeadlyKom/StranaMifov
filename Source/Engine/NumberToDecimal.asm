
; -----------------------------------------
; преобразовать число калькулятора в десятичные цифры
; DE буфер назначения, использует пятьбайтное поле #72DE и десятьбайтный массив цифр #72E3, через
; калькулятор последовательно получает десять разрядов, подавляет ведущие нули, записывает
; ASCII0..9 без нулевого терминатора, DE после последней цифры
; In:
;   DE буфер назначения, число на стеке калькулятора ROM
; Out:
;   DE сразу после записанных десятичных цифр, нулевой терминатор не добавляется, IX сохранён
; Corrupt:
;   HL, DE, BC, AF, рабочие поля #72DE..#72EC, альтернативные HL', DE', BC', AF' зависят от
;   внутреннего соглашения ROM и отдельно не проверены, IY не защищён собственным PUSH, зависит
;   от калькулятора ROM
; -----------------------------------------
NumberToDecimal PUSH IX
                PUSH DE
                LD HL, Engine.NumberToDecimal.Digits                            ; десять промежуточных десятичных разрядов
                LD DE, Engine.NumberToDecimal.Digits + 1                        ; следующий байт массива при его очистке
                LD (HL), #00
                LD BC, #0009
                LDIR
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #27                                                          ; int, округление вниз, 7238
                DB #38                                                          ; end-calc, возврат в Z80, 7239
                LD BC, #2710
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD BC, #2710
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD BC, #000A
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, 724D
                DB #04                                                          ; multiply, умножение, 724E
                DB #38                                                          ; end-calc, возврат в Z80, 724F
                LD HL, Engine.NumberToDecimal.FloatScale                        ; пятибайтный десятичный делитель при разборе числа
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                LD HL, Engine.NumberToDecimal.Digits                            ; десять промежуточных десятичных разрядов
                LD B, #0A

                ; преобразование числа калькулятора в десятичные цифры
.ConvertNumber  PUSH BC
                PUSH HL
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #31                                                          ; duplicate, дублирование вершины, 725E
                DB #38                                                          ; end-calc, возврат в Z80, 725F
                LD HL, Engine.NumberToDecimal.FloatScale                        ; пятибайтный десятичный делитель при разборе числа
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 7267
                DB #27                                                          ; int, округление вниз, 7268
                DB #31                                                          ; duplicate, дублирование вершины, 7269
                DB #38                                                          ; end-calc, возврат в Z80, 726A
                CALL PopA                                                       ; извлечь байтовое целое из калькулятора ROM
                POP HL
                LD (HL), A
                INC HL
                PUSH HL
                LD HL, Engine.NumberToDecimal.FloatScale                        ; пятибайтный десятичный делитель при разборе числа
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, 7279
                DB #03                                                          ; subtract, вычитание, 727A
                DB #38                                                          ; end-calc, возврат в Z80, 727B
                LD HL, Engine.NumberToDecimal.FloatScale                        ; пятибайтный десятичный делитель при разборе числа
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD BC, #000A
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 7289
                DB #38                                                          ; end-calc, возврат в Z80, 728A
                LD HL, Engine.NumberToDecimal.FloatScale                        ; пятибайтный десятичный делитель при разборе числа
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                POP HL
                POP BC
                DJNZ .ConvertNumber

                CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                LD HL, Engine.NumberToDecimal.Digits - 1                        ; база перед массивом десяти цифр, цикл пропуска нулей сначала INC HL
                LD B, #0A
                XOR A

                ; пропуск ведущих нулей перед записью печатного текста
.SkipZeroes     INC HL
                CP (HL)
                JR NZ, .StartCopy                                               ; переход, если найдена первая значащая десятичная цифра

                DJNZ .SkipZeroes

                INC B
.StartCopy      POP DE
.CopyDigits     LD A, (HL)
                ADD A, #30
                LD (DE), A
                INC HL
                INC DE
                DJNZ .CopyDigits

                POP IX
                RET

.PrintPos       EQU $                                                           ; текущая позиция вывода сообщения
.PrintRow       EQU $+1                                                         ; текущая строка вывода сообщения
.LineBuffer     EQU $+2                                                         ; буфер распакованной строки сообщения
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
.FloatScale     EQU $+5                                                         ; пятибайтный десятичный делитель при разборе числа
                DB #00, #00, #00, #00, #00, #00, #00, #00
.Digits         EQU $+2                                                         ; десять промежуточных десятичных разрядов
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00
