
; -----------------------------------------
; увеличить 16 битное поле героя #6A02 с насыщением #FFFF
; ROM формула использует число 2 и поля #6567, #656C в обратном порядке к #89E0, токены #05, #04,
; #27, результат BC прибавляется, при переносе записывается #FFFF
; In:
;   пятибайтные #6567/#656C и поле #6A02
; Out:
;   HL новое значение #6A02=min(65535, старое+floor(2*#6567/#656C)), BC вычисленное увеличение
; Corrupt:
;   HL, DE, BC, AF, IX/IY зависят от прямых ROM токенов, альтернативные HL', DE', BC', AF' могут
;   изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
GainLeadership  LD A, #02
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                LD HL, State.FloatA
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                LD HL, State.FloatB
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 8A1A
                DB #04                                                          ; multiply, умножение, 8A1B
                DB #27                                                          ; int, округление вниз, 8A1C
                DB #38                                                          ; end-calc, возврат в Z80, 8A1D
                CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                LD HL, (State.Leadership)
                ADD HL, BC
                JR NC, LoseLeadership.StoreLimit                                ; переход, если увеличение лидерства не превысило шестнадцатибитный диапазон

                LD HL, #FFFF
                JR LoseLeadership.StoreLimit
