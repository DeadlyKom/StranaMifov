
; -----------------------------------------
; сохранить вершину калькулятора в пятибайтное поле по HL
; ROM #2BF1 возвращает A, E, D, C, B, они записываются последовательно, HL увеличен на 5, DE, BC,
; AF сохранены
; In:
;   HL адрес назначения пятибайтного числа, вершина стека калькулятора ROM
; Out:
;   HL исходный адрес+5, число записано последовательно A, E, D, C, B, DE, BC, AF сохранены
; Corrupt:
;   HL, альтернативные HL', DE', BC', AF' зависят от внутреннего соглашения ROM и отдельно не
;   проверены, IX/IY здесь явно не сохраняются, соглашение ROM #2BF1 отдельно не проверено
; -----------------------------------------
StoreFloat5     PUSH DE
                PUSH BC
                PUSH AF
                PUSH HL
                CALL Rom.PopFloat                                               ; снятие пятибайтного числа калькулятора в A,E,D,C,B
                POP HL
                LD (HL), A
                INC HL
                LD (HL), E
                INC HL
                LD (HL), D
                INC HL
                LD (HL), C
                INC HL
                LD (HL), B
                INC HL
                POP AF
                POP BC
                POP DE
                RET
