
; -----------------------------------------
; сложить произведения количества отрядов на поле силы типа
; стек калькулятора получает 0, для каждой трёхбайтной записи берётся беззнаковое 16 битное
; количество и 16 битное поле 22/23 описателя SOLDIERS, токен 04 умножает,0F прибавляет, нулевой
; ID завершает раньше B, #9193 использует результат для сравнения сил армий, поле силы названо по
; проверенному потребителю
; In:
;   HL список трёхбайтных записей армии, BC, B максимум записей
; Out:
;   HL после обработанных записей либо у первого нулевого ID, сумма количества*поле 22/23 на
;   стеке калькулятора, выбранный до входа банк восстановлен
; Corrupt:
;   HL, DE, BC, AF, IX и альтернативные регистры калькулятора не сохраняются полностью, IY
;   зависит от ROM
; -----------------------------------------
SumArmyPower    LD A, (State.Bank)
                LD (Engine.SumArmyPower.SavedPage), A
                XOR A
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
.UnitLoop       LD A, (Engine.SumArmyPower.SavedPage)
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD A, (HL)
                OR A
                RET Z                                                           ; выход, если достигнут конец суммируемой армии

                PUSH BC
                INC HL
                LD C, (HL)
                INC HL
                LD B, (HL)
                INC HL
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                CALL UnitDesc                                                   ; получить описатель типа отряда
                LD C, (IX + FSoldier.UnitValue.Low)
                LD B, (IX + FSoldier.UnitValue.High)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                PUSH HL
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, 7A41
                DB #0F                                                          ; addition, сложение, 7A42
                DB #38                                                          ; end-calc, возврат в Z80, 7A43
                POP HL
                POP BC
                DJNZ .UnitLoop

.SavedPage      EQU $+1                                                         ; сохранённый логический банк при подсчёте силы
                LD A, #00
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                RET
