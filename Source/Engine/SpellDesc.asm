
; -----------------------------------------
; получить описатель одного из десяти заклинаний
; банк 3, IX=#CE58+23*A, ID1 соответствует #CE6F, имя 20 байт и 0, стоимость магической силы
; в+21/+22, бой #D993 читает эту стоимость и передаёт #DB75 для списания, названия Заморозка,
; Ослепление, Шаровая молния и другие
; In:
;   AF, A номер записи начиная с 1, нулевой индекс недопустим
; Out:
;   IX адрес записи, банк 3 выбран и прерывания разрешены, HL, DE, BC, AF, IY сохранены
; Corrupt:
;   IX, состояние банка и IFF, остальные регистры не меняются
; -----------------------------------------
SpellDesc       PUSH DE
                PUSH BC
                PUSH AF
                LD B, A
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD DE, #0017
                LD IX, Data.Battle.Freeze - FSpell                              ; смещённая база заклинаний, ID1 даёт Freeze
.SpellLoop      ADD IX, DE
                DJNZ .SpellLoop

                POP AF
                POP BC
                POP DE
                RET
