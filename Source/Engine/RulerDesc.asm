
; -----------------------------------------
; получить описатель одного из пятнадцати вражеских правителей
; банк 3, IX=#CCAF+28*A, ID1 соответствует #CCCB, записи содержат 21 байт имени и 0, затем 16
; битные текущую магическую силу+22, максимум+24 и восстановление+26, имена и вывод владельца
; подтверждены оверлеями 1/2/17/21, поля пополняются #A082
; In:
;   AF, A номер записи начиная с 1, нулевой индекс недопустим
; Out:
;   IX адрес записи, банк 3 выбран и прерывания разрешены, HL, DE, BC, AF, IY сохранены
; Corrupt:
;   IX, состояние банка и IFF, остальные регистры не меняются
; -----------------------------------------
RulerDesc       PUSH DE
                PUSH BC
                PUSH AF
                LD B, A
                LD A, #03
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD DE, #001C
                LD IX, Data.Battle.Ruler01 - FRuler                             ; смещённая база правителей, ID1 даёт Ruler01
.RulerLoop      ADD IX, DE
                DJNZ .RulerLoop

                POP AF
                POP BC
                POP DE
                RET
