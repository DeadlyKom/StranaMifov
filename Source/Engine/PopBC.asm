
; -----------------------------------------
; извлечь результат калькулятора ROM в BC
; вызов ROM #2DA2, остальные явно сохраняемые регистры восстановлены
; In:
;   верхнее число стека калькулятора ROM
; Out:
;   BC преобразованное целое, HL, DE, AF, IX, IY сохранены
; Corrupt:
;   BC, альтернативные HL', DE', BC', AF' зависят от внутреннего соглашения ROM и отдельно не
;   проверены, правила переполнения и округления самого ROM отдельно не доказаны
; -----------------------------------------
PopBC           PUSH HL
                PUSH DE
                PUSH AF
                PUSH IX
                PUSH IY
                CALL Rom.PopBC                                                  ; преобразование вершины калькулятора в целое BC
                POP IY
                POP IX
                POP AF
                POP DE
                POP HL
                RET
