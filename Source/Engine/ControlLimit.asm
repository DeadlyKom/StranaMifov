
; -----------------------------------------
; рассчитать численный предел типа отряда из поля героя и таблицы
; BC=#6A02 передаётся ROM, байт по #6AD3+A второй операнд, последовательность калькулятора #05,
; #27, #38, #6D76 возвращает BC, остальные сохранённые регистры восстановлены
; In:
;   AF, A ID типа отряда
; Out:
;   BC=floor(word(#6A02)/byte(#6AD3+A)), HL, DE, AF, IX, IY сохранены
; Corrupt:
;   BC и альтернативные регистры калькулятора ROM, нулевой делитель проверкой не защищён
; -----------------------------------------
ControlLimit    PUSH HL
                PUSH DE
                PUSH AF
                PUSH IY
                PUSH IX
                LD BC, (State.Leadership)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD HL, State.ControlIndex
                LD B, #00
                LD C, A
                ADD HL, BC
                LD A, (HL)
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 8704
                DB #27                                                          ; int, округление вниз, 8705
                DB #38                                                          ; end-calc, возврат в Z80, 8706
                CALL PopBC                                                      ; извлечь результат калькулятора ROM в BC
                POP IX
                POP IY
                POP AF
                POP DE
                POP HL
                RET
