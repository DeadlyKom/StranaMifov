
; -----------------------------------------
; передать стоимость отряда на стек калькулятора
; IY трёхбайтная запись армии, по ID читается 16 битное поле 24/25 описателя SOLDIERS, умножается
; на количество+1/+2 токеном 04, токен 31 дублирует результат, регистры восстановлены
; In:
;   IY трёхбайтная запись ID/количество
; Out:
;   на стек калькулятора добавлены две копии произведения количества на поле 24/25 описателя,
;   HL, DE, BC, AF, IX, IY сохранены, банк 3 остаётся выбранным
; Corrupt:
;   HL, DE, BC, AF, IX, IY сохранены, альтернативные HL', DE', BC', AF' могут изменяться
;   вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
StackTroopCost  PUSH IY
                PUSH IX
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                LD A, (IY + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                CALL UnitDesc                                                   ; получить описатель типа отряда
                LD C, (IX + FSoldier.Upkeep.Low)
                LD B, (IX + FSoldier.Upkeep.High)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD C, (IY + FTroop.Count.Low)                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD B, (IY + FTroop.Count.High)                                  ; +#02, старший байт, беззнаковая численность little-endian
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #04                                                          ; multiply, умножение, 9E99
                DB #31                                                          ; duplicate, дублирование вершины, 9E9A
                DB #38                                                          ; end-calc, возврат в Z80, 9E9B
                POP AF
                POP BC
                POP DE
                POP HL
                POP IX
                POP IY
                RET
