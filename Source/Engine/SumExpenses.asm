
; -----------------------------------------
; сложить отмеченные статьи расходов
; семь записей по 6 байт от #9C7F, бит 7 первого байта включает следующее пятибайтное число в
; сумму, на стеке сначала 0, токен 0F сложение, результат сохраняется в #9C6B
; In:
;   семь шестибайтных записей расходов #9C7F с флагами бит 7
; Out:
;   пятибайтная сумма отмеченных записей записана #9C6B..#9C6F, временно добавленная сумма снята
;   со стека калькулятора
; Corrupt:
;   HL, DE, BC, AF, IX/IY зависят от ROM #2ABB/#2BF1, альтернативные HL', DE', BC', AF' могут
;   изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
SumExpenses     XOR A
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                LD HL, Engine.TickTime.ExpenseList
                LD B, #07
.ExpenseLoop    BIT EXP_PAY_BIT, (HL)                                           ; статья выбрана для оплаты и включается в SumExpenses
                JR Z, .NextExpense                                              ; переход, если статья расходов не выбрана для оплаты

                PUSH BC
                PUSH HL
                INC HL
                CALL StackFloat5                                                ; передать пятибайтное число по HL на стек калькулятора
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #0F                                                          ; addition, сложение, 9EB9
                DB #38                                                          ; end-calc, возврат в Z80, 9EBA
                POP HL
                POP BC
.NextExpense    LD DE, #0006
                ADD HL, DE
                DJNZ .ExpenseLoop

                LD HL, Engine.TickTime.PaymentTotal                             ; сумма отмеченных для оплаты недельных расходов
                CALL StoreFloat5                                                ; сохранить вершину калькулятора в пятибайтное поле по HL
                RET
