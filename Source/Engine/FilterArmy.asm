
; -----------------------------------------
; отфильтровать армию по маске местности и обновить записи
; L=0 даёт обычный RET, иначе маска патчится в AND #8C5F/#8C81, если #8CD1 нашёл объект в текущей
; клетке, несовместимые по флагам E #7AEF ID армии обнуляются и список уплотняется, если объекта
; нет, первая несовместимая запись вызывает диалог «Мы туда не пойдём!», затем POP HL отбрасывает
; адрес возврата, обновляется вид #82D5 и управление переходит JP #8A2C, эта ветвь не возвращается
; вызывающей процедуре
; In:
;   HL, L маска допустимых флагов отрядов, состояние армии/клетки героя
; Out:
;   при L=0 обычный RET, при объекте в клетке неподходящие ID обнулены и армия уплотнена. Без
;   объекта неподходящий отряд вызывает сообщение и нелокальный переход в #8A2C
; Corrupt:
;   HL, DE, BC, AF, IX, IY, армия и операнды маски, ветвь запрета удаляет одно слово возврата из
;   стека
; -----------------------------------------
FilterArmy      LD A, L
                OR A
                RET Z                                                           ; выход, если маска ограничений передвижения не задана

                LD (Engine.FilterArmy.MovementMask), A
                LD (Engine.FilterArmy.ObjectMask), A
                LD BC, (State.Position)
                LD (State.ObjectCell), BC
                CALL FindMapObject                                              ; определить тип объекта в координатах #8D29
                LD A, C
                OR A
                JR Z, .FilterByMove                                             ; переход, если в текущей клетке нет объекта для размещения несовместимых отрядов

                LD HL, State.Army
                LD B, #05

                ; удаление отрядов, несовместимых с выбранной маской передвижения
.CheckUnit      LD A, (HL)
                OR A
                JR Z, .CompactTroops                                            ; переход, если достигнут конец проверяемой армии

                CALL UnitFlags                                                  ; прочитать пару флагов описателя отряда
                LD A, E
.ObjectMask     EQU $+1                                                         ; маска совместимости отрядов с местностью объекта
                AND #00
                JR NZ, .NextUnit                                                ; переход, если отряд совместим с допустимой маской местности

                LD (HL), A
.NextUnit       INC HL
                INC HL
                INC HL
                DJNZ .CheckUnit

.CompactTroops  LD HL, State.Army
                LD B, #05
                CALL CompactArmy                                                ; сжать список трёхбайтных записей армии
                RET

                ; отказ в перемещении, если хотя бы один отряд не проходит проверку маски
.FilterByMove   LD IY, State.Army
                LD B, #05
.UnitLoop       LD A, (IY + FTroop.ID)
                OR A
                RET Z                                                           ; выход, если достигнут конец армии без запрещённого отряда

                CALL UnitFlags                                                  ; прочитать пару флагов описателя отряда
                LD A, E
.MovementMask   EQU $+1                                                         ; маска совместимости отрядов с обычным шагом
                AND #00
                JR NZ, .AdvanceUnit                                             ; переход, если отряд совместим с допустимой маской местности

                CALL ResetViewFlags                                             ; сбросить младшие шесть флагов 48 записей объектов
                LD BC, #0701
                LD DE, #0710
                LD A, #42
                CALL DrawFrame                                                  ; нарисовать рамку окна из восьми одноклеточных элементов
                LD A, (IY + FTroop.ID)
                LD BC, #0202
                CALL SetUnitPicture                                             ; создать четырёхкадровый экранный объект
                LD BC, #0D03
                LD DE, Engine.FilterArmy.RefusalText                            ; сообщение отказа отрядов идти на выбранную местность
                CALL PrintMessage                                               ; разобрать строку сообщения с управляющими кодами
                CALL StartView                                                  ; включить обработку объектов в прерывании
                LD B, #14
                CALL WaitOrInput                                                ; выдержать паузу с досрочным выходом по вводу
                POP HL
                CALL UpdateLocalView                                            ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT
                JP HandleMapInput

.AdvanceUnit    INC IY
                INC IY
                INC IY
                DJNZ .UnitLoop

                RET

.RefusalText    EQU $                                                           ; сообщение отказа отрядов идти на выбранную местность
                DB #8C, #EB, #20, #E2, #E3, #A4, #A0, #20
                DB #AD, #A5, #20, #AF, #AE, #A9, #A4, #A5
                DB #AC, #20, #21, #00
