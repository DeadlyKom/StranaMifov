
; -----------------------------------------
; выполнить оверлей 20 и продолжить подсчётом записей
; A=20, #6C3B, CALL #B200, затем выполнение без RET продолжается в #87A1
; In:
;   BC, C вариант завершения, передаваемый оверлею 20
; Out:
;   обычный путь оверлея 20 перезапускает меню без возврата, если он вернётся, выполнение падает
;   в #87A1 и возвращает BC число собственных активных замков
; Corrupt:
;   HL, DE, BC, AF, IX, IY и системное состояние оверлея 20, возможен безвозвратный переход к
;   загрузчику
; -----------------------------------------
RunOverlay20    LD A, #14
                CALL LoadOverlay                                                ; скопировать выбранный оверлей в #B200
                CALL Overlay.Entry                                              ; выполнение выбранного оверлея после копирования в общую область
