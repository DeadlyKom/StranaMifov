
; -----------------------------------------
; проверить координаты DE относительно ближайшей области героя
; нижние границы #9292/#9293, верхние #9294/#9295, все включены, carry=1 внутри, carry=0 снаружи
; In:
;   DE координаты
; Out:
;   AF, carry=1 внутри включительных границ #9292..#9295, остальные регистры сохранены
; Corrupt:
;   AF
; -----------------------------------------
InNearbyRect    LD A, (State.NearbyMax)
                CP E
                JR C, .OutsideRect                                              ; переход, если объект правее правой границы области близости

                LD A, (State.NearbyMin)
                CP E
                JR Z, .CheckRow                                                 ; переход, если объект находится на левой включённой границе

                JR NC, .OutsideRect                                             ; переход, если объект левее левой границы области близости

.CheckRow       LD A, (State.NearbyMax + FPosition.Y)
                CP D
                JR C, .OutsideRect                                              ; переход, если объект ниже нижней границы области близости

                LD A, (State.NearbyMin + FPosition.Y)
                CP D
                JR Z, .InsideRect                                               ; переход, если объект находится на верхней включённой границе

                JR C, .InsideRect                                               ; переход, если объект ниже верхней границы и остаётся внутри области

.OutsideRect    OR A
                RET

.InsideRect     SCF
                RET
