
; -----------------------------------------
; загрузить и выполнить обработчик своего замка
; A=21, #6C3B переносит модуль, CALL #B200
; In:
;   #867B адрес имени текущего своего замка, армия героя и состояние угрозы
; Out:
;   оверлей 21 выполнен через #B200, результатом служат гарнизон/армия/состояние защиты,
;   фиксированного результата в регистрах нет
; Corrupt:
;   HL, DE, BC, AF, IX, IY и состояния обработчика оверлея 21, альтернативные HL', DE', BC', AF'
;   могут изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
RunOwnCastle    LD A, #15
                CALL LoadOverlay                                                ; скопировать выбранный оверлей в #B200
                CALL Overlay.Entry                                              ; выполнение выбранного оверлея после копирования в общую область
                RET

                DB #00, #00
