
; -----------------------------------------
; уменьшить строку героя в пределах рабочей части карты
; при B=2 переход #8BE4 обрабатывает запрет шага, иначе DEC B, нижняя допустимая строка 2
; In:
;   BC координаты героя, предполагается вызов из обработки перемещения
; Out:
;   если B!=2, B изменён на-1 и обычный RET, для горизонтального шага обновлены биты 3/4 #6A33.
;   На границе 7HALT с бордюром, POP HL отбрасывает адрес возврата и JP #8A2C
; Corrupt:
;   AF и изменяемый байт BC в обычной ветви, HL, DE, IX, IY сохранены только до граничного
;   перехода, после перехода действует контракт #8A2C
; -----------------------------------------
MapMoveUp       LD A, B
                CP #02
                JR Z, .FlashBorder                                              ; переход, если герой достиг верхней допустимой строки карты

                DEC B
                RET

.FlashBorder    LD A, #07
.BorderLoop     OUT (#FE), A
                HALT
                DEC A
                JR NZ, .BorderLoop                                              ; переход, если остались такты пограничной индикации

                OUT (#FE), A
                POP HL
                JP HandleMapInput
