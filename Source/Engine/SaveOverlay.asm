
; -----------------------------------------
; сохранить изменённую рабочую копию оверлея в банк хранения
; обратное направление #6C3B, адреса меняются EX DE, HL перед LDIR, номер берётся из #655E,
; сохраняются самoизменяемые поля рабочего модуля
; In:
;   состояние рабочих таблиц и текущий логический банк
; Out:
;   HL, DE, BC, AF, IX, IY сохранены
; Corrupt:
;   HL, DE, BC, AF, IX, IY сохранены, альтернативные регистры не используются в собственном
;   коде, возможные прерывания работают независимо
; -----------------------------------------
SaveOverlay     PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                LD A, (State.Bank)
                PUSH AF
                CALL OverlayBank                                                ; выбрать банк хранения по номеру оверлея
                LD A, (State.Overlay)
                CP #0E
                JR C, .CopyOverlay                                              ; переход, если выбран оверлей из первой группы банков

                SUB #0D
.CopyOverlay    CALL FindOverlay                                                ; найти исходный адрес и размер оверлея
                LD DE, Overlay.Entry
                EX DE, HL
                LDIR
                POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                POP BC
                POP DE
                POP HL
                RET
