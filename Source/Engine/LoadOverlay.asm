
; -----------------------------------------
; скопировать выбранный оверлей в #B200
; номер A сохраняется в #655E, #6C89 выбирает логический банк 12 либо 13, номер >=14 уменьшается
; на 13, #6C97 возвращает исходный адрес и длину, LDIR копирует блок вместе с конечным маркером
; overlay
; In:
;   AF, A номер оверлея 1..22
; Out:
;   HL, DE, BC, AF, IX, IY сохранены, выбранный до входа банк восстановлен, рабочий модуль
;   размещён по #B200
; Corrupt:
;   HL, DE, BC, AF, IX, IY сохранены, #655E меняется, процедура не сохраняет предыдущее
;   состояние IFF и заканчивает с разрешёнными прерываниями
; -----------------------------------------
LoadOverlay     PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                LD (State.Overlay), A
                LD A, (State.Bank)
                PUSH AF
                CALL OverlayBank                                                ; выбрать банк хранения по номеру оверлея
                LD A, (State.Overlay)
                CP #0E
                JR C, .CopyOverlay                                              ; переход, если выбран оверлей из первой группы банков

                SUB #0D
.CopyOverlay    CALL FindOverlay                                                ; найти исходный адрес и размер оверлея
                LD DE, Overlay.Entry
                LDIR
                POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                POP BC
                POP DE
                POP HL
                RET
