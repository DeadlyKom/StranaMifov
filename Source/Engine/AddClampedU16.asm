
; -----------------------------------------
; прибавить BC к HL с верхней границей DE
; если сложение переносит 16 бит либо сумма>=DE, HL=DE, иначе HL сумма, при сравнении carry от ADD
; равен 0
; In:
;   HL текущее значение, DE верхний предел, BC прибавление
; Out:
;   HL=min(сумма, DE), при переносе 16 биттакже HL=DE, DE, BC, A, IX, IY сохранены
; Corrupt:
;   HL и F
; -----------------------------------------
AddClampedU16   ADD HL, BC
                JR C, .ClampToLimit                                             ; переход, если сумма превысила диапазон шестнадцатибитного числа

                PUSH HL
                SBC HL, DE
                POP HL
                RET C                                                           ; выход, если сумма ещё меньше верхнего предела

.ClampToLimit   LD H, D
                LD L, E
                RET
