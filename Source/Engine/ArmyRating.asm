
; -----------------------------------------
; рассчитать оценку армии из суммы взвешенных количеств
; на стек сначала 100, до 5 записей #6A1E добавляют количество*поле 22/23 описателя/100, затем
; токены 27,31 дают floor результата и его копию, формула floor(100+sum(количество*сила/100)),
; #957C использует показатель в панели с рейтингом
; In:
;   пять трёхбайтных записей #6A1E
; Out:
;   на стек калькулятора положены две копии floor(100+sum(количество*поле 22/23)/100), банк 3
;   остаётся выбранным
; Corrupt:
;   HL, DE, BC, AF, IX, IY не сохраняются как единый контракт, альтернативные HL', DE', BC', AF'
;   могут изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
ArmyRating      LD A, #64
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                LD IY, State.Army
                LD B, #05
.UnitLoop       LD A, (IY + FTroop.ID)
                OR A
                JR Z, .FinishSum                                                ; переход, если достигнут конец плотного списка армии

                PUSH BC
                CALL UnitDesc                                                   ; получить описатель типа отряда
                LD C, (IY + FTroop.Count.Low)
                LD B, (IY + FTroop.Count.High)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD C, (IX + FSoldier.UnitValue.Low)
                LD B, (IX + FSoldier.UnitValue.High)
                CALL StackBC                                                    ; передать целое BC на стек калькулятора ROM
                LD A, #64
                CALL StackA                                                     ; передать байт A на стек калькулятора ROM
                RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #05                                                          ; division, деление, 7ADD
                DB #04                                                          ; multiply, умножение, 7ADE
                DB #0F                                                          ; addition, сложение, 7ADF
                DB #38                                                          ; end-calc, возврат в Z80, 7AE0
                POP BC
                INC IY
                INC IY
                INC IY
                DJNZ .UnitLoop

.FinishSum      RST #28                                                         ; передача вычисления стековому калькулятору ПЗУ, токены следуют ниже
                DB #27                                                          ; int, округление вниз, 7AEB
                DB #31                                                          ; duplicate, дублирование вершины, 7AEC
                DB #38                                                          ; end-calc, возврат в Z80, 7AED
                RET
