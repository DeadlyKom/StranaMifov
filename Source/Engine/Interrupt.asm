
; -----------------------------------------
; обработать маскируемое прерывание IM 2
; сохраняет основные и альтернативные регистры, IX, IY, текущий банк и изменяемые адреса вызова в
; #703B и #708D, увеличивает 16-битный счётчик #6561, при бите 5 #6566 обновляет анимацию символов
; #F2..#F5 через #70D4, при бите 2 вызывает #8104, затем ROM #386E и проверку #6BB0,
; восстанавливает состояние, EI, RETI
; In:
;   маскируемое прерывание IM 2, SP в доступной памяти, #6566 задаёт фоновые работы
; Out:
;   HL, DE, BC, AF, IX, IY сохранены, выбранный до входа банк восстановлен, прерывания разрешены
;   после EI/RETI
; Corrupt:
;   основные и альтернативные HL, DE, BC, AF, IX, IY сохранены, R естественно увеличивается при
;   исполнении, память фоновых процедур и счётчик #6561 изменены
; -----------------------------------------
Interrupt       PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                PUSH IX
                PUSH IY
                EXX
                EX AF, AF'
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                EXX
                EX AF, AF'
                LD A, (State.Bank)
                PUSH AF
                LD HL, (Engine.DrawGlyph.EnterPageCall)
                PUSH HL
                LD HL, (Engine.DrawGlyph.LeavePageCall)
                PUSH HL
                LD HL, (State.FrameCount)
                INC HL
                LD (State.FrameCount), HL
                LD A, (State.ViewFlags)
                BIT TEXT_CURSOR_BIT, A                                          ; разрешает мигающий текстовый курсор в кадровом обработчике
                JR Z, .TickObjects                                              ; переход, если мигание текстового курсора отключено

                LD A, (State.CursorDelay)
                OR A
                JR NZ, .TickCursor                                              ; переход, если не истекла задержка до смены символа курсора

                LD A, (State.CursorGlyph)
                CP #F5
                JR NZ, .NextGlyph                                               ; переход, если текущий символ курсора ещё не последний в цикле

                LD A, #F1

                ; циклическая смена символа текстового курсора
.NextGlyph      INC A
                LD (State.CursorGlyph), A
                LD A, #07
.TickCursor     DEC A
                LD (State.CursorDelay), A
                LD BC, (State.CursorPos)
                LD A, (State.CursorGlyph)
                CALL DrawGlyphDI                                                ; вывести символ из прерывания с сохранением режима DI

                ; обновление графических объектов разрешается общим флагом режима просмотра
.TickObjects    LD A, (State.ViewFlags)
                BIT VIEW_RENDER_BIT, A                                          ; разрешает обновление экранных объектов из прерывания
                CALL NZ, RenderObjects                                          ; вызов процедуры, если обновление экранных объектов разрешено режимом просмотра
                LD IY, System.IYBase                                            ; системная база IY для внешнего вызова
                CALL Rom.ScanKeys128                                            ; внешний системный вход, вызываемый из IM2 после фоновых работ, внутренний контракт не установлен
                CALL CheckCalls                                                 ; проверить неизменность трёх инструкций CALL #6B8D
                POP HL
                LD (Engine.DrawGlyph.LeavePageCall), HL
                POP HL
                LD (Engine.DrawGlyph.EnterPageCall), HL
                POP AF
                CALL State.BankDriver                                           ; переключение логического банка через установленный драйвер памяти
                EXX
                EX AF, AF'
                POP AF
                POP BC
                POP DE
                POP HL
                EXX
                EX AF, AF'
                POP IY
                POP IX
                POP AF
                POP BC
                POP DE
                POP HL
                EI
                RETI

