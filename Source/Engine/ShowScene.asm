
; -----------------------------------------
; показать одну из девяти упакованных сцен BL1/BL2 с восстановлением банка и основных регистров
; #8801..#8839 сохраняет IX, IY, HL, DE, BC, AF, сохраняет номер банка из #5FA0, выбирает банк,
; записывает локальный номер в #C002, очищает экран, вызывает #C000 и восстанавливает банк и
; сохранённые регистры. A=1..5 выбирает банк 14/BL1 и локальный номер A, A=6..9 выбирает банк
; 15/BL2 и локальный номер A-5. RLE-тело идентично HERIMG, #C0FD..#C104 использует только B'/C' из
; альтернативного набора
; In:
;   AF — A=1..9, #5FA0 — исходный логический банк, BL1 по #C000 банка 14 и BL2 по #C000 банка 15
;   ранее загружены
; Out:
;   HL, DE, BC, AF, HL', DE', AF', IX, IY и исходный логический банк восстановлены, выбранная
;   сцена на экране, прерывания разрешены
; Corrupt:
;   BC'. HL, DE, BC, AF, HL', DE', AF', IX, IY сохранены
; Note:
;   #4000..#5AFF, настройки #C002..#C005 выбранного банка, временное переключение банка, EI
;   через #6D2F
; -----------------------------------------
ShowScene       PUSH IX
                PUSH IY
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                LD BC, (Memory.BankAF)
                PUSH BC
                LD B, #0E
                CP #06
                JR C, .SelectScene                                              ; переход, если номер сцены относится к первому ресурсу экранов

                INC B
                SUB #05
.SelectScene    PUSH AF
                LD A, B
                CALL State.BankDriver                                           ; переключение логического банка через установленный драйвер памяти
                POP AF
                LD (Scene.Number), A
                LD BC, #0000
                LD DE, #1820
                XOR A
                CALL ClearRectangle                                             ; обнулить пиксели прямоугольника и заполнить его атрибуты
                CALL Scene.Entry                                                ; вход загруженного BL1/BL2 выбранного банка
                POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                POP BC
                POP DE
                POP HL
                POP IY
                POP IX
                RET
