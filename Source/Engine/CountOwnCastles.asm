
; -----------------------------------------
; подсчитать записи банка 0 по флагу и полю #13
; просматривает 80 записей с шагом 35 от #C000, запись учитывается, если бит 0 флагов сброшен и
; поле+19 равно 0, результат C
; In:
;   80 записей замков банка 0 по 35 байт
; Out:
;   BC, B=0 и C число записей с бит 0 поля 0=0 и владельцем+19 равным 0, HL, DE, AF, IX, IY
;   сохранены, прежний банк восстановлен
; Corrupt:
;   BC, IFF после #6D2F разрешён
; -----------------------------------------
CountOwnCastles PUSH IX
                PUSH DE
                PUSH AF
                LD A, (State.Bank)
                PUSH AF
                XOR A
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD BC, #5000
                LD IX, State.AllCastles                                         ; физические записи замков логического банка0
.CastleLoop     BIT CASTLE_OFF_BIT, (IX + FCastle.Flags)                        ; +#00, бит 0 выключает запись, значения остальных битов отдельно не установлены
                JR NZ, .NextCastle                                              ; переход, если замок исключён из обработки

                LD A, (IX + FCastle.Owner)                                      ; +#13, 0 собственный замок, 1..15 правитель FRuler, #FF особое отсутствие правителя/банды
                OR A
                JR NZ, .NextCastle                                              ; переход, если замок принадлежит другому владельцу

                INC C
.NextCastle     LD DE, #0023
                ADD IX, DE
                DJNZ .CastleLoop

                POP AF
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                POP AF
                POP DE
                POP IX
                RET
