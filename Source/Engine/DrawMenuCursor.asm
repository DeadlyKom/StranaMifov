
; -----------------------------------------
; нарисовать указатель меню с пиксельным смещением
; разница младших 3 бит X прежней позиции #79CA и новой #79CC определяет циклический сдвиг
; пикселей и маски #7980/#79A5, затем 8 строк по 3 байта рисуются #7722
; In:
;   #79CA старая и #79CC новая пиксельная позиция, #79CE пиксели и #79E6 маска указателя
; Out:
;   указатель 8 строк по 3 байта наложен на экран, циклический сдвиг массива согласован с X
; Corrupt:
;   HL, DE, BC, AF, IX, IY, байты указателя/маски и счётчик сдвига #7A16
; -----------------------------------------
DrawMenuCursor  LD DE, (Engine.ShiftCursorL.OldCursor)
                LD BC, (Engine.ShiftCursorL.NewCursor)
                LD A, C
                AND #07
                LD C, A
                LD A, E
                AND #07
                SUB C
                JR Z, .DrawCursor                                               ; переход, если смещение курсора уже соответствует новой пиксельной позиции

                JR C, .ShiftRight                                               ; переход, если новая позиция требует сдвига шаблона вправо

                CALL ShiftCursorL                                               ; циклически сдвинуть влево 24 битные строки указателя и маски
                JR .DrawCursor

.ShiftRight     NEG
                CALL ShiftCursorR                                               ; циклически сдвинуть вправо 24 битные строки указателя и маски

                ; наложение восьми строк трёхбайтного курсора с заранее подготовленным сдвигом
.DrawCursor     LD IX, Engine.head_cursor                                       ; существующий рисунок либо маска курсора меню
                LD IY, Engine.head_cursorMask                                   ; существующий рисунок либо маска курсора меню
                LD BC, (Engine.ShiftCursorL.NewCursor)
                LD A, #08
.PixelRow       PUSH AF
                CALL PixelAddress                                               ; вычислить адрес байта экрана по пиксельным координатам
                CALL CursorMaskByte                                             ; наложить один байт указателя в пределах пиксельной области
                CALL CursorMaskByte                                             ; наложить один байт указателя в пределах пиксельной области
                CALL CursorMaskByte                                             ; наложить один байт указателя в пределах пиксельной области
                POP AF
                INC B
                DEC A
                JR NZ, .PixelRow                                                ; переход, если остались пиксельные строки курсора

                RET
