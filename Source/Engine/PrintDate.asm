
; -----------------------------------------
; разобрать счётчик дней и вывести календарную дату
; поле #6A36, повторные вычитания #0162 и таблица длин периодов #94BB, печать числа дня по
; BC=#010C и названия через #70E3/#94C8, точные имена периодов зависят от встроенной таблицы
; In:
;   word(#6A36) счётчик дней
; Out:
;   календарная дата выведена в верхнюю строку, IY собственным кодом сохранён
; Corrupt:
;   HL, DE, BC, AF, IX, альтернативные HL', DE', BC', AF' могут изменяться вызываемым
;   калькулятором ROM и здесь не сохраняются
; -----------------------------------------
PrintDate       LD BC, #010B
                LD DE, #0102
                LD A, #45
                CALL ClearRectangle                                             ; обнулить пиксели прямоугольника и заполнить его атрибуты
                LD BC, #0111
                LD DE, #0106
                LD A, #45
                CALL ClearRectangle                                             ; обнулить пиксели прямоугольника и заполнить его атрибуты
                LD HL, (State.Days)
                LD DE, #0162
                OR A

                ; выделение полных лет из общего числа дней
.CountYears     INC A
                SBC HL, DE
                JR NC, .CountYears                                              ; переход, если в числе дней ещё содержится полный год

                LD DE, #0163
                ADD HL, DE
                LD IX, Engine.PrintDate.MonthDays - 1                           ; двенадцать длин календарных месяцев
                XOR A
                LD B, #00

                ; выбор месяца по таблице длительностей
.CountMonths    INC A
                INC IX
                LD C, (IX + #00)
                SBC HL, BC
                JR NC, .CountMonths                                             ; переход, если в остатке дней ещё содержится полный месяц

                ADD HL, BC
                INC HL
                PUSH AF
                LD BC, #010C
                CALL PrintU16                                                   ; вывести 16 битное число HL без ведущих нулей
                POP AF
                LD B, A
                LD DE, Engine.PrintU16.MonthNames - 1                           ; нулевая строка перед названиями календарных месяцев
.SkipMonthName  INC DE
                LD A, (DE)
                OR A
                JR NZ, .SkipMonthName                                           ; переход, если не достигнут конец пропускаемого названия месяца

                DJNZ .SkipMonthName

                INC DE
                LD BC, #0117
                CALL PrintZeroText                                              ; вывести строку с нулевым терминатором
                RET

.MonthDays      EQU $                                                           ; двенадцать длин календарных месяцев
                DB #1F, #1C, #1F, #1E, #1F, #1E, #1F, #1F
                DB #1E, #1F, #1E, #1F
