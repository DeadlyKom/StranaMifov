
; -----------------------------------------
; установить бит 7 байта клетки стратегической карты
; BC координаты, сохраняет банк, выбирает карту #80AE, адрес #80B4, SET7,(HL), восстанавливает
; банк
; In:
;   BC координаты клетки
; Out:
;   HL адрес клетки карты банка 10, бит 7 клетки установлен, DE, BC, AF, IX, IY сохранены,
;   прежний банк восстановлен
; Corrupt:
;   HL, IFF после прямого #5FA1 запрещён
; -----------------------------------------
MarkMapCell     LD A, (State.Bank)
                PUSH AF
                CALL SelectMapBank                                              ; выбрать логический банк 10 с текущей картой
                CALL MapCellAddress                                             ; вычислить адрес клетки карты
                SET MAP_BUSY_BIT, (HL)                                          ; клетка стратегической карты занята объектом
                POP AF
                CALL State.BankDriver                                           ; переключение логического банка через установленный драйвер памяти
                RET
