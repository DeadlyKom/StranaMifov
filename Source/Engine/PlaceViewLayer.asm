
; -----------------------------------------
; поставить графический слой только на текущем континенте и в области обзора
; A должен совпасть #6A2D, BC должен быть в #853F..#8542, иначе RET без размещения, вход H/L
; задают банк/смещение данных, IY графический адрес, DE задаёт маску E и флаги D, вычисляет запись
; от #655D со смещениями 160*(B-top+1)+20*(C-left+1), поле 0=(поле 0 AND E) OR D, затем по
; смещению L записывает байт H и двухбайтный графический адрес из входного IY, операнды
; #852D/#8534/#8536 являются рабочими параметрами, IX принудительно=#6A2D
; In:
;   HL, H банк и L смещение поля слоя, DE, D флаги и E маска, BC клетка, AF, A континент, IY
;   графический адрес
; Out:
;   при совпадении континента и видимости обновляет флаги и поле графики экранного объекта,
;   иначе ранний RET, IX=#6A2D
; Corrupt:
;   HL, BC, AF, IX, IY, DE собственный код сохраняет, изменяемые операнды #852D/#8534/#8536
; -----------------------------------------
PlaceViewLayer  LD IX, State.Continent
                CP (IX + #00)
                RET NZ                                                          ; выход, если слой относится к другому континенту

                CALL InLocalView                                                ; проверить попадание координат BC в прямоугольник локального окна
                RET NC                                                          ; выход, если клетка слоя находится вне локального окна

                LD (Engine.PlaceViewLayer.LayerAddress), IY
                LD A, L
                LD (Engine.PlaceViewLayer.LayerOffset), A
                LD A, H
                LD (Engine.PlaceViewLayer.LayerBank), A

                ; перевод мировой клетки в смещение относительно левого верхнего угла окна
                PUSH BC
                POP HL
                LD BC, (Engine.PlaceViewLayer.ViewLeft)
                OR A
                SBC HL, BC
                LD IY, State.ViewObjects - FScreenObject20                      ; база на одну экранную запись перед массивом, строка и колонка передаются с предварительным инкрементом
                INC H
                INC L
                LD BC, #00A0
.ViewRow        ADD IY, BC
                DEC H
                JR NZ, .ViewRow                                                 ; переход, если адрес ещё не достиг строки экранного объекта

                LD BC, #0014
.ViewColumn     ADD IY, BC
                DEC L
                JR NZ, .ViewColumn                                              ; переход, если адрес ещё не достиг колонки экранного объекта

                ; обновление флагов объекта без изменения битов, сохранённых входной маской
                LD A, (IY + FScreenObject20.Flags)                              ; +#00, режим и флаги экранного объекта
                AND E
                OR D
                LD (IY + FScreenObject20.Flags), A                              ; +#00, режим и флаги экранного объекта

                ; выбор поля графического слоя по входному смещению, затем запись банка и адреса
.LayerOffset    EQU $+1                                                         ; операнд смещения выбираемого графического слоя
                LD BC, #0000
                ADD IY, BC
.LayerBank      EQU $+3                                                         ; операнд номера банка выбираемого графического слоя
                LD (IY + FFrameRef.Bank), #00
.LayerAddress   EQU $+1                                                         ; операнд адреса выбираемого графического слоя
                LD HL, #0000
                LD (IY + FFrameRef.Address.Low), L
                LD (IY + FFrameRef.Address.High), H
                RET

.ViewLeft       EQU $                                                           ; столбец левой границы локального окна
.ViewTop        EQU $+1                                                         ; строка верхней границы локального окна
.ViewRight      EQU $+2                                                         ; столбец правой границы локального окна
.ViewBottom     EQU $+3                                                         ; строка нижней границы локального окна
                DB #00, #00, #00, #00
