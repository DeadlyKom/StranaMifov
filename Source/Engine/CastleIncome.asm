
; -----------------------------------------
; рассчитать доход замка с учётом ближайших городов
; IY запись замка, A континент, группа городов #6AF9, базовый доход 100, города учитываются при
; абсолютной разнице координат<=17 пообеимосям, отдельная проверка бита 1 поля+1 и поля 17 может
; исключить город, добавляется 350 либо 450 взависимости от полей 15/16, результат BC
; In:
;   AF, A континент 1..4, IY запись замка, банк 0 с городами уже выбран
; Out:
;   BC доход 100 плюс 350/450 за подходящие ближайшие города, IY сохранён
; Corrupt:
;   HL, DE, BC, AF, IX, накопитель #AE81, альтернативные регистры собственным кодом не
;   используются
; -----------------------------------------
CastleIncome    LD IX, State.TownsIndex
                CALL IndexFourBytes                                             ; сместить IX к четырёхбайтной записи с индексом A
                LD L, (IX + FMapList.Data.Low)
                LD H, (IX + FMapList.Data.High)
                LD B, (IX + FMapList.Count.Low)
                PUSH HL
                POP IX
                LD HL, #0064
                LD (Engine.CastleIncome.Income), HL
                LD A, (IY + FCastle.X)                                          ; +#01, столбец карты
                LD (Engine.CastleIncome.CastleX), A
                LD A, (IY + FCastle.Y)                                          ; +#02, строка карты
                LD (Engine.CastleIncome.CastleY), A

                ; учёт действующих городов в пределах области сбора дохода
.TownLoop       BIT TOWN_OFF_BIT, (IX + FTown.Flags)                            ; +#00, бит 0 выключает запись, бит 1 проверяется при доступности контракта
                JR NZ, .NextTown                                                ; переход, если город исключён из обработки

.CastleX        EQU $+1                                                         ; столбец замка, собирающего доход
                LD A, #00
                SUB (IX + FTown.X)                                              ; +#01, столбец карты
                JR Z, .CheckY                                                   ; переход, если город находится в той же колонке, что и замок

                JR NC, .LimitX                                                  ; переход, если колонка замка не меньше колонки города

                NEG
.LimitX         DEC A
                CP #11
                JR NC, .NextTown                                                ; переход, если город удалён от замка по горизонтали более чем на допустимое расстояние

.CastleY        EQU $+1                                                         ; строка замка, собирающего доход
.CheckY         LD A, #00
                SUB (IX + FTown.Y)                                              ; +#02, строка карты
                JR Z, .CheckGarrison                                            ; переход, если город находится в той же строке, что и замок

                JR NC, .LimitY                                                  ; переход, если строка замка не меньше строки города

                NEG
.LimitY         DEC A
                CP #11
                JR NC, .NextTown                                                ; переход, если город удалён от замка по вертикали более чем на допустимое расстояние

                ; особенность оригинала, проверку гарнизона включает бит 1 координаты X города
                ; отдельный байт Flags здесь не используется
.CheckGarrison  BIT TOWN_XCHECK_BIT, (IX + FTown.X)                             ; +#01, столбец карты
                JR Z, .AddIncome                                                ; переход, если в координате X города сброшен бит 1, проверка гарнизона пропускается

                LD A, (IX + FTown.Army)                                         ; +#11, до трёх отрядов FTroop
                OR A
                JR NZ, .NextTown                                                ; переход, если город занят армией

                ; добавление дохода выбранного города к общему результату
.AddIncome      PUSH BC
                LD BC, #015E
                LD A, (IX + FTown.DockPos.Low)                                  ; +#0F, столбец причала города
                OR (IX + FTown.DockPos.High)                                    ; +#10, строка причала города
                JR Z, .Accumulate                                               ; переход, если у города нет причала, к доходу прибавляется 350

                LD BC, #01C2
.Income         EQU $+1                                                         ; накопленная сумма дохода замка и соседних городов
.Accumulate     LD HL, #0000
                ADD HL, BC
                LD (Engine.CastleIncome.Income), HL
                POP BC
.NextTown       LD DE, #001A
                ADD IX, DE
                DJNZ .TownLoop

                LD BC, (Engine.CastleIncome.Income)
                RET
