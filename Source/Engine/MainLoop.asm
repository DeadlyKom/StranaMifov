
; -----------------------------------------
; обновлять экран и обрабатывать ввод основного режима
; #82D5, HALT, #8A2C, поиск пары в таблице #653A, загрузка оверлея #6C3B и CALL #B200, при
; отсутствии клавиши обработка #9704/#8DDA/#92CB и событий карты через #8CD1/#8D6E
; In:
;   инициализированные модули, #6A2D континент, #6A2E позиция, #6A33 режим, таблицы оверлеев
; Out:
;   обновляет вид, ввод, время и взаимодействия, продолжает главный цикл без обычного RET
; Corrupt:
;   HL, DE, BC, AF, IX, IY и состояния вызываемых модулей, альтернативные HL', DE', BC', AF'
;   могут изменяться вызываемым калькулятором ROM и здесь не сохраняются
; -----------------------------------------
MainLoop        CALL UpdateLocalView                                            ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT

                ; диспетчер команд карты и оверлеев до очередного тика мира
.ReadCommand    CALL HandleMapInput                                             ; получить команду главного режима и обработать движение
                OR A
                JR Z, .TickWorld                                                ; переход, если обработана команда ожидания очередного тика

                LD IX, State.OverlayKeys - FOverlayKey                          ; база перед первым элементом таблицы команд, цикл сначала прибавляет размер пары
                LD B, A
.CommandLoop    INC IX
                INC IX
                LD A, (IX + FOverlayKey.Code)
                OR A
                JR Z, .ReadCommand                                              ; переход, если достигнут конец таблицы команд без совпадения

                CP B
                JR NZ, .CommandLoop                                             ; переход, если код ещё не совпал с искомой командой оверлея

                LD A, (IX + FOverlayKey.Overlay)
                CALL LoadOverlay                                                ; скопировать выбранный оверлей в #B200
                CALL Overlay.Entry                                              ; выполнение выбранного оверлея после копирования в общую область
                JR MainLoop

                ; общий тик времени и перемещений стратегических отрядов
.TickWorld      CALL TickTime                                                   ; продвинуть время игры и выполнить периодические расчёты
                CALL StepArmies                                                 ; сближение, отступление и разделение внешних армий около героя
                CALL StepMapTroops                                              ; перемещение шестибайтовых объектов из континентальной таблицы #6B69
                LD A, (State.MoveFlags)
                AND #03
                CP #02
                JR Z, MainLoop                                                  ; переход, если герой находится в режиме полёта

                CP #01
                JR Z, .FindObject                                               ; переход, если герой находится на корабле

                LD A, (State.ShipPos)
                CP #FF
                JR Z, .FindObject                                               ; переход, если сохранённого корабля на карте нет

                LD BC, (State.ShipPos)
                CALL ReadMapCell                                                ; прочитать байт клетки текущей карты
                BIT MAP_BUSY_BIT, A                                             ; клетка стратегической карты занята объектом
                JR Z, .FindObject                                               ; переход, если клетка корабля не занята другим объектом

                LD BC, #FFFF
                LD (State.ShipPos), BC
.FindObject     LD BC, (State.Position)
                LD (State.ObjectCell), BC
                CALL FindMapObject                                              ; определить тип объекта в координатах #8D29

                ; запуск оверлея взаимодействия по типу найденного объекта
.DispatchObject LD A, C
                OR A
                JR Z, .CheckArmies                                              ; переход, если в клетке нет объекта для вызова оверлея

                LD HL, State.ObjectOverlays
                LD B, #00
                ADD HL, BC
                LD A, (HL)
                CALL LoadOverlay                                                ; скопировать выбранный оверлей в #B200
                CALL Overlay.Entry                                              ; выполнение выбранного оверлея после копирования в общую область
                CALL SaveOverlay                                                ; сохранить изменённую рабочую копию оверлея в банк хранения
                CALL RefreshPanels                                              ; перерисовать верхнюю строку и боковую панель игры

                ; проверка встречи с армией после обработки обычного объекта
.CheckArmies    LD A, #01
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, State.MapArmiesIndex
                LD HL, (State.Position)
                LD DE, #0016
                LD BC, #0101
                CALL FindRecord                                                 ; найти активную запись группы, покрывающую координату HL
                OR A
                JP Z, MainLoop                                                  ; переход, если в клетке героя не найдена стратегическая армия

.StartBattle    LD A, #07
                CALL LoadOverlay                                                ; скопировать выбранный оверлей в #B200
                CALL Overlay.Entry                                              ; выполнение выбранного оверлея после копирования в общую область
                CALL SaveOverlay                                                ; сохранить изменённую рабочую копию оверлея в банк хранения
                CALL RefreshPanels                                              ; перерисовать верхнюю строку и боковую панель игры
                LD BC, (State.Position)
                LD (State.ObjectCell), BC
                CALL FindMapObject                                              ; определить тип объекта в координатах #8D29
                LD A, C
                OR A
                JR NZ, .DispatchObject                                          ; переход, если после перемещения корабля в клетке найден объект

                LD A, #01
                CALL PageEI                                                     ; переключить логический банк и разрешить прерывания
                LD IX, State.MapArmiesIndex
                LD HL, (State.Position)
                LD DE, #0016
                LD BC, #0101
                CALL FindRecord                                                 ; найти активную запись группы, покрывающую координату HL
                OR A
                JP NZ, .StartBattle                                             ; переход, если в клетке героя найдена стратегическая армия

