; исходный файл каталога 48, смещение #2EEE
                module Overlay
                module Land
                org #B200

; -----------------------------------------
; проверка клетки и завершение полёта
; Требует текущий режим 2 в младших двух битах #6A33. Читает клетку под героем по #6A2E. Если бит
; 7 клетки установлен либо младшие 6 бит ненулевые, выходит. Иначе сбрасывает два младших бита
; режима и возвращает наземное перемещение.
; In:
;   текущее состояние героя, армии и объекта в ядре
; Out:
;   состояние обновлено выбранной ветвью либо сохранено при отказе
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; -----------------------------------------
Entry           LD A, (State.MoveFlags)
                AND #03
                CP #02
                RET NZ                                                          ; выход, если герой сейчас не находится в режиме полёта

                LD BC, (State.Position)
                CALL Engine.ReadMapCell                                         ; прочитать байт клетки текущей карты
                BIT MAP_BUSY_BIT, A                                             ; флаг, клетка стратегической карты занята объектом
                RET NZ                                                          ; выход, если клетка посадки занята объектом

                AND #3F
                RET NZ                                                          ; выход, если код местности клетки не допускает посадку

                LD A, (State.MoveFlags)
                AND #FC
                LD (State.MoveFlags), A
                RET

                DB #6F, #76, #65, #72, #6C, #61, #79

                assert $ = #B225
                endmodule
                endmodule
