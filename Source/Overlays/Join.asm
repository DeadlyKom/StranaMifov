; оверлей 06 из OVR1
; исходный файл каталога 48, смещение #2073
                module Overlay
                module Join
                org #B200

; -----------------------------------------
; присоединение встреченного отряда
; До предложения пользователю помечает исходный объект использованным через SET0 его первого байта
; и снимает bit7 с клетки карты. Показывает отряд, ищет пустой либо совпадающий ID среди пяти
; троек #6A1E. Если места нет, выводит сообщение и возвращается, объект при этом уже помечен
; использованным. Проверки управляемости через #86B1/#86EA в оверлее нет. После согласия прямо
; прибавляет 16-битную численность в найденную запись и устанавливает ID, при первом добавлении
; сбрасывает служебные счётчики #7A94. Отказ тоже не отменяет уже поставленную отметку объекта.
; In:
;   текущее состояние героя, армии и объекта в ядре
; Out:
;   объект помечен использованным при любом ответе, после согласия численность добавлена в армию
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; -----------------------------------------
Entry           INC IX
                INC IX
                INC IX
                LD (Entry.SourceTroop), IX
                LD A, (State.MoveFlags)
                SET HERO_HIDE_BIT, A                                            ; флаг, пропустить подготовку изображения героя в локальном окне
                LD (State.MoveFlags), A
                CALL Engine.UpdateLocalView                                     ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT
                LD A, (State.MoveFlags)
                RES HERO_HIDE_BIT, A                                            ; флаг, пропустить подготовку изображения героя в локальном окне
                LD (State.MoveFlags), A
                XOR A
                CALL Engine.PageEI                                              ; переключить логический банк и разрешить прерывания
                LD IX, (Entry.SourceTroop)
                SET TROOP_FREE_BIT, (IX + FMapTroop.Flags - FMapTroop.ID)       ; флаг, шестибайтовая запись войск карты свободна или уже использована
                LD C, (IX + FMapTroop.X - FMapTroop.ID)
                LD B, (IX + FMapTroop.Y - FMapTroop.ID)
                CALL Engine.SelectMapBank                                       ; выбрать логический банк 10 с текущей картой
                CALL Engine.MapCellAddress                                      ; вычислить адрес клетки карты
                RES MAP_BUSY_BIT, (HL)                                          ; флаг, клетка стратегической карты занята объектом
                XOR A
                CALL Engine.PageEI                                              ; переключить логический банк и разрешить прерывания
                CALL Engine.ResetViewFlags                                      ; сбросить младшие шесть флагов 48 записей объектов
                LD BC, #1000
                LD DE, #061E
                LD A, #47
                CALL Engine.DrawFrame                                           ; нарисовать рамку окна из восьми одноклеточных элементов
                LD BC, #1103
                LD A, #01
                LD IY, (Entry.SourceTroop)
                CALL Engine.PrintArmyBrief                                      ; вывести краткий список состава армии
                LD IX, (Entry.SourceTroop)
                LD C, (IX + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                LD IY, State.Army
                LD B, #05

                ; поиск разрешает свободную запись либо отряд того же типа, занять шестую запись
                ; нельзя
.FindArmySlot   LD A, (IY + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                OR A
                JR Z, .JoinPrompt                                               ; переход, если найдена свободная запись армии

                CP C
                JR Z, .JoinPrompt                                               ; переход, если встреченный тип уже есть в армии

                INC IY
                INC IY
                INC IY
                DJNZ .FindArmySlot

                LD BC, #1203
                LD DE, Overlay.Join.Entry.DestroyedText                         ; сообщение об уничтожении присоединяемого отряда при невозможности вместить тип
                CALL Engine.PrintMessage                                        ; разобрать строку сообщения с управляющими кодами
                LD B, #14
                CALL Engine.WaitOrInput                                         ; выдержать паузу с досрочным выходом по вводу
                RET

.JoinPrompt     PUSH IY
                LD BC, #1516
                LD DE, #0209
                LD A, #46
                CALL Engine.FillAttributes                                      ; заполнить прямоугольник атрибутов цветом A
                LD B, #12
                LD DE, Overlay.Join.Entry.JoinOffer                             ; предложение принять отряд в армию героя
                CALL Engine.PrintMessage                                        ; разобрать строку сообщения с управляющими кодами
                LD IX, Overlay.Join.Entry.JoinMenu                              ; меню согласия на присоединение отряда
                CALL Engine.SelectMenuItem                                      ; управлять указателем и выбрать прямоугольный пункт меню
                POP IY
                CP #02
                RET Z                                                           ; выход, если игрок отказался присоединять отряд

                LD IX, (Entry.SourceTroop)
                LD L, (IY + FTroop.Count.Low)                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD H, (IY + FTroop.Count.High)                                  ; +#02, старший байт, беззнаковая численность little-endian
                LD A, H
                OR L
                JR NZ, .MergeUnit                                               ; переход, если целевой отряд уже существует и численность нужно сложить

                LD A, (IX + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                CALL Engine.ClearTwoFlags                                       ; обнулить два связанных байта таблиц

                ; численность встречи напрямую прибавляется к существующему отряду без проверки
                ; управляемости
.MergeUnit      LD C, (IX + FTroop.Count.Low)                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD B, (IX + FTroop.Count.High)                                  ; +#02, старший байт, беззнаковая численность little-endian
                ADD HL, BC
                LD (IY + FTroop.Count.Low), L                                   ; +#01, младший байт, беззнаковая численность little-endian
                LD (IY + FTroop.Count.High), H                                  ; +#02, старший байт, беззнаковая численность little-endian
                LD A, (IX + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                LD (IY + FTroop.ID), A                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                RET

.SourceTroop    DW #0000                                                        ; адрес поля ID встреченного отряда
.DestroyedText  EQU $                                                           ; сообщение об уничтожении присоединяемого отряда при невозможности вместить тип
                DB #81, #EB, #AB, #A8, #20, #E3, #AD, #A8
                DB #E7, #E2, #AE, #A6, #A5, #AD, #EB, #20
                DB #A2, #A0, #E8, #A5, #A9, #20, #A0, #E0
.JoinOffer      EQU $+6                                                         ; предложение принять отряд в армию героя
                DB #AC, #A8, #A5, #A9, #2E, #00, #88, #A7
                DB #EA, #EF, #A2, #A8, #AB, #A8, #20, #A6
                DB #A5, #AB, #A0, #AD, #A8, #A5, #20, #AF
                DB #A5, #E0, #A5, #A9, #E2, #A8, #0D, #2A
                DB #AD, #A0, #20, #A2, #A0, #E8, #E3, #20
                DB #E1, #E2, #AE, #E0, #AE, #AD, #E3, #2E
                DB #20, #82, #EB, #20, #E1, #AE, #A3, #AB
                DB #A0, #E1, #AD, #EB, #20, #3F, #0D, #2A
                DB #0D, #00, #91, #AE, #A3, #AB, #A0, #E1
                DB #A5, #AD, #0D, #1E, #8D, #A5, #20, #E1
                DB #AE, #A3, #AB, #A0, #E1, #A5, #AD, #0D
.JoinMenu       EQU $+2                                                         ; меню согласия на присоединение отряда
                DB #1D, #00, #02, #00, #70, #ED, #BF, #C8
                DB #AA, #16, #15, #1F, #16, #16, #16, #1F
                DB #17, #6F, #76, #65, #72, #6C, #61, #79

                assert $ = #B356
                endmodule
                endmodule
