; оверлей 11 из OVR1
; исходный файл каталога 48, смещение #2E15
                module Overlay
                module TakeOff
                org #B200

; -----------------------------------------
; проверка состава армии и переход в полёт
; Требует наземный режим и непустую армию. В первом обходе каждый непустой отряд должен иметь bit2
; поля SOLDIERS+#0D, прочитанного через #7AEF. Второй обход ищет хотя бы один отряд с bit2 поля
; SOLDIERS+#15, иначе функция возвращается без взлёта. В данном образе этот второй бит установлен
; только у ID16 «Драконы» и ID25 «Демоны», HELP объясняет возможность летать с героем на спине.
; Лишь после нахождения такого перевозчика проверяется глобальный bit5 #6A33 — наличие катапульты.
; Если она есть, меню предлагает бросить её либо не лететь. При успехе младшие два бита #6A33
; становятся 2, bit5 сбрасывается.
; In:
;   текущее состояние героя, армии и объекта в ядре
; Out:
;   состояние обновлено выбранной ветвью либо сохранено при отказе
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; -----------------------------------------
Entry           LD A, (State.MoveFlags)
                AND #03
                RET NZ                                                          ; выход, если герой уже находится в корабельном или воздушном режиме

                LD A, (State.Army)
                OR A
                RET Z                                                           ; выход, если армия героя пуста

                LD IY, State.Army
                LD B, #05

                ; сначала каждый отряд должен уметь летать, затем отдельный обход ищет
                ; перевозчика героя
.CheckFlyers    LD A, (IY + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                OR A
                JR Z, .FindCarrier                                              ; переход, если завершён обход типов для общей проверки полёта

                CALL Engine.UnitFlags                                           ; прочитать пару флагов описателя отряда
                BIT UNIT_FLY_BIT, E                                             ; флаг, тип существ способен летать
                RET Z                                                           ; выход, если очередной отряд не умеет летать

                INC IY
                INC IY
                INC IY
                DJNZ .CheckFlyers

.FindCarrier    LD IY, State.Army
                LD B, #05

                ; хотя бы один тип должен иметь флаг перевозки героя, одного общего умения
                ; летать недостаточно
.CarrierUnit    LD A, (IY + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                OR A
                RET Z                                                           ; выход, если перевозчик героя среди отрядов не найден

                CALL Engine.UnitDesc                                            ; получить описатель типа отряда
                BIT HERO_CARRY_BIT, (IX + FSoldier.SpecialFlags)                ; +#15, особые способности, ограничение восстановления и участие в перевозке
                JR Z, .NextCarrier                                              ; переход, если текущий тип существ не способен переносить героя

                LD A, (State.MoveFlags)
                BIT HERO_SIEGE_BIT, A                                           ; флаг, у героя есть осадное орудие, перед взлётом требуется его оставить
                JR Z, .StartFlying                                              ; переход, если нет осадного ограничения, запрещающего взлёт

                CALL Engine.StopView                                            ; выключить обработку объектов в прерывании
                CALL Engine.ResetViewFlags                                      ; сбросить младшие шесть флагов 48 записей объектов
                LD BC, #0701
                LD DE, #0B10
                LD A, #42
                CALL Engine.DrawFrame                                           ; нарисовать рамку окна из восьми одноклеточных элементов
                LD B, #0D
                LD DE, Overlay.TakeOff.Entry.SiegeText                          ; вопрос о судьбе осадных орудий перед полётом
                CALL Engine.PrintMessage                                        ; разобрать строку сообщения с управляющими кодами
                LD A, (IY + FTroop.ID)                                          ; +#00, ID типа отряда, 0 завершает плотный список. В финансовом проходе #9B10/#9B14 временно устанавливаются биты 7/6, поэтому не во всех промежуточных состояниях байт является чистым ID
                LD BC, #0202
                CALL Engine.SetUnitPicture                                      ; создать четырёхкадровый экранный объект
                CALL Engine.StartView                                           ; включить обработку объектов в прерывании
                LD IX, Overlay.TakeOff.Entry.SiegeMenu                          ; меню отказа от осадных орудий или отказа от полёта
                CALL Engine.SelectMenuItem                                      ; управлять указателем и выбрать прямоугольный пункт меню
                PUSH AF
                CALL Engine.UpdateLocalView                                     ; отметить открытые клетки вокруг героя и подготовить экранные объекты
                HALT
                POP AF
                CP #02
                RET Z                                                           ; выход, если герой отказался оставлять осадное орудие ради полёта

                ; включение полёта меняет режим передвижения и снимает наличие оставленного
                ; осадного орудия
.StartFlying    LD A, (State.MoveFlags)
                AND #FC
                OR #02
                RES HERO_SIEGE_BIT, A                                           ; флаг, у героя есть осадное орудие, перед взлётом требуется его оставить
                LD (State.MoveFlags), A
                RET

.NextCarrier    INC IY
                INC IY
                INC IY
                DJNZ .CarrierUnit

                RET

.SiegeText      EQU $                                                           ; вопрос о судьбе осадных орудий перед полётом
                DB #11, #00, #1A, #80, #20, #AA, #A0, #AA
                DB #20, #A6, #A5, #20, #A1, #EB, #E2, #EC
                DB #0D, #2A, #AA, #A0, #E2, #A0, #AF, #E3
                DB #AB, #EC, #E2, #AE, #A9, #20, #3F, #0D
                DB #2A, #0D, #00, #81, #E0, #AE, #E1, #A8
                DB #E2, #EC, #0D, #2A, #8D, #A5, #20, #AB
                DB #A5, #E2, #A5, #E2, #EC, #0D, #2A, #00
.SiegeMenu      EQU $                                                           ; меню отказа от осадных орудий или отказа от полёта
                DB #02, #10, #78, #8C, #98, #32, #82, #02
                DB #10, #12, #11, #02, #11, #12, #12, #6F
                DB #76, #65, #72, #6C, #61, #79

                assert $ = #B2D9
                endmodule
                endmodule
