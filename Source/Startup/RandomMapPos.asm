
; -----------------------------------------
; выбор случайных внутренних координат стратегической карты
; Вызывает генератор #7132 с масштабом 154, к результату E прибавляет 3 и переносит в C. Затем
; использует масштаб 93, прибавляет 3 и переносит в B. Исходный DE сохраняет. Точная верхняя
; включённая граница зависит от округления генератора, поэтому формула результата описана через
; два вызова без произвольного сужения диапазона.
; In:
;   состояние генератора
; Out:
;   C=randomScaled(154)+3, B=randomScaled(93)+3, DE сохранён
; Corrupt:
;   BC, AF
; -----------------------------------------
RandomMapPos    PUSH DE
                LD DE, #009A
                CALL RandomRange                                                ; получить псевдослучайное число, масштабированное к входному пределу
                INC E
                INC E
                INC E
                LD C, E
                LD DE, #005D
                CALL RandomRange                                                ; получить псевдослучайное число, масштабированное к входному пределу
                INC E
                INC E
                INC E
                LD B, E
                POP DE
                RET
