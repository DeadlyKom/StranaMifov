
; -----------------------------------------
; нарисовать символ без дополнительного EI в обёртке переключения банка
; сохраняет HL, записывает прямой адрес 5FA1 в операнды 6DFE и 6E50, вызывает 6DEE, используется
; из обработчика прерывания 6161, здесь нет EI обёртки 70DF, сохранение и восстановление регистров
; выполняет 6DEE
; In:
;   BC текстовая позиция, A код символа
; Out:
;   символ нарисован, регистры сохранены, операнды вызовов настроены на 5FA1
; Corrupt:
;   операнды 6DFE/6E50 устанавливаютсяна 5FA1 и пиксели символа, дополнительный EI не
;   выполняется, HL, DE, BC, AF, IX, IY сохранены
; -----------------------------------------
DrawGlyphNoEI   PUSH HL
                LD HL, Memory.SelectBank
                LD (Startup.DrawGlyph.SelectCall), HL
                LD (Startup.DrawGlyph.RestoreCall), HL
                CALL DrawGlyph                                                  ; нарисовать символ шириной шесть пикселей с произвольным битовым сдвигом
                POP HL
                RET
