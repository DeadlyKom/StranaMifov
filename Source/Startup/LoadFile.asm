
; -----------------------------------------
; загрузить именованный файл в заданную область через TR-DOS
; копирует девять байт имени и расширения из HL в 5CDD, записывает 0 в 5D10, исходный DE переносит
; в HL, задаёт C=0E и A=3, хвостовой JP 6DBC вызывает TR-DOS, длина выбирается из параметров файла
; In:
;   HL имя из восьми байтов и однобайтовый тип, DE адрес загрузки
; Out:
;   файл загружен через TR-DOS, I=60, IM2
; Corrupt:
;   HL, DE, BC, AF, IY
; -----------------------------------------
LoadFile        PUSH DE
                LD DE, TrDos.Descriptor                                         ; рабочий дескриптор имени и параметров файла TR-DOS
                LD BC, #0009
                LDIR
                XOR A
                LD (TrDos.Error), A
                POP HL
                LD C, #0E
                LD A, #03
                JP CallTrdos

