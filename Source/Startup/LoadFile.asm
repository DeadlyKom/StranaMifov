                DB #20, #E1, #20, #E1, #AE, #E1, #E2, #AE
                DB #EF, #AD, #A8, #EF, #AC, #A8, #20, #2E
                DB #2E, #2E, #2E, #00, #32, #DD, #70, #83
                DB #07, #32, #DE, #70, #AE, #77, #23, #0B
                DB #78, #B1, #20, #E1, #C9, #00, #00, #00
