
; -----------------------------------------
; циклическое вращение 24-битных строк рисунка и маски курсора вправо
; Для 16 последовательных троек байтов #76C2..#76F1 выполняет SRL, RR, RR и возвращает ушедший бит
; в бит 7 первого байта. Это отдельно 8 строк рисунка и 8 строк маски. Повторяет A раз, увеличивая
; счётчик суммарного вращения #770A после каждого прохода. A=0 не допускается, поскольку DEC A
; создаст 256 проходов.
; In:
;   A — положительное число пиксельных сдвигов
; Out:
;   A=0, B=0, образцы повёрнуты
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   #76C2..#76F1, #770A
; -----------------------------------------
RotateCursorR   PUSH AF
                LD B, #10
                LD HL, Startup.BL3_cursor                                       ; 24байта пикселей начального курсора

                ; циклический перенос битов в 24-битной строке, одинаково для восьми строк рисунка и восьми строк маски
.RotateRow      PUSH HL
                POP DE
                SRL (HL)
                INC HL
                RR (HL)
                INC HL
                RR (HL)
                INC HL
                JR NC, .NextRow                                                 ; переход, если правый край курсора не требует переноса пикселя в левый

                EX DE, HL
                SET PIXEL_LEFT_BIT, (HL)                                        ; позиция левого пикселя в экранном байте Spectrum
                EX DE, HL
.NextRow        DJNZ .RotateRow

                LD A, (Startup.BL3_cursorMask.Rotation)
                INC A
                LD (Startup.BL3_cursorMask.Rotation), A
                POP AF
                DEC A
                JR NZ, RotateCursorR                                            ; переход, если остались шаги вращения вправо

                RET
