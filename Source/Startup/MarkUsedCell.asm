
; -----------------------------------------
; установка бита занятости клетки с восстановлением банка
; Сохраняет текущий банк, передаёт номер континента #77A2 в #78A4, устанавливает бит 7 полученного
; байта карты и возвращает прежний банк.
; In:
;   B — строка, C — столбец, #77A2 — континент
; Out:
;   выбранный ранее банк восстановлен
; Corrupt:
;   HL, AF
; Note:
;   один байт карты
; -----------------------------------------
MarkUsedCell    LD A, (Memory.CurrentBank)
                PUSH AF
                LD A, (Startup.MarkUsedCell.Continent)
                CALL MapCellAddress                                             ; адрес клетки карты выбранного континента при создании игры
                SET MAP_BUSY_BIT, (HL)                                          ; флаг, клетка стратегической карты уже занята объектом при генерации
                POP AF
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                RET

.Continent      DB #00                                                          ; номер континента при отметке занятости карты
