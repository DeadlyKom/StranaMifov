
; -----------------------------------------
; восстановление фона старой позиции курсора
; Для восьми строк от старых координат #76BE копирует три байта из #76F2 обратно на экран,
; преобразуя адрес каждой строки через #73EF.
; In:
;   #76BE — старая позиция, #76F2..#7709 — фон
; Out:
;   изображение прежнего курсора убрано
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   пиксельная память экрана
; -----------------------------------------
RestoreCursor   LD BC, (Startup.RotateCursorL.PixelPos)
                LD DE, Startup.BL3_cursorMask.CursorBack                        ; сохранённые24пиксельныхбайта фона трёхбайтного курсора
                LD A, #08
.RestoreRow     PUSH BC
                PUSH AF
                CALL CursorByteAddr                                             ; адрес экранного пиксельного байта по координатам курсора
                EX DE, HL
                LDI
                LDI
                LDI
                EX DE, HL
                POP AF
                POP BC
                INC B
                DEC A
                JR NZ, .RestoreRow                                              ; переход, если ещё не восстановлены все строки фона курсора

                RET
