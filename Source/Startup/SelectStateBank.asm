
; -----------------------------------------
; запросить диск с состояниями и выбрать банк 1
; вызывает 65A9 для приглашения и ожидания клавиши, затем A=1 и хвостовой JP5FA1 выбирает
; логический банк 1, возврат выполняет RAMDRIVE
; In:
;   регистровых аргументов нет, подготовлен экран банка 4, доступны клавиатура и RAMDRIVE для
;   выбора банка 1
; Out:
;   выбран логический банк 1
; Corrupt:
;   HL, DE, BC, AF
; -----------------------------------------
SelectStateBank CALL PromptStateDisk                                            ; показать приглашение вставить диск с состояниями и дождаться клавиши
                LD A, #01
                JP Memory.SelectBank

                DB #CD, #AE, #65, #21, #FE, #FE, #C9
