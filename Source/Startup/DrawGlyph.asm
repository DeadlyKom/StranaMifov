
; -----------------------------------------
; нарисовать символ шириной шесть пикселей с произвольным битовым сдвигом
; сохраняет HL, DE, BC, AF, IY, IX и текущий логический банк, код переключения банка находится в
; изменяемых операндах 6DFE и 6E50, выбирает банк 3 со шрифтом BF00+8*A, 6E5B получает экранный
; адрес и сдвиг X=6*C+2, 16-битная маска начинается 03FF и сдвигается вправо с заполнением старших
; битов единицами, восемь байтов символа сдвигаются в пару D,E, каждый экранный байт заменяется по
; формуле (экран AND маска) OR символ, строки идут INC IXh, исходный банк и регистры
; восстанавливаются
; In:
;   BC текстовая позиция, B строка знакомест, C шестипиксельный столбец, A код символа
; Out:
;   восемь пиксельных строк символа нарисованы, регистры и логический банк сохранены
; Corrupt:
;   пиксели двух соседних экранных байтов на восьми строках, временно выбирается банк 3 и
;   восстанавливается исходный, IFF зависит от выбранной обёртки 6DFE/6E50, HL, DE, BC, AF, IX,
;   IY сохранены
; -----------------------------------------
DrawGlyph       PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                PUSH IY
                PUSH IX
                LD HL, (Memory.CurrentBank - FWord.High)
                PUSH HL
                PUSH AF
                LD A, #03
.SelectCall     EQU $+1                                                         ; операнд адреса переключения банка перед выводом глифа
                CALL PageAndEnable                                              ; выбрать логический банк и разрешить прерывания
                POP AF
                PUSH AF
                CALL GlyphAddress                                               ; вычислить экранный адрес и битовый сдвиг шестипиксельного символа
                LD BC, #03FF
                OR A
                JR Z, .GlyphAddress                                             ; переход, если символ выровнен на границу знакоместа

                ; подготовка маски для шестипиксельного символа, который может пересекать границу экранного байта
.ShiftMask      SRL B
                RR C
                SET MASK_FILL_BIT, B                                            ; позиция старшего бита маски, заполняемого единицей при смещении шестипиксельного символа
                DEC A
                JR NZ, .ShiftMask                                               ; переход, если ещё не получена маска нужного смещения

.GlyphAddress   POP AF
                LD IYL, A
                LD IYH, #00
                ADD IY, IY
                ADD IY, IY
                ADD IY, IY
                LD DE, StartupTables.FontGlyphs - 32 * 8                        ; смещённая база глифов по ASCII, первый хранимый код32
                ADD IY, DE
                LD H, #08

                ; вывод восьми строк символа с сохранением пикселей вне его маски
.PixelRow       LD D, (IY + #00)
                LD E, #00
                LD A, L
                OR A
                JR Z, .MergePixels                                              ; переход, если символ выровнен на границу знакоместа

.ShiftGlyph     SRL D
                RR E
                DEC A
                JR NZ, .ShiftGlyph                                              ; переход, если строка глифа ещё не сдвинута на требуемое число пикселей

.MergePixels    LD A, (IX + #00)
                AND B
                OR D
                LD (IX + #00), A
                LD A, (IX + Screen.PairRight)
                AND C
                OR E
                LD (IX + Screen.PairRight), A
                INC IXH
                INC IY
                DEC H
                JR NZ, .PixelRow                                                ; переход, если ещё не выведены все пиксельные строки глифа

                POP AF
.RestoreCall    EQU $+1                                                         ; операнд адреса восстановления банка после вывода глифа
                CALL PageAndEnable                                              ; выбрать логический банк и разрешить прерывания
                POP IX
                POP IY
                POP AF
                POP BC
                POP DE
                POP HL
                RET
