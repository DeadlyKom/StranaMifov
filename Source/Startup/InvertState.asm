
; -----------------------------------------
; побайтовая инверсия блока данных состояния
; Читает байт по HL, выполняет CPL и записывает обратно, увеличивает HL и уменьшает DE до нуля.
; Два одинаковых вызова восстанавливают исходные байты. При входном DE=0 цикл затронул бы весь 64
; Кдиапазон, реальные вызывающие участки передают ненулевую длину.
; In:
;   HL — начало, DE — ненулевой размер
; Out:
;   HL после блока, DE=0
; Corrupt:
;   HL, DE, AF
; Note:
;   исходный блок заменён инверсией XOR #FF
; -----------------------------------------
InvertState     LD A, (HL)
                CPL
                LD (HL), A
                INC HL
                DEC DE
                LD A, D
                OR E
                JR NZ, InvertState                                              ; переход, если остались байты состояния для инверсии

                RET
