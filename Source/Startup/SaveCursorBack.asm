
; -----------------------------------------
; сохранение фона новой позиции курсора
; Для восьми строк от новых координат #76C0 вычисляет адрес #73EF и копирует по 3 байта в линейный
; буфер #76F2. Это 24 байта пиксельного фона, атрибуты не копируются.
; In:
;   #76C0 — новая позиция
; Out:
;   #76F2..#7709 — сохранённый фон
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   буфер фона
; -----------------------------------------
SaveCursorBack  LD BC, (Startup.RotateCursorL.HitPos)
                LD DE, Startup.BL3_cursorMask.CursorBack                        ; сохранённые24пиксельныхбайта фона трёхбайтного курсора
                LD A, #08
.SaveRow        PUSH BC
                PUSH AF
                CALL CursorByteAddr                                             ; адрес экранного пиксельного байта по координатам курсора
                LDI
                LDI
                LDI
                POP AF
                POP BC
                INC B
                DEC A
                JR NZ, .SaveRow                                                 ; переход, если ещё не сохранены все строки фона курсора

                RET
