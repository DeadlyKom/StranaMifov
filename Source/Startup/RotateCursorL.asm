
; -----------------------------------------
; циклическое вращение 24-битных строк рисунка и маски курсора влево
; Обратный к #7674 проход от #76F1, SLA последнего байта, RL среднего, RL первого, ушедший бит
; возвращает в бит 0 последнего. Обрабатывает 16 троек, повторяет A раз и уменьшает #770A.
; In:
;   A — положительное число сдвигов
; Out:
;   A=0, B=0, вращение вправо отменено на A шагов
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   #76C2..#76F1, #770A
; -----------------------------------------
RotateCursorL   PUSH AF
                LD B, #10
                LD HL, Startup.BL3_cursorMask + 23                              ; последний байт восьмистрочной трёхбайтной маски, вращение идёт с конца

                ; обратное циклическое вращение 24-битных строк рисунка и маски курсора
.RotateRow      PUSH HL
                POP DE
                SLA (HL)
                DEC HL
                RL (HL)
                DEC HL
                RL (HL)
                DEC HL
                JR NC, .NextRow                                                 ; переход, если левый край курсора не требует переноса пикселя в правый

                EX DE, HL
                SET PIXEL_RIGHT_BIT, (HL)                                       ; позиция правого пикселя в экранном байте Spectrum
                EX DE, HL
.NextRow        DJNZ .RotateRow

                LD A, (Startup.BL3_cursorMask.Rotation)
                DEC A
                LD (Startup.BL3_cursorMask.Rotation), A
                POP AF
                DEC A
                JR NZ, RotateCursorL                                            ; переход, если остались шаги вращения влево

                RET

.PixelPos       DB #00                                                          ; пиксельные координаты курсора, X в младшем байте
.PixelY         DB #00                                                          ; пиксельная строка курсора
.HitPos         DB #00                                                          ; координаты курсора для проверки прямоугольников меню
.HitY           DB #00                                                          ; строка курсора для проверки прямоугольников меню
BL3_cursor      INCBIN "Assets/Gfx/raw/BL3_cursor.ink"                          ; графический ресурс, исходное смещение #1579
BL3_cursorMask  INCBIN "Assets/Gfx/raw/BL3_cursor.mask"                         ; графический ресурс, исходное смещение #1591
.CursorBack     EQU $                                                           ; сохранённые24пиксельныхбайта фона трёхбайтного курсора
                DB #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00, #00, #00, #00, #00
                DB #00, #00, #00, #00
.Rotation       DB #00                                                          ; текущий битовый поворот курсора 0..7
