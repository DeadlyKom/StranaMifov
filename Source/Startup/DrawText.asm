
; -----------------------------------------
; вывести строку с нулевым терминатором и переходами строк
; читает символы из DE до 0, обычный байт передаёт 6E88 и увеличивает C, код 0D потребляет
; следующий байт как новый столбец C и увеличивает строку B, DE, BC, AF сохраняются, ограничения
; длины и экранного края отсутствуют
; In:
;   DE строка, BC начальная текстовая позиция
; Out:
;   текст выведен, регистры сохранены
; Corrupt:
;   пиксели текста, операнды 6DFE/6E50 и IFF через 6E88, HL, DE, BC, AF, IX, IY сохранены
; -----------------------------------------
DrawText        PUSH DE
                PUSH BC
                PUSH AF
.ReadChar       LD A, (DE)
                OR A
                JR Z, .RestoreRegs                                              ; переход, если достигнут нулевой терминатор текста

                CP #0D
                JR NZ, .DrawChar                                                ; переход, если символ не является переводом строки

                INC DE
                LD A, (DE)
                INC B
                LD C, A
                JR .NextChar

.DrawChar       CALL DrawGlyphEI                                                ; нарисовать символ с разрешением прерываний после переключения банка
                INC C
.NextChar       INC DE
                JR .ReadChar

.RestoreRegs    POP AF
                POP BC
                POP DE
                RET
