
; -----------------------------------------
; опрос клавиатуры ROM и Kempston с преобразованием направлений
; Вызывает ROM #028E. Если E!=#FF, возвращает A=E. Иначе читает порт #1F и повторяет при нуле.
; Bit4 Kempston немедленно возвращает код действия #27. Для прочих значений ищет точную пару
; состояние/код в таблице #762F. Проверки отсутствующего порта #FF нет, такое значение имеет бит 4
; и будет воспринято как действие.
; In:
;   порты клавиатуры и Kempston
; Out:
;   A — код, #13 вверх-влево, #1B вверх, #23 вверх-вправо, #12 влево, #22 вправо, #11
;   вниз-влево, #19 вниз, #21 вниз-вправо, #27 действие
; Corrupt:
;   HL, DE, BC, AF по ROM и поиску
; -----------------------------------------
ReadMenuInput   CALL Rom.ScanKeyboard                                           ; сканер клавиатуры, E=#FF означает отсутствие распознанной клавиши
                LD A, E
                CP #FF
                RET NZ                                                          ; выход, если клавиатурный сканер распознал клавишу

                IN A, (#1F)
                OR A
                JR Z, ReadMenuInput                                             ; переход, если Kempston не сообщает ни одного направления или кнопки

                BIT JOY_FIRE_BIT, A                                             ; флаг, кнопка действия Kempston нажата
                JR Z, .MapKey                                                   ; переход, если кнопка подтверждения Kempston не нажата

                LD A, #27
                RET

.MapKey         LD HL, Startup.ReadMenuInput.KeyPairs - 1                       ; смещённая база клавиш Kempston, цикл сначала увеличивает HL
.FindKeyCode    INC HL
                CP (HL)
                INC HL
                JR NZ, .FindKeyCode                                             ; переход, если код Kempston ещё не найден в таблице соответствий

                LD A, (HL)
                RET

.KeyPairs       EQU $                                                           ; пары состояния Kempston и кода меню
                DB #08, #1B, #09, #23, #01, #22, #05, #21
                DB #04, #19, #06, #11, #02, #12, #0A, #13
.HoverRect      DB #00, #00, #00, #00, #00                                      ; указатель подсвеченного прямоугольника меню, 0 вне пунктов
