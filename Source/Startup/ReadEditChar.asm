
; -----------------------------------------
; дождаться допустимого символа для строкового ввода
; обнуляет LAST_K5C08 и ждёт ненулевого значения от ROM-сканера, код 07 переключает бит 6 поля
; 61D5 и продолжает ожидание, 0C/0D/0E возвращаются напрямую, бит 4 разрешает только цифры и
; управляющие коды, без него допустимы пробел и латинские буквы, малые буквы переводятся в
; большие, бит 6 включает перекодировку цифр по 701A и букв по 7024 в символы альтернативного
; алфавита
; In:
;   биты 4 и 6 поля 61D5, работающие прерывания с ROM-сканером
; Out:
;   A допустимый код, HL и BC сохранены
; Corrupt:
;   AF
; -----------------------------------------
ReadEditChar    PUSH HL
                PUSH BC
                LD HL, Startup.Interrupt.EditFlags
.ClearKey       XOR A
                LD (System.LastKey), A
.WaitKey        LD A, (System.LastKey)
                OR A
                JR Z, .WaitKey                                                  ; переход, если новая клавиша ещё не поступила

                CP #07
                JR NZ, .TestControlKey                                          ; переход, если не нажато переключение русского алфавита

                LD A, (Startup.Interrupt.EditFlags)
                XOR #40
                LD (Startup.Interrupt.EditFlags), A
                JR .ClearKey

.TestControlKey CP #0C
                JR Z, .ReturnKey                                                ; переход, если нажато удаление символа

                CP #0D
                JR Z, .ReturnKey                                                ; переход, если нажато подтверждение текста

                CP #20
                JR NZ, .TestDigit                                               ; переход, если нажат не пробел

                BIT TEXT_DIGIT_BIT, (HL)                                        ; флаг, разрешены только цифры и служебные коды ввода
                JR NZ, .ClearKey                                                ; переход, если режим числового ввода запрещает пробел

                JR .ReturnKey

.TestDigit      CP #0E
                JR Z, .ReturnKey                                                ; переход, если нажата отмена редактирования

                CP #30
                JR C, .ClearKey                                                 ; переход, если код клавиши меньше первой цифры

                CP #3A
                JR NC, .TestLetter                                              ; переход, если код клавиши выше последней цифры

                BIT TEXT_DIGIT_BIT, (HL)                                        ; флаг, разрешены только цифры и служебные коды ввода
                JR NZ, .ReturnKey                                               ; переход, если включён режим ввода цифр

                BIT TEXT_RUS_BIT, (HL)                                          ; флаг, вводимые цифры и буквы преобразуются в русский алфавит
                JR Z, .ReturnKey                                                ; переход, если преобразование символов в русский алфавит отключено

                LD HL, Startup.ReadEditChar.DigitMap - 48                       ; смещённая база таблицы цифр, индексируется ASCII0..9
                LD B, #00
                LD C, A
                ADD HL, BC
                LD A, (HL)
                JR .ReturnKey

.TestLetter     BIT TEXT_DIGIT_BIT, (HL)                                        ; флаг, разрешены только цифры и служебные коды ввода
                JR NZ, .ClearKey                                                ; переход, если режим числового ввода запрещает буквы

                CP #41
                JR C, .ClearKey                                                 ; переход, если код клавиши меньше первой заглавной буквы

                CP #5B
                JR C, .MapLetter                                                ; переход, если введена заглавная латинская буква

                CP #61
                JR C, .ClearKey                                                 ; переход, если код клавиши находится между заглавными и строчными буквами

                CP #7B
                JR NC, .ClearKey                                                ; переход, если код клавиши выше последней строчной буквы

                SUB #20
.MapLetter      BIT TEXT_RUS_BIT, (HL)                                          ; флаг, вводимые цифры и буквы преобразуются в русский алфавит
                JR Z, .ReturnKey                                                ; переход, если преобразование символов в русский алфавит отключено

                LD HL, Startup.ReadEditChar.LetterMap - 65                      ; смещённая база таблицы букв, индексируется ASCIIA..Z
                LD B, #00
                LD C, A
                ADD HL, BC
                LD A, (HL)
.ReturnKey      POP BC
                POP HL
                RET

.DigitMap       EQU $                                                           ; преобразование цифр в режиме русского алфавита
                DB #5F, #98, #99, #9D, #9E, #97, #9A, #27
.LetterMap      EQU $+2                                                         ; преобразование заглавных латинских букв в русский алфавит
                DB #28, #29, #80, #81, #96, #84, #85, #94
                DB #83, #95, #88, #89, #8A, #8B, #8C, #8D
                DB #8E, #8F, #9F, #90, #91, #92, #93, #86
                DB #82, #9C, #9B, #87, #E5, #D5, #C5, #F5
                DB #DD, #E5, #FD, #E5, #CD, #2B, #2D, #CF
                DB #85, #FD, #E1, #DD, #E1, #F1, #C1, #D1
                DB #E1, #C9, #E5, #D5, #F5, #DD, #E5, #FD
                DB #E5, #CD, #A2, #2D, #FD, #E1, #DD, #E1
                DB #F1, #D1, #E1, #C9, #D5, #C5, #F5, #7E
                DB #23, #5E, #23, #56, #23, #4E, #23, #46
                DB #23, #E5, #CD, #BB, #2A, #E1, #F1, #C1
                DB #D1, #C9, #D5, #C5, #F5, #E5, #CD, #F1
                DB #2B, #E1, #77, #23, #73, #23, #72, #23
                DB #71, #23, #70, #23, #F1, #C1, #D1, #C9
