
; -----------------------------------------
; обработать кадровое прерывание начального модуля
; сохраняет основные, альтернативные и индексные регистры и текущий банк памяти
; сохраняет операнды DrawGlyph.SelectCall и RestoreCall на время фоновых обработчиков
; EditFlags разрешает мигание текстового курсора, CursorTimer задаёт период смены CursorGlyph
; TickIntroText выводит текст создания игры, Rom.ScanKeys128 обслуживает клавиатуру ПЗУ 128
; затем восстанавливает операнды, банк и регистры и возвращается через EI, RETI
; In:
;   аппаратный адрес возврата на стеке, установлены Memory.SelectBank и фоновые обработчики
; Out:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY восстановлены, исходный банк восстановлен
; Corrupt:
;   R, IFF, CursorTimer и CursorGlyph при разрешённом мигании, экран курсора и плеер
; -----------------------------------------
Interrupt       PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                PUSH IX
                PUSH IY
                EXX
                EX AF, AF'
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                EXX
                EX AF, AF'
                LD A, (Memory.CurrentBank)
                PUSH AF
                LD HL, (Startup.DrawGlyph.SelectCall)
                PUSH HL
                LD HL, (Startup.DrawGlyph.RestoreCall)
                PUSH HL
                LD A, (Startup.Interrupt.EditFlags)
                BIT TEXT_CURSOR_BIT, A                                          ; флаг, прерывание рисует мигающий текстовый курсор
                JR Z, .TickIntroText                                            ; переход, если редактор не разрешает мигание текстового курсора

                LD A, (Startup.Interrupt.CursorTimer)
                OR A
                JR NZ, .CursorTick                                              ; переход, если таймер курсора ещё не истёк

                LD A, (Startup.Interrupt.CursorGlyph)
                CP #F5
                JR NZ, .NextCursorChar                                          ; переход, если текущий символ курсора отличается от F5

                LD A, #F1
.NextCursorChar INC A
                LD (Startup.Interrupt.CursorGlyph), A
                LD A, #07
.CursorTick     DEC A
                LD (Startup.Interrupt.CursorTimer), A
                LD BC, (Startup.Interrupt.CursorPos)
                LD A, (Startup.Interrupt.CursorGlyph)
                CALL DrawGlyphNoEI                                              ; нарисовать символ без дополнительного EI в обёртке переключения банка
.TickIntroText  CALL TickIntroText                                              ; периодический вывод и прокрутка текста во время создания новой игры
                LD IY, System.FlagsAnchor                                       ; системная база IY перед вызовами TR-DOS или128ROM
                CALL Rom.ScanKeys128                                            ; KEYS128ROM, опрос клавиатуры и необязательного keypad
                POP HL
                LD (Startup.DrawGlyph.RestoreCall), HL
                POP HL
                LD (Startup.DrawGlyph.SelectCall), HL
                POP AF
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                EXX
                EX AF, AF'
                POP AF
                POP BC
                POP DE
                POP HL
                EXX
                EX AF, AF'
                POP IY
                POP IX
                POP AF
                POP BC
                POP DE
                POP HL
                EI
                RETI

.CursorTimer    DB #06                                                          ; таймер анимации текстового курсора начального модуля
.CursorGlyph    DB #F2                                                          ; текущий символ анимации текстового курсора
.CursorPos      DB #00, #00                                                     ; координаты BC текстового курсора редактора
.EditAnchor     DB #00                                                          ; опорный адрес за один байт перед управляющими флагами текстового ввода

