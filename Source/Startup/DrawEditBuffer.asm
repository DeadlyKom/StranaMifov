
; -----------------------------------------
; перерисовать поле редактирования и стереть символ за его концом
; из 6FA5 берёт буфер, из 6FA3 позицию, из 6FA7 число символов, рисует ровно эту длину через 6E88
; с увеличением столбца, затем один пробел после поля, входные DE, BC, AF сохраняются, HL не
; используется
; In:
;   6FA3 позиция, 6FA5 буфер, 6FA7 длина>0
; Out:
;   поле строки и следующий пробел нарисованы, регистры сохранены
; Corrupt:
;   пиксели поля ввода и пробела за ним, операнды 6DFE/6E50 и IFF через 6E88, HL, DE, BC, AF,
;   IX, IY сохранены
; -----------------------------------------
DrawEditBuffer  PUSH DE
                PUSH BC
                PUSH AF
                LD DE, (Startup.DrawEditBuffer.Buffer)
                LD BC, (Startup.DrawEditBuffer.Position)
                LD A, (Startup.DrawEditBuffer.MaxLength)
.DrawCharLoop   PUSH AF
                LD A, (DE)
                CALL DrawGlyphEI                                                ; нарисовать символ с разрешением прерываний после переключения банка
                POP AF
                INC C
                INC DE
                DEC A
                JR NZ, .DrawCharLoop                                            ; переход, если ещё не выведены все позиции поля редактирования

                LD A, #20
                CALL DrawGlyphEI                                                ; нарисовать символ с разрешением прерываний после переключения банка
                POP AF
                POP BC
                POP DE
                RET

.Position       DW #0000                                                        ; позиция BC начала редактируемого поля
.Buffer         DW #0000                                                        ; указатель редактируемого текстового буфера
.MaxLength      DB #00                                                          ; предел длины редактируемого поля
