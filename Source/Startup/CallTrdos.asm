
; -----------------------------------------
; вызвать TR-DOS с временным переходом в IM 1
; DI, IY=5C3A, входной AF сохраняется вокруг установки I=3F, затем IM1 и EI, вызывается 3D13 с
; исходными A и остальными параметрами, после возврата DI, I=60, IM2, EI, исходный IY не
; восстанавливается, A к выходу равен 60
; In:
;   A и остальные регистры по контракту функции TR-DOS в C
; Out:
;   результат выбранной функции TR-DOS, IY=5C3A, I=60, IM2, прерывания разрешены
; Corrupt:
;   регистры по контракту TR-DOS, AF, IY, I и режим прерываний
; -----------------------------------------
CallTrdos       DI
                LD IY, System.FlagsAnchor                                       ; системная база IY перед вызовами TR-DOS или128ROM
                PUSH AF
                LD A, #3F
                LD I, A
                POP AF
                IM 1
                EI
                CALL TrDos.Service                                              ; вызов сервиса TR-DOS, номер операции находится в C
                DI
                LD A, #60
                LD I, A
                IM 2
                EI
                RET
