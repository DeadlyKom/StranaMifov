
; -----------------------------------------
; поиск N-й неудалённой записи типа M в буфере каталога
; Начинает перед каталогом с IX=#BFF0, добавляет 16 байтов на запись. Сравнивает тип+8 с ASCII M,
; пропускает удалённые записи с первым байтом 1. Счётчик B уменьшается только для подходящих
; записей. Проверки нулевого конца каталога здесь нет, поэтому A должен не превышать уже
; подсчитанное число сохранений.
; In:
;   A — порядковый номер сохранения с 1, текущий банк содержит каталог по #C000
; Out:
;   IX —16-байтовая запись, BC сохранён
; Corrupt:
;   DE, AF, IX
; -----------------------------------------
FindSaveRecord  PUSH BC
                LD B, A
                LD IX, StartupTables.Directory - FTrdosEntry                    ; позиция перед первой записью каталога, цикл сначала добавляет16байтов
                LD DE, #0010
.RecordLoop     ADD IX, DE
                LD A, (IX + FTrdosEntry.Type)
                CP #4D
                JR NZ, .RecordLoop                                              ; переход, если запись не имеет сигнатуры сохранения M

                LD A, (IX + FTrdosEntry.Name)
                CP #01
                JR Z, .RecordLoop                                               ; переход, если запись каталога помечена как удалённая

                DJNZ .RecordLoop

                POP BC
                RET
