
; -----------------------------------------
; генерация от двух до пяти трёхбайтовых отрядов по весовой таблице
; Сохраняет IX. Число записей получает как scaledRandom(3)+2. Для каждой выбирает банк 3, получает
; случайный байт с масштабом 254, берёт таблицу по исходному HL+150*A и проходит 6-байтовые
; записи, пока случайное значение не меньше порога+1. Из записи берёт ID+0, базовое 16-битное
; количество+2/+3 и разброс+4/+5. Ещё один вызов #7132 даёт добавку, сумма записывается в банк 0
; по IY как ID и 16-битное количество. IY увеличиваетсяна 3. Самостоятельной очистки оставшихся
; мест массива или установки нулевого терминатора нет.
; In:
;   A — номер континентальной таблицы, HL — база перед группами по 150 байтов, IY — приёмник
;   банк 0
; Out:
;   записано 2..5 отрядов, IY после них, IX сохранён
; Corrupt:
;   HL, DE, BC, AF, IY
; Note:
;   приёмник банк 0, операнды #78EF/#78F2
; -----------------------------------------
GenerateArmy    PUSH IX
                LD (Startup.GenerateArmy.Continent), A
                LD (Startup.GenerateArmy.TypeTable), HL
                LD DE, #0003
                CALL RandomRange                                                ; получить псевдослучайное число, масштабированное к входному пределу
                INC E
                INC E
                LD B, E
.UnitLoop       PUSH BC
                LD A, #03
                CALL PageAndEnable                                              ; выбрать логический банк и разрешить прерывания
                LD DE, #00FE
                CALL RandomRange                                                ; получить псевдослучайное число, масштабированное к входному пределу
                LD A, E
.Continent      EQU $+1                                                         ; операнд B выбора таблицы континента
                LD B, #00
.TypeTable      EQU $+2                                                         ; операнд IX базы весовой таблицы отрядов
                LD IX, #0000
                LD DE, #0096
.ContinentTable ADD IX, DE
                DJNZ .ContinentTable

                LD DE, #0006

                ; выбор записи по накопленному весу и генерация количества внутри её диапазона
.WeightedUnit   ADD IX, DE
                CP (IX + FWeightedTroop.Threshold)
                JR NC, .WeightedUnit                                            ; переход, если случайный отсчёт вышел за накопленный вес варианта

                LD B, (IX + FWeightedTroop.UnitID)
                LD E, (IX + FWeightedTroop.CountRange.Low)
                LD D, (IX + FWeightedTroop.CountRange.High)
                CALL RandomRange                                                ; получить псевдослучайное число, масштабированное к входному пределу
                LD L, (IX + FWeightedTroop.BaseCount.Low)
                LD H, (IX + FWeightedTroop.BaseCount.High)
                ADD HL, DE
                XOR A
                CALL PageAndEnable                                              ; выбрать логический банк и разрешить прерывания
                LD (IY + FTroop.ID), B
                LD (IY + FTroop.Count.Low), L
                LD (IY + FTroop.Count.High), H
                INC IY
                INC IY
                INC IY
                POP BC
                DJNZ .UnitLoop

                POP IX
                RET

