
; -----------------------------------------
; восстановление полного экрана из сохранённого фона в банк 4
; Сохраняет номер текущего банка из #5FA0, выбирает банк 4 и копирует #1B00 байтов из #C000 в
; #4000. Возвращает исходный банк. Копируются и 6144 пиксельных байта, и 768 атрибутов.
; In:
;   банк 4, #C000..#DAFF — исходный экран
; Out:
;   текущий банк восстановлен
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   #4000..#5AFF
; -----------------------------------------
RestoreScreen   LD A, (Memory.CurrentBank)
                PUSH AF
                LD A, #04
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                LD HL, Presentation.screen                                      ; первые6912байтов PRES в банке4 служат сохранённым фоном меню
                LD DE, Screen.Pixels                                            ; начало видимой пиксельной памяти экрана
                LD BC, #1B00
                LDIR
                POP AF
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                RET
