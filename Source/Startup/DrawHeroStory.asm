
; -----------------------------------------
; вывод текстового описания выбранного героя из HERTXT
; Берёт номер изображения героя из #7D35, вычитает 1 и ищет соответствующий разделитель #B0 в
; HERTXT от #D6FF. После двух служебных байтов печатает текст в строке 1, столбце 22. CR начинает
; новую строку со столбца 22, #B1 завершает описание. Выбор героя и его текст связаны номером, а
; сами записи PERSON данная процедура не читает.
; In:
;   #7D35 — номер выбранного изображения, HERTXT загружен в банк 0, #D6FF
; Out:
;   описание выведено, DE у завершающего #B1
; Corrupt:
;   DE, BC, AF
; -----------------------------------------
DrawHeroStory   LD A, (Graphics.Heroes.Draw.Picture)
                LD B, A
                DEC B
                LD DE, StartupTables.HeroStories - 1                            ; база перед первым маркером HERTXT, цикл сначала увеличивает DE
.FindStory      INC DE
                LD A, (DE)
                CP #B0
                JR NZ, .FindStory                                               ; переход, если маркер начала истории ещё не найден

                DJNZ .FindStory

                INC DE
                INC DE
                LD BC, #0116
.StoryChar      LD A, (DE)
                CP #B1
                RET Z                                                           ; выход, если достигнут маркер конца истории

                CP #0D
                JR Z, .NewStoryLine                                             ; переход, если встретился перевод строки

                CALL DrawGlyphEI                                                ; нарисовать символ с разрешением прерываний после переключения банка
                INC DE
                INC C
                JR .StoryChar

.NewStoryLine   INC DE
                LD C, #16
                INC B
                JR .StoryChar
