
; -----------------------------------------
; отметка занимаемых строениями клеток стартовых карт
; Сохраняет AF, задаёт номер континента #77A2, выбирает банк 0. Вызывает #7746 для трёх таблиц
; #6CD6, #6CE6, #6CF6, шаги 35, 26, 5 и прямоугольники 3x2, 1x1, 2x2 клетки соответственно. Во
; всех клетках объектов устанавливается бит 7 стратегической карты. Это отметка
; занятости/резервирования, а не отдельная битовая маска карты пройденного из банка 11.
; In:
;   A — континент 1..4
; Out:
;   AF восстановлен, активен банк 0
; Corrupt:
;   HL, DE, BC, IX, IY
; Note:
;   карты банк 10..13, #77A2 и рабочие операнды
; -----------------------------------------
MarkStructures  PUSH AF
                LD (Startup.MarkUsedCell.Continent), A
                XOR A
                CALL Memory.SelectBank                                          ; переключение логического банка через установленный драйвер памяти
                LD IX, Startup.PromptGameDisk.CastleIndex
                LD BC, #0203
                LD DE, #0023
                CALL MarkGroupCells                                             ; обход записей одной группы и отметка их прямоугольного следа на карте
                LD IX, Startup.PromptGameDisk.TownLists - FMapList              ; смещённая база таблицы до первого континента
                LD BC, #0101
                LD DE, #001A
                CALL MarkGroupCells                                             ; обход записей одной группы и отметка их прямоугольного следа на карте
                LD IX, Startup.PromptGameDisk.TempleLists - FMapList            ; смещённая база таблицы до первого континента
                LD BC, #0202
                LD DE, #0005
                CALL MarkGroupCells                                             ; обход записей одной группы и отметка их прямоугольного следа на карте
                POP AF
                RET
