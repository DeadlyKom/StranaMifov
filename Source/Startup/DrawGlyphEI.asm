
; -----------------------------------------
; нарисовать символ с разрешением прерываний после переключения банка
; сохраняет HL, записывает адрес 70DF в оба изменяемых операнда 6DFE и 6E50, вызывает 6DEE и
; восстанавливает HL, обёртка 70DF делает CALL5FA1 и EI, этот вариант используется обычным выводом
; текста
; In:
;   BC текстовая позиция, A код символа
; Out:
;   символ нарисован, регистры сохранены, операнды вызовов настроены на 70DF
; Corrupt:
;   операнды 6DFE/6E50 устанавливаютсяна 70DF, пиксели символа и IFF, прерывания разрешаются,
;   HL, DE, BC, AF, IX, IY сохранены
; -----------------------------------------
DrawGlyphEI     PUSH HL
                LD HL, Startup.PageAndEnable                                    ; адрес обёртки выбора банка с EI для самопатча DrawGlyph
                LD (Startup.DrawGlyph.SelectCall), HL
                LD (Startup.DrawGlyph.RestoreCall), HL
                CALL DrawGlyph                                                  ; нарисовать символ шириной шесть пикселей с произвольным битовым сдвигом
                POP HL
                RET
