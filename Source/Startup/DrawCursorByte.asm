
; -----------------------------------------
; маскированная запись одного байта курсора
; Если H<#58, записывает (экран AND маска IY) OR рисунок IX. При H>=#58 запись пропускается. В
; любом случае увеличивает HL, IX, IY, сохраняя продвижение источников даже за нижней границей
; пиксельной памяти.
; In:
;   HL — экран, IX — рисунок, IY — маска
; Out:
;   HL, IX, IY увеличены на 1
; Corrupt:
;   HL, AF, IX, IY
; Note:
;   байт экрана при H<#58
; -----------------------------------------
DrawCursorByte  LD A, H
                CP #58
                JR NC, .NextByte                                                ; переход, если адрес уже вышел из пиксельной области экрана

                LD A, (HL)
                AND (IY + #00)
                OR (IX + #00)
                LD (HL), A
.NextByte       INC HL
                INC IX
                INC IY
                RET
