
; -----------------------------------------
; движение курсора на один пиксель вверх в пределах меню
; Сравнивает старый y #76BF с minY IX+2. При равенстве оставляет новую позицию, иначе пишет y-1 в
; #76C1. Это шаг от последней показанной позиции, не накопление поверх уже изменённого y.
; In:
;   IX — меню, #76BF — старый y
; Out:
;   #76C1 — кандидат нового y
; Corrupt:
;   AF
; -----------------------------------------
CursorUp        LD A, (Startup.RotateCursorL.PixelY)
                CP (IX + FMenuHeader.MinY)
                RET Z                                                           ; выход, если курсор достиг верхней границы меню

                DEC A
                LD (Startup.RotateCursorL.HitY), A
                RET
