
; -----------------------------------------
; адрес клетки карты выбранного континента при создании игры
; Выбирает логический банк A+9. Вычисляет #BF5F+161*(B+1)+C, что равно #C000+161*row+column. Пары
; DE/BC сохраняет, выбранный банк остаётся активным.
; In:
;   A — континент 1..4, B — строка, C — столбец
; Out:
;   HL — байт карты, BC и DE сохранены
; Corrupt:
;   HL, AF
; Note:
;   активныйбанк 10..13
; -----------------------------------------
MapCellAddress  PUSH DE
                PUSH BC
                ADD A, #09
                CALL PageAndEnable                                              ; выбрать логический банк и разрешить прерывания
                LD HL, Memory.BankWindow - 161                                  ; смещённая база карты, расчёт прибавляет161*(строка+1)+столбец
                LD DE, #00A1
                INC B
.ContinentBase  ADD HL, DE
                DJNZ .ContinentBase

                ADD HL, BC
                POP BC
                POP DE
                RET
