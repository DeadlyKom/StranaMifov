
; -----------------------------------------
; расшифровать начальный модуль перед передачей управления
; после внешнего дешифрования из KB отключает прерывания и задаёт R=50, XOR с показаниями R
; обрабатывает 7125 байтов 615E..7D32, первый ключ 54, шаг 9 по модулю 128, последний байт файла
; 7D33 не меняется этим проходом
; In:
;   BL3 после внешних 15 проходов KB загружен 6149..7D33, код 6149..615D цел, регистровые
;   аргументы не требуются
; Out:
;   615E..7D32 расшифрованы собственным R-XOR, первый ключ 54 и шаг 9 по модулю 128, последний
;   байт 7D33 не меняется, вход в 615E с HL=7D33, BC=0, A=0, R=4F, DE, SP, IX, IY сохранены
; Corrupt:
;   HL, BC, AF, R, память 615E..7D32, прерывания запрещены через DI
; -----------------------------------------
DecodeBoot      DI
                LD A, #50
                LD R, A
                LD HL, Startup.Entry                                            ; первый байт расшифровываемого основного кода BL3
                LD BC, #1BD5
.DecodeByte     LD A, R
                XOR (HL)
                LD (HL), A
                INC HL
                DEC BC
                LD A, B
                OR C
                JR NZ, .DecodeByte                                              ; переход, если остались незакодированные байты загрузочного блока
