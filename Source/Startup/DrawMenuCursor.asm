
; -----------------------------------------
; рисование курсора в новой позиции с выравниванием маски
; Вычисляет (старый x mod8)-(новый x mod8). Положительную разность компенсирует левым вращением
; образцов #7699, отрицательную правым #7674. Для восьми строк новой позиции #76C0 получает
; экранный адрес #73EF и трижды вызывает маскированный вывод #7416. Источник 24 байта #76C2, маска
; 24 байта #76DA.
; In:
;   #76BE — старые x, y, #76C0 — новые x, y
; Out:
;   курсор 8 строк, по 3 экранных байта в строке
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; Note:
;   экран, вращаемые образцы #76C2..#76F1, #770A
; -----------------------------------------
DrawMenuCursor  LD DE, (Startup.RotateCursorL.PixelPos)
                LD BC, (Startup.RotateCursorL.HitPos)
                LD A, C
                AND #07
                LD C, A
                LD A, E
                AND #07
                SUB C
                JR Z, .DrawCursor                                               ; переход, если вращение курсора уже совпало с координатой X

                JR C, .RotateRight                                              ; переход, если курсор требуется повернуть вправо

                CALL RotateCursorL                                              ; циклическое вращение 24-битных строк рисунка и маски курсора влево
                JR .DrawCursor

                ; выравнивание рисунка и маски курсора к новому битовому смещению
.RotateRight    NEG
                CALL RotateCursorR                                              ; циклическое вращение 24-битных строк рисунка и маски курсора вправо

                ; вывод восьми трёхбайтовых строк курсора в новой позиции
.DrawCursor     LD IX, Startup.BL3_cursor                                       ; 24байта пикселей начального курсора
                LD IY, Startup.BL3_cursorMask                                   ; 24байта маски начального курсора
                LD BC, (Startup.RotateCursorL.HitPos)
                LD A, #08
.CursorRow      PUSH AF
                CALL CursorByteAddr                                             ; адрес экранного пиксельного байта по координатам курсора
                CALL DrawCursorByte                                             ; маскированная запись одного байта курсора
                CALL DrawCursorByte                                             ; маскированная запись одного байта курсора
                CALL DrawCursorByte                                             ; маскированная запись одного байта курсора
                POP AF
                INC B
                DEC A
                JR NZ, .CursorRow                                               ; переход, если ещё не выведены все строки курсора

                RET
